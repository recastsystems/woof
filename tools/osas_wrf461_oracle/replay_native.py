#!/usr/bin/env python3
"""Replay an instrumented, live CU_OSAS call without changing its inputs.

The capture hook writes the read_run header and inputs to --capture, and
the matching eight output arrays to --native-output. Both use little-endian
Fortran stream records, with no record markers. The native random draw is
an input, not regenerated by this verifier.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import tempfile

import numpy as np


def replay(capture: Path, native_output: Path) -> dict:
    import cupy as cp
    from woof import wrf_exact
    from woof.core import column_cumulus_r8 as columns
    from woof.verify.osas_oracle import read_run

    if not wrf_exact.ENABLED:
        raise ValueError("live word replay requires GPUWM_WRF_EXACT=1")
    raw = capture.read_bytes() + native_output.read_bytes()
    # read_run also validates all record lengths and rejects trailing bytes.
    with tempfile.NamedTemporaryFile(dir=capture.parent, suffix=".replay") as stream:
        stream.write(raw)
        stream.flush()
        run = read_run(stream.name)
    fields = []
    for call in run.calls:
        inputs = {name: cp.asarray(call.inputs[name]) for name in
                  columns.LEVEL_INPUTS + columns.IFACE_INPUTS + ("xland",)}
        draw = cp.asarray(call.inputs["xkt2"])
        got = columns.run_columns(columns.COLUMN_CUMULUS_SCHEMES[95],
                                  inputs, draw, dt=call.dt,
                                  stepcu=call.stepcu, flags=1)
        for name, expected in call.outputs.items():
            actual = cp.asnumpy(got[name])
            different = int(np.count_nonzero(actual.view("u4") != expected.view("u4")))
            fields.append({"field": name, "words": int(expected.size),
                           "differing_words": different,
                           "native_nonzero_words": int(np.count_nonzero(expected)),
                           "native_sha256": hashlib.sha256(expected.tobytes()).hexdigest(),
                           "cuda_sha256": hashlib.sha256(actual.tobytes()).hexdigest()})
    return {"schema": "gpuwm-osas-live-native-replay-v1", "cu_physics": 95,
            "strict": True, "native_ql_backout": True,
            "shape": {"im": run.im, "jm": run.jm, "kx": run.kx},
            "calls": len(run.calls), "fields": fields,
            "words": sum(row["words"] for row in fields),
            "differing_words": sum(row["differing_words"] for row in fields),
            "capture_sha256": hashlib.sha256(capture.read_bytes()).hexdigest(),
            "native_output_sha256": hashlib.sha256(native_output.read_bytes()).hexdigest()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--capture", required=True, type=Path)
    parser.add_argument("--native-output", required=True, type=Path)
    parser.add_argument("--receipt", required=True, type=Path)
    args = parser.parse_args()
    receipt = replay(args.capture, args.native_output)
    args.receipt.write_text(json.dumps(receipt, indent=2) + "\n")
    print(f"live native words={receipt['words']} differing={receipt['differing_words']}")
    return int(receipt["differing_words"] != 0)


if __name__ == "__main__":
    raise SystemExit(main())
