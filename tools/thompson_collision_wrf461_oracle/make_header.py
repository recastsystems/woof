#!/usr/bin/env python3
"""Render exact native initialization words for the GPU collision quadrature."""
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'thompson_classic_constants'))
import make_header as native

def main(words, output):
    native.main(['make_header', words, output])
    path = Path(output)
    body = path.read_text().splitlines()[3:]
    path.write_text('// GENERATED by tools/thompson_collision_wrf461_oracle/make_header.py\n'
                    '// Native public-domain WRF v4.6.1 initialization; regenerate with build.sh.\n'
                    '// Source SHA256 fabf19e2a9073cff886e882b187080bfdf089d3fd40c0fce1d19bc93b1e5e802.\n'
                    + '\n'.join(body) + '\n')

if __name__ == '__main__':
    main(*sys.argv[1:])
