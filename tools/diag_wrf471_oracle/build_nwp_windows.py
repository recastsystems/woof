#!/usr/bin/env python3
"""Build native NWP expression references, keeping the WRF module unchanged."""
from __future__ import annotations
import argparse
import ctypes
import hashlib
import json
from pathlib import Path
import platform
import re
import subprocess

HERE = Path(__file__).resolve().parent


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output",type=Path,required=True)
    args = parser.parse_args()
    output = args.output.resolve()
    output.mkdir(parents=True,exist_ok=True)
    source = HERE/"upstream/module_diag_nwp.F"
    manifest = json.loads((HERE/"sources.json").read_text())
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    assert digest == next(r["sha256"] for r in manifest["sources"] if r["path"] == "phys/module_diag_nwp.F")
    registries = [HERE/"upstream"/name for name in
                  ("Registry/Registry.EM_COMMON", "Registry/registry.sbm")]
    for registry in registries:
        expected = next(r["sha256"] for r in manifest["sources"]
                        if r["path"] == str(registry.relative_to(HERE/"upstream")))
        if hashlib.sha256(registry.read_bytes()).hexdigest() != expected:
            raise ValueError(f"source hash mismatch: {registry}")
    rows = re.findall(r"^package\s+(\w+)\s+mp_physics==(\d+)",
                      "\n".join(p.read_text() for p in registries), re.M)
    needed = ("KESSLERSCHEME LINSCHEME SBU_YLINSCHEME WSM3SCHEME WSM5SCHEME WSM6SCHEME ETAMPNEW "
              "THOMPSON THOMPSONAERO THOMPSONGH MORR_TWO_MOMENT GSFCGCESCHEME WDM5SCHEME WDM6SCHEME "
              "MILBRANDT2MOM CAMMGMPSCHEME FULL_KHAIN_LYNN MORR_TM_AERO NSSL_2MOM FAST_KHAIN_LYNN_SHPUND").lower().split()
    values = dict(rows)
    constants = "module module_state_description\n"+"\n".join(
        f" integer,parameter :: {key}={values[key]}" for key in needed)+"\nend module\n"
    adapter = (HERE/"nwp_window_ref.f90").read_text()
    split = adapter.index("! Wrapper is compiled")
    deps,wrapper = output/"nwp_dependencies.f90",output/"nwp_wrapper.f90"
    deps.write_text(adapter[:split]+constants)
    wrapper.write_text(adapter[split:])
    command = ["gfortran","-cpp","-DNMM_CORE=0","-O0","-fPIC","-shared","-ffp-contract=off",
               "-fno-fast-math","-ffree-form","-ffree-line-length-none",str(deps),str(source),str(wrapper),
               str(HERE/"nwp_hail_ref.f90"),
               "-o",str(output/"nwp_window_ref.so")]
    subprocess.run(command,cwd=output,check=True)
    lib = ctypes.CDLL(str(output/"nwp_window_ref.so"))
    table = ctypes.c_double * 50
    diameter, width = table(), table()
    lib.nwp_hail_bins_ref(diameter, width)
    header = ("// Generated by the pinned native 50-bin grid expression.\n"
              "// WRF public-domain notice: tools/diag_wrf471_oracle/LICENSE-WRF.txt\n")
    for name, values in (("d", diameter), ("width", width)):
        header += f"__device__ __constant__ double nwp_hail_{name}[50] = {{\n"
        header += ",\n".join("    "+v.hex() for v in values)+"\n};\n"
    header_path = HERE.parent.parent/"woof/core/kernels/nwp_hail_bins.cuh"
    header_path.write_text(header)
    receipt = {"command":command,"source_sha256":digest,
               "registry_sha256":{p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in registries},
               "scope":"window and PSD hail module expressions; dependency stubs are not a full native WRF run",
               "compiler":subprocess.check_output(["gfortran","--version"],text=True),"libc":platform.libc_ver(),
               "adapter_sha256":hashlib.sha256(adapter.encode()).hexdigest(),
               "hail_adapter_sha256":hashlib.sha256((HERE/"nwp_hail_ref.f90").read_bytes()).hexdigest(),
               "hail_bins_sha256":hashlib.sha256(header.encode()).hexdigest(),
               "library_sha256":hashlib.sha256((output/"nwp_window_ref.so").read_bytes()).hexdigest()}
    (output/"nwp-build.json").write_text(json.dumps(receipt,indent=2)+"\n")
    print(output/"nwp-build.json")


if __name__ == "__main__":
    main()
