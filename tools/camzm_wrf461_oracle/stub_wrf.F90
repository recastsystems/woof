! Harness stand-ins for the pieces of the WRF framework that the CAM
! Zhang-McFarlane sources USE but that are not physics.  None of them
! carries a number the scheme computes with.
!
! * module_state_description is GENERATED by WRF's Registry tool.  The CAM
!   files read param_num_moist (only as the static dimension of
!   module_cam_support's pcnst parameter; every loop the scheme runs is
!   bounded by pcnst_runtime = 5, set by CAM_INIT) and param_first_scalar.
!   get_tpert (module_cu_camzm_driver.F:889-898) reads the scheme IDs below
!   to choose its arm; their values are the Registry.EM_COMMON package
!   selectors of WRF v4.6.1 (sf_sfclay_physics==1/2/3, sf_surface_physics
!   ==1/2/3, bl_pbl_physics==2/9).
! * module_wrf_error: the CAM files USE it for wrf_message/wrf_error_fatal,
!   which in WRF are external subroutines defined beside the module.
!   Messages are dropped; a fatal stops the oracle with a non-zero status so
!   no fixture is written after one.
module module_state_description
  implicit none
  integer, parameter :: param_num_moist = 16
  integer, parameter :: param_first_scalar = 2
  integer, parameter :: SFCLAYSCHEME = 1
  integer, parameter :: MYJSFCSCHEME = 2
  integer, parameter :: GFSSFCSCHEME = 3
  integer, parameter :: SLABSCHEME = 1
  integer, parameter :: LSMSCHEME = 2
  integer, parameter :: RUCLSMSCHEME = 3
  integer, parameter :: MYJPBLSCHEME = 2
  integer, parameter :: CAMUWPBLSCHEME = 9
end module module_state_description

module module_wrf_error
  implicit none
  character(len=256) :: wrf_err_message
end module module_wrf_error

subroutine wrf_message(str)
  implicit none
  character(len=*), intent(in) :: str
end subroutine wrf_message

subroutine wrf_debug(level, str)
  implicit none
  integer, intent(in) :: level
  character(len=*), intent(in) :: str
end subroutine wrf_debug

subroutine wrf_error_fatal(str)
  implicit none
  character(len=*), intent(in) :: str
  write(0, '(a,a)') 'WRF FATAL: ', trim(str)
  stop 99
end subroutine wrf_error_fatal
