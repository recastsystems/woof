#!/usr/bin/env python3
"""Assemble woof/core/kernels/ntu.cu from the hand-written runtime and
driver and the mechanical transcription of the (fixed) WRF module.

usage: assemble.py RT.cuh GEN.cuh DRIVER.cuh PRISTINE.F FIXES.patch OUT.cu
"""
import hashlib, sys

BANNER = """// ===========================================================================
// NTU multi-moment microphysics, WRF mp_physics = 56, for WOOF.
//
// Source: WRF v4.6.1 phys/module_mp_ntu.F (commit d66e442), public domain,
//   sha256 {src}
// with the declared divergences of tools/ntu_wrf461_oracle/apply_fixes.py
//   (fixes patch sha256 {fix}).
// Generated by tools/ntu_wrf461_oracle/f2cu.py (operation-order
// transcription) between the hand-written runtime and column drivers.
// Regenerate with tools/ntu_wrf461_oracle/build.sh; do not hand-edit the
// transcribed block.
// ===========================================================================
"""

def main(rt, gen, drv, src, fix, out):
    h = lambda p: hashlib.sha256(open(p, "rb").read()).hexdigest()
    parts = [BANNER.format(src=h(src), fix=h(fix)), open(rt).read(),
             "// ---- BEGIN transcription (f2cu.py) ----\n", open(gen).read(),
             "// ---- END transcription ----\n", open(drv).read()]
    open(out, "w", newline="\n").write("\n".join(parts))

if __name__ == "__main__":
    main(*sys.argv[1:7])
