PIN='d03fd43559e1562bde415eb7a50906b993c6da3f5dc3e501f957b48031629645'
spec=importlib.util.spec_from_file_location('deng_lake_parser',ROOT/'tools/lake_wrf461_oracle/translate.py')
lake=importlib.util.module_from_spec(spec);sys.modules[spec.name]=lake;spec.loader.exec_module(lake)


def statements():
    stack=[];active=True;carry=''
    for n,raw in enumerate(SOURCE.read_text().splitlines(),1):
        line=raw.strip()
        if line.startswith('#'):
            if line.startswith('#if'):
                take=line.startswith('#ifndef');stack.append((active,take));active=active and take
            elif line.startswith('#else'):
                parent,take=stack[-1];active=parent and not take
            elif line.startswith('#endif'):active,_=stack.pop()
            else:raise ValueError((n,line))
            continue
        if not active:continue
        line=line.split('!',1)[0].strip().lower()
        if not line:continue
        if not carry:start=n
        carry+=' '+line.lstrip('&').rstrip('&').strip()
        if not line.endswith('&'):
            if not carry.strip().startswith(('write','print')):
                for part in lake.split(carry.strip(),';'):yield start,part
            carry=''
    assert not carry and not stack


def declaration(line):
    if 'external' in line:return []
    m=re.match(r'(real|integer|logical)\s+(.+)',line)
    if m and '::' not in line:line=m[1]+' :: '+m[2]
    return lake.declaration(line)


def routines():
    module={};rows=[];current=None
    for n,line in statements():
        m=re.fullmatch(r'(?:(real)\s+)?(subroutine|function)\s+(\w+)\s*\((.*)\)',line)
        if m:
            current=dict(name=m[3],ret='float' if m[2]=='function' else 'void',args=lake.split(m[4]),vars={},body=[])
            rows.append(current);continue
        if line.startswith(('end subroutine','end function')) or line=='end':current=None;continue
        if line.startswith(('module ','end module','contains','use ','implicit ','character')):continue
        if line.startswith('dimension '):
            for item in lake.split(line[10:]):
                m=re.fullmatch(r'(\w+)\((.*)\)',item);assert m,line
                dest=current['vars'];name=m[1]
                if name not in dest:dest[name]=lake.Variable(name,'int' if name[0] in 'ijklmn' else 'float',[])
                dest[name].dims=lake.split(m[2])
            continue
        dec=declaration(line)
        if dec is not None:
            dest=module if current is None else current['vars']
            for v in dec:dest[v.name]=v
        elif current is not None:current['body'].append((n,line))
        else:raise ValueError((n,line))
    for r in rows:
        if r['name'] in ('minim','maxim'):
            for name in r['args']+['k','x','xar']:
                r['vars'].setdefault(name,lake.Variable(name,'int' if name[0] in 'ijklmn' else 'float',[]))
    return module,rows


def expr(source,symbols,slices=None):
    source=re.sub(r'\b(amax1|amin1|max0|min0)\(',lambda m:('max' if 'max' in m[1] else 'min')+'(',source)
    source=source.replace('wrf_dm_on_monitor()', '.false.')
    source=re.sub(r'(\.[a-z]+\.)',r' \1 ',source)
    source=re.sub(r'\bfloat\(','real(',source)
    parser=lake.Expression(source,symbols,slices)
    value=parser.parse()
    assert parser.i==len(parser.tokens),(source,parser.tokens[parser.i:])
    # These are the native REAL32 intrinsic conversions, including the
    # GAMMA statement function CONV. No arithmetic precision is promoted.
    value=re.sub(r'\bconv\(', 'deng_real(',value)
    value=re.sub(r'\baint\(', 'truncf(',value)
    return value


lake.expr=expr
_original_action=lake.action
def action(line,symbols,n):
    if line.startswith(('write','print','flush(')):return ''
    if line.startswith('call get_wrf_debug_level'):return 'dbg_level=0;'
    if line.startswith('goto '):return line+';'
    if line.startswith('stop '):return f'error={n}; return;'
    return _original_action(line,symbols,n)
lake.action=action


def generate():
    assert hashlib.sha256(SOURCE.read_bytes()).hexdigest()==PIN
    module,rows=routines()
    out=['// WRF 4.7.1 public-domain Deng module. Generated by tools/deng_wrf471/translate.py.',
         '// Source SHA256: '+hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
         'struct DengColumn {','DengArena arena; int error=0;',
         'DengArray<float> ttab,qstab,the0k,alu; float rdpr,rdthk,plutop;',
         'static constexpr float to=263.15f; static constexpr int kfnt=250,kfnp=220;']
    skip={'deng_shcu_init','kf_lutab','kf_lutabbg'}
    for r in rows:
        if r['name'] in skip:continue
        symbols=module|r['vars'];args=[]
        for name in r['args']:
            v=r['vars'][name]
            typ=f'DengArray<{v.typ}>' if v.dims else v.typ
            args.append(typ+(' ' if v.dims or v.intent=='in' else '& ')+name)
        out.append('__device__ '+r['ret']+' '+r['name']+'('+','.join(args)+') { DengFrame scope(arena);')
        for name,v in r['vars'].items():
            if name in r['args']:continue
            if v.dims:
                b=[expr(x,symbols) for d in v.dims for x in lake.bounds(d)]
                count='*'.join('('+expr(hi,symbols)+'-'+expr(lo,symbols)+'+1)' for lo,hi in map(lake.bounds,v.dims))
                out.append(f'DengArray<{v.typ}> {name}=arena.make<{v.typ}>({count},'+','.join(b)+');')
            else:
                init=expr(v.initial,symbols) if v.initial else '0'
                out.append(('const ' if v.const else '')+v.typ+' '+name+'='+init+';')
        labels=[]
        for n,line in r['body']:
            # All local declarations precede labels, preserving Fortran GOTO.
            label='';m=re.match(r'^(\d+)\s+(.*)',line)
            if m:
                label='deng_label_'+m[1]+':;';line=m[2]
                if labels and labels[-1]==m[1]:
                    labels.pop();out.append('}');continue
            if re.match(r'do\s+\d+\s+',line):
                m=re.match(r'do\s+(\d+)\s+(.*)',line);labels.append(m[1]);line='do '+m[2]
            named_end=re.fullmatch(r'end\s*do\s+(\w+)',line)
            line=re.sub(r'\bexit\s+(\w+)',r'goto deng_exit_\1',line)
            line=re.sub(r'\bcycle\s+(\w+)',r'goto deng_cycle_\1',line)
            if named_end:
                name=named_end[1];out.append(f'deng_cycle_{name}:; }} deng_exit_{name}:;');continue
            if line.startswith('format('):continue
            if line.startswith('data '):
                value=''
                for names,values in re.findall(r'([^/]+)/([^/]+)/',line[5:]):
                    names=lake.split(names.strip().lstrip(','));vals=lake.split(values)
                    if len(names)==1 and names[0] in symbols and symbols[names[0]].dims:
                        value+=''.join(f'{names[0]}({i+1})={expr(v,symbols)};' for i,v in enumerate(vals))
                    else:
                        assert len(names)==len(vals),(n,line)
                        value+=''.join(name+'='+expr(v,symbols)+';' for name,v in zip(names,vals))
            elif line=='conv(i) = real(i)':value=''
            elif line=='continue':value=';'
            else:
                line=re.sub(r'\bgo\s*to\s+(\d+)',r'goto deng_label_\1',line)
                if line.startswith('goto '):value=line+';'
                else:
                    try:value=lake.body_line(n,line,symbols,r['name'] if r['ret']!='void' else None)
                    except Exception as e:raise ValueError((r['name'],n,line)) from e
            # A bare Fortran RETURN after the result was returned is dead code,
            # and a valueless return in a non-void function is a hard error
            # for the HIP compiler (-Wreturn-mismatch); NVRTC only warned.
            if (r['ret']!='void' and not label and value=='return;'
                    and out[-1].rsplit('\n',1)[-1].split(':;')[-1].startswith('return ')):
                out.append('// WRF:'+str(n));continue
            out.append('// WRF:'+str(n)+'\n'+label+value)
        out.append('}')
    return '\n'.join(out+['};'])+'\n'


