"""Record layout shared by the SSiB column oracle and the GPU replay.

The lists live in :mod:`woof.core.ssib` (the kernel's own layout); this
shim re-exports them so the oracle tools read the same object.  ``layout.inc``
(the Fortran include the oracle driver reads its indices from) is GENERATED
from them by ``python3 layout.py --fortran``, so the Fortran reader, the
Python packer and the CUDA kernel cannot disagree about an offset.

Every value travels as a little-endian float32.  The integer-valued entries
(ivgtyp, mminlu, ra_sw, isnow) are small integers, exact in float32.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from woof.core.ssib import FORCING, MMINLU_CODES, SNOW_LAYER_VARS, STATE, STATIC  # noqa: E402

MMINLU = {code: name for name, code in MMINLU_CODES.items()}


def fortran_include() -> str:
    lines = ["! GENERATED by layout.py --fortran; do not edit."]
    for prefix, names in (("C", STATIC), ("F", FORCING), ("S", STATE)):
        for i, name in enumerate(names, start=1):
            lines.append(f"integer, parameter :: {prefix}_{name.upper()} = {i}")
        lines.append(f"integer, parameter :: N{prefix} = {len(names)}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    if sys.argv[1:] == ["--fortran"]:
        sys.stdout.write(fortran_include())
    else:
        raise SystemExit("usage: layout.py --fortran")
