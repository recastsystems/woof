#!/usr/bin/env python3
"""Reproduce NTU's level/column/level execution layout, without algebra changes.

Input is the exact licence-checked generate.py transcription embedded in ntu.cu.
The original remains the audit reference. Independent K loops execute with one
level per thread; only PTFLUX/FLFLUX retain native ordered column loops. Those
flux functions use strided references into persistent global stage storage.
"""
import argparse
import hashlib
from pathlib import Path
import re

from generate import EXPECTED

ROOT = Path(__file__).resolve().parents[2]


def function(source, name):
    pattern = rf'NTU_DEV(?:_BIG)? void {name}\([^\n]+\) \{{'
    match = re.search(pattern, source)
    if match is None:
        raise ValueError(name)
    start = match.start()
    at = match.end()
    depth = 1
    while depth:
        depth += (source[at] == '{') - (source[at] == '}')
        at += 1
    return source[start:at]


def generate():
    source = (ROOT/'woof/core/kernels/ntu.cu').read_text()
    original = source.split('// ---- BEGIN transcription (f2cu.py) ----\n')[1].split('// ---- END transcription ----')[0]
    # The source file includes a separating newline outside the generated file.
    if hashlib.sha256(original.rstrip('\n').encode()+b'\n').hexdigest() != EXPECTED:
        raise ValueError('native transcription digest changed')
    micro = function(original, 'ntu_ntu_micro')
    body = micro[micro.index('{')+1:-1]
    decl_end = body.index('    { const int ntu_hi_k = KTE;')
    flux_start = body.index('    ntu_ptflux(')
    post_start = body.index('    { const int ntu_hi_k = KTE;', flux_start)
    declarations, pre, flux, post = (body[:decl_end], body[decl_end:flux_start],
                                    body[flux_start:post_start], body[post_start:])
    arrays = ['QC','QR','QI','QS','QG','QH','NC','NR','NI','NS','NG','NH',
              'VI','VS','VG','FI','FS','AI','AS','AG','AH','I3M',
              'QDCN','QTCN','QCCN','QRCN','QNIN']
    vt = ['VT_'+name for name in arrays[:21]]+['VTI3M']
    assert len(vt)==22
    work = ['TAIR','PRES','RHO']+vt+['VTMEAN0','VTMEAN1','VTMEAN2']
    out = ['// Generated by tools/ntu_wrf471_oracle/parallelize.py.\n'
           '// Public-domain WRF v4.7.1; see ntu.cu for pin and licence.\n'
           f'// Native transcription SHA256 {EXPECTED}\n'
           '// Arithmetic statements and ordered sedimentation are retained.\n'
           f'#define NTU_WORK_VOLUMES {len(work)}\n'
           'struct NtuStride {\n'
           '    float* ptr; long long stride;\n'
           '    __device__ __forceinline__ float& operator[](int k) const { return ptr[k*stride]; }\n'
           '};\n']
    for name in ('ntu_ptflux','ntu_flflux'):
        fn = function(original,name).replace(name+'(',name+'_strided(',1)
        for param in ('Q1D','VT1D','RHO','DZ'):
            fn = fn.replace('float* '+param,'NtuStride '+param,1)
        out.append(fn+'\n')
    def local_inputs(post_stage):
        text = ('    const size_t at = (size_t)blockIdx.x*blockDim.x + threadIdx.x;\n'
                '    const size_t count = ncol*(size_t)nz;\n'
                '    if (at >= count) return;\n'
                '    const int KTS=1, KTE=1;\n'
                '    float DT=dt, DTMN=dt/60.0f;\n')
        text += '    float TK3D[1] = {'+('work[at]' if post_stage else 'f3[NTU_F_TH][at]*f3[NTU_F_PII][at]')+'};\n'
        for var,expr in [('QV','f3[NTU_F_QV][at]'),('DZ','f3[NTU_F_DZ][at]'),('P','f3[NTU_F_P][at]'),('S','0.0f'),('W','0.5f*(f3[NTU_F_W][at]+f3[NTU_F_W][at+ncol])')]:
            text += f'    float {var}3D[1] = {{{expr}}};\n'
        for name in arrays:
            expr = f'f3[NTU_F_{name}][at]'
            if not post_stage and name.startswith('Q') and name.endswith(('CN','IN')):
                expr = f'ntu_fmax(NTU_RLIMIT, {expr})'
            text += f'    float {name}3D[1] = {{{expr}}};\n'
        return text
    signature='(NtuAeroConst* AC, float* const* f3, float* work, size_t ncol, int nz, float dt) {\n'
    out.append('extern "C" __global__ void ntu_level_pre_kernel'+signature)
    out.append(local_inputs(False)+declarations.replace('NTU_KMAX','1')+pre.replace('NTU_KMAX','1'))
    for name in arrays[:22]:
        out.append(f'    f3[NTU_F_{name}][at] = {name}3D[0];\n')
    out.append('    f3[NTU_F_QV][at] = QVAP[0];\n')
    for i,name in enumerate(arrays[22:]):
        out.append(f'    f3[NTU_F_{name}][at] = AERO[{i}];\n')
    for i,name in enumerate(work):
        expr = f'VTMEAN[{int(name[-1])}]' if name.startswith('VTMEAN') else name+'[0]'
        out.append(f'    work[{i}*count+at] = {expr};\n')
    out.append('}\n')
    out.append('extern "C" __global__ void ntu_column_flux_kernel(float* const* f3, float* const* f2, float* work, size_t ncol, int nz, float DT) {\n'
               '    const size_t c = (size_t)blockIdx.x*blockDim.x+threadIdx.x;\n'
               '    if (c>=ncol) return;\n'
               '    const size_t count = ncol*(size_t)nz, top=(nz-1)*ncol+c;\n'
               '    const long long stride=-(long long)ncol;\n'
               '    const int KTS=1, KTE=nz;\n'
               '    int IV0=0, IV=0;\n'
               '    float DTMN=DT/60.0f;\n'
               '    float CLODNCV=0, ICENCV=0, VINCV=0, VSNCV=0, VGNCV=0, FINCV=0, FSNCV=0, AINCV=0, ASNCV=0, AGNCV=0, AHNCV=0, I3MNCV=0;\n')
    for name in ('RAINNC','RAINNCV','SNOWNC','SNOWNCV','GRAPNC','GRAPNCV','HAILNC','HAILNCV','SR'):
        out.append(f'    float& {name}=f2[NTU_S_{name}][c];\n')
    out.append('    RAINNCV=0; SNOWNCV=0; GRAPNCV=0; HAILNCV=0; SR=0;\n')
    for name in arrays:
        out.append(f'    NtuStride {name}3D={{f3[NTU_F_{name}]+top,stride}};\n')
    out.append('    NtuStride DZ3D={f3[NTU_F_DZ]+top,stride};\n')
    for i,name in enumerate(work):
        out.append(f'    NtuStride {name}={{work+{i}*count+top,stride}};\n')
    out.append('    NtuStride AERO[5]={QDCN3D,QTCN3D,QCCN3D,QRCN3D,QNIN3D};\n'
               '    NtuStride VTMEAN[3]={VTMEAN0,VTMEAN1,VTMEAN2};\n')
    # Replace pointer-to-first-element expressions with the corresponding
    # strided view. These regexes consume only addressing, never arithmetic.
    flux = re.sub(r'&AERO\[\(\(1\) - \(KTS\)\) \+ NTU_KMAX \* \(\(\((IV0 \+ [34])\)\) - \(1\)\)\]',r'AERO[(\1)-1]',flux)
    flux = re.sub(r'&VTMEAN\[\(\(1\) - \(KTS\)\) \+ NTU_KMAX \* \(\(([123])\) - \(1\)\)\]',lambda m:f'VTMEAN[{int(m[1])-1}]',flux)
    flux = re.sub(r'&([A-Z0-9_]+)\[\(1\) - \(KTS\)\]',r'\1',flux)
    if '&' in flux or 'NTU_KMAX' in flux:
        raise ValueError('untranslated flux addressing: '+flux)
    out.append(flux.replace('ntu_ptflux(','ntu_ptflux_strided(').replace('ntu_flflux(','ntu_flflux_strided(')+'}\n')
    out.append('extern "C" __global__ void ntu_level_post_kernel'+signature)
    out.append(local_inputs(True)+declarations.replace('NTU_KMAX','1'))
    for name in ('TAIR','PRES','RHO'):
        out.append(f'    {name}[0] = work[{work.index(name)}*count+at];\n')
    out.append('    QVAP[0] = QV3D[0];\n')
    for i,name in enumerate(arrays[22:]):
        out.append(f'    AERO[{i}] = {name}3D[0];\n')
    out.append(post.replace('NTU_KMAX','1'))
    out.append('    f3[NTU_F_TH][at] = TK3D[0]/f3[NTU_F_PII][at];\n'
               '    f3[NTU_F_QV][at] = ntu_fmax(0.0f,QV3D[0]);\n')
    for name in arrays:
        out.append(f'    f3[NTU_F_{name}][at] = ntu_fmax(0.0f,{name}3D[0]);\n')
    out.append('}\n')
    return '\n'.join(out)


if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--out',type=Path,default=ROOT/'woof/core/kernels/ntu_parallel.cuh')
    args=ap.parse_args()
    args.out.write_text(generate())
    print(hashlib.sha256(args.out.read_bytes()).hexdigest())
