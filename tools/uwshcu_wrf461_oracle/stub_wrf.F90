! Harness stand-ins for the pieces of the WRF framework the UW shallow
! cumulus sources USE that carry no number the scheme computes with.
!
! * module_state_description is GENERATED by WRF's Registry tool.  The
!   scheme reads param_num_moist (only the static dimension of
!   module_cam_support's pcnst; every loop runs to pcnst_runtime = 5),
!   param_first_scalar, the P_Q* species indices (which the driver only
!   compares with param_first_scalar to decide which tendencies exist),
!   and the three PBL selector values init_uwshcu accepts.  The species
!   indices are run-time variables in WRF too
!   (set_scalar_indices_from_config); the harness sets them from the case
!   file so both arms of the driver's p_qnc/p_qni tests are graded.
! * modal_aero_data is USEd by compute_uwshcu under #define MODAL_AERO for
!   its tracer-positivity loop over constituents m = 4..ncnst that are not
!   NUMLIQ/NUMICE.  With WRF's five CAM constituents (CAM_INIT, no
!   chemistry, no CAMMGMP) m = 4 and 5 ARE NUMLIQ and NUMICE, so the loop
!   body never runs and ntot_amode/numptr_amode are never read; the real
!   module drags in radconstants and the MAM tables, which this scheme
!   does not consume.
! * module_wrf_error and the three external messaging routines: messages
!   are dropped; a fatal stops the oracle with status 99 so no fixture is
!   written after one.
module module_state_description
  implicit none
  integer, parameter :: param_num_moist = 16
  integer, parameter :: param_first_scalar = 2
  integer, parameter :: CAMUWPBLSCHEME = 9
  integer, parameter :: MYJPBLSCHEME = 2
  integer, parameter :: MYNNPBLSCHEME = 5
  integer :: p_qc = 2, p_qr = 3, p_qi = 4, p_qs = 5, p_qg = 6
  integer :: p_qnc = 1, p_qni = 1
end module module_state_description

module module_wrf_error
  implicit none
  character(len=256) :: wrf_err_message
end module module_wrf_error

module modal_aero_data
  implicit none
  integer, parameter :: ntot_amode = 3
  integer :: numptr_amode(ntot_amode) = (/ -1, -1, -1 /)
end module modal_aero_data

subroutine wrf_message(str)
  implicit none
  character(len=*), intent(in) :: str
end subroutine wrf_message

subroutine wrf_debug(level, str)
  implicit none
  integer, intent(in) :: level
  character(len=*), intent(in) :: str
end subroutine wrf_debug

subroutine wrf_error_fatal(str)
  implicit none
  character(len=*), intent(in) :: str
  write(0, '(a,a)') 'WRF FATAL: ', trim(str)
  stop 99
end subroutine wrf_error_fatal
