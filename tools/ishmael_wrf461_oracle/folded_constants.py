"""Constants gfortran folds at compile time in module_mp_jensen_ishmael.F.

gfortran's front end simplifies an intrinsic or a power whose operands are
constants (MPFR, rounded once to binary32), and GCC's -O2 middle end folds a
math builtin whose argument constant-propagates (MPFR again).  The device
must use those correctly rounded words, not recompute them with a runtime
libm call, so this script derives each one exactly (mpmath at 200 bits,
rounded to nearest-even binary32) and writes woof/core/kernels/
ishmael_folded.cuh.

It also reports, for each folded call, whether the runtime float32 word
the WRF build would use WITHOUT folding equals the folded one; where they
agree the folding question cannot move a result.

Needs mpmath (the oracle box's system python has it).  Development tool;
the engine never imports it.
"""

from __future__ import annotations

import argparse
import ctypes
import ctypes.util
import struct
from pathlib import Path

import mpmath

mpmath.mp.prec = 200


def f32(x) -> float:
    """Round a real (mpf or float or str) to nearest-even binary32."""
    v = mpmath.mpf(x)
    if v == 0:
        return 0.0
    # binary32 has 24-bit significands and every constant here is normal,
    # so rounding to nearest at 24 bits is rounding to binary32.
    with mpmath.workprec(24):
        r = +v
    out = struct.unpack("<f", struct.pack("<f", float(r)))[0]
    if mpmath.mpf(out) != r:
        raise ValueError(f"{x} does not round-trip at 24 bits")
    return out


def hexf(x: float) -> str:
    bits = struct.unpack("<I", struct.pack("<f", x))[0]
    return f"__int_as_float(0x{bits:08x})"


def lit(s: str) -> float:
    """A Fortran default-REAL literal: decimal rounded to binary32."""
    return f32(mpmath.mpf(s))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("out", type=Path)
    args = ap.parse_args()

    libm = ctypes.CDLL(ctypes.util.find_library("m"))
    for name in ("logf", "expf"):
        getattr(libm, name).restype = ctypes.c_float
        getattr(libm, name).argtypes = [ctypes.c_float]
    libm.powf.restype = ctypes.c_float
    libm.powf.argtypes = [ctypes.c_float, ctypes.c_float]

    ao = lit("0.1e-6")
    one = 1.0
    entries = {}
    report = []

    def fold(name, exact, runtime=None, note=""):
        word = f32(exact)
        entries[name] = (word, note)
        if runtime is not None:
            report.append((name, word, runtime, word == runtime))

    fold("ISH_LOG_AO", mpmath.log(ao), libm.logf(ao),
         "log(ao), ao a PARAMETER: front-end folded")
    e045 = f32(mpmath.mpf(one) - mpmath.mpf(lit("0.55")))
    em03 = f32(mpmath.mpf(one) - mpmath.mpf(lit("1.3")))
    fold("ISH_AO_POW_045", mpmath.power(ao, e045), libm.powf(ao, e045),
         "ao**(1.-dsdum) after dsdum=0.55 (:2981-2982)")
    fold("ISH_AO_POW_M03", mpmath.power(ao, em03), libm.powf(ao, em03),
         "ao**(1.-dsdum) after dsdum=1.3 (:2986-2987)")
    for name, s in (("ISH_CUBE_2EM6", "2.e-6"), ("ISH_CUBE_5EM6", "5.e-6"),
                    ("ISH_CUBE_25EM6", "25.E-6"), ("ISH_VMIN", "10.e-6")):
        v = lit(s)
        fold(name, mpmath.mpf(v) ** 3, None, f"({s})**3: front-end folded")
    lrsig = lit("1.3")
    sig = f32(mpmath.log(lrsig))
    entries["ISH_SIG"] = (sig, "log(lrsig), lrsig=1.3: -O2 folded (:2400-2401)")
    report.append(("ISH_SIG", sig, libm.logf(lrsig), sig == libm.logf(lrsig)))
    sig2 = struct.unpack("<f", struct.pack("<f", sig * sig))[0]
    a45 = struct.unpack("<f", struct.pack("<f", 4.5 * sig2))[0]
    half = struct.unpack("<f", struct.pack("<f", sig2 / 2.0))[0]
    fold("ISH_EXP_45SIG2", mpmath.exp(a45), libm.expf(a45),
         "exp(4.5*(sig**2)): -O2 folded (:2406)")
    fold("ISH_EXP_SIG2_HALF", mpmath.exp(half), libm.expf(half),
         "EXP((sig**2)/2.): -O2 folded (:2411)")
    for name, s in (("ISH_LOG_1EM6", "1.e-6"), ("ISH_LOG_1EM2", "1.e-2")):
        v = lit(s)
        fold(name, mpmath.log(v), libm.logf(v),
             f"log({s}) of aggregation's tablo/tabhi (:3932-3933)")

    lines = [
        "// gpuwm/core/kernels/ishmael_folded.cuh -- GENERATED by",
        "// tools/ishmael_wrf461_oracle/folded_constants.py; do not edit.",
        "// Words gfortran evaluates at compile time (MPFR, correctly",
        "// rounded) in WRF v4.6.1 module_mp_jensen_ishmael.F, so the device",
        "// must not recompute them with a runtime libm call.",
    ]
    for name, (word, note) in entries.items():
        lines.append(f"#define {name} {hexf(word)}   /* {word!r}: {note} */")
    args.out.write_text("\n".join(lines) + "\n", encoding="ascii")
    for name, word, rt, same in report:
        print(f"{name:20s} folded {word!r:>24} runtime {rt!r:>24} "
              f"{'same' if same else 'DIFFERENT'}")


if __name__ == "__main__":
    main()
