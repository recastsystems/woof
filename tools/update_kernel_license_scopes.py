def arm_files(root: Path) -> list[str]:
    kernels = root / "woof/core/kernels"
    return sorted(p.relative_to(kernels).as_posix()
                  for pattern in ("*.cu", "*.cuh") for p in kernels.rglob(pattern)
                  if ARM_TABLE.search(p.read_text(encoding="utf-8")))


def _between(text: str, start: str, end: str, replacement: str) -> str:
    first = text.index(start)
    last = text.index(end, first)
    return text[:first] + textwrap.fill(replacement, width=78) + "\n\n" + text[last:]


def generated_notices(root: Path) -> dict[Path, str]:
    arm = arm_files(root)
    kernels = root / "woof/core/kernels"
    missing = [name for name in FDLIBM_FILES if not (kernels / name).is_file()]
    if missing:
        raise ValueError(f"FDLIBM audited carriers are missing: {missing}")
    fdlibm = sorted(FDLIBM_FILES)
    kernel_path = kernels / "LICENSE-third-party.txt"
    notice_path = root / "NOTICE"
    kernel = kernel_path.read_text(encoding="utf-8")
    notice = notice_path.read_text(encoding="utf-8")
    kernel = _between(kernel, "Scope in this directory:", "wrf_vi_pressure_log helper",
        "Scope in this directory: generated by tools/update_kernel_license_scopes.py. "
        f"Arm table carriers ({len(arm)} files): {', '.join(arm)}. "
        f"FDLIBM audited carriers ({len(fdlibm)} files): {', '.join(fdlibm)}.")
    kernel = kernel.replace("\n\nwrf_vi_pressure_log helper", "\n\nThe wrf_vi_pressure_log helper")
    # Remove the former duplicate FDLIBM enumeration while retaining provenance.
    if "The expm1f / tanhf / atanf /" in kernel:
        first = kernel.index("The expm1f / tanhf / atanf /")
        last = kernel.index("The binary64 log10", first)
        kernel = kernel[:first] + kernel[last:]
    notice = _between(notice, "transcriptions appear", "vert_interp.cu's wrf_vi_pressure_log",
        "transcriptions appear under woof/core/kernels/ in "
        f"{len(arm)} files: {', '.join(arm)}. "
        "The scope is generated by tools/update_kernel_license_scopes.py from the "
        "coefficient tables. The Python log/exp/pow copy in "
        "woof/core/noahmp_libm.py is separate.")
    notice = notice.replace("This adds one trig header to the seventeen log/exp/pow kernel files above;\n"
                            "the Python log/exp/pow copy remains separate.",
                            "The generated scope above includes this trig header.")
    notice = _between(notice, "Sun's code. They appear", "woof/core/ruc.py. thompson_aerosol_libm.cuh",
        "Sun's code. They appear under woof/core/kernels/ in "
        f"{len(fdlibm)} audited files: {', '.join(fdlibm)}. "
        "The scope is generated by tools/update_kernel_license_scopes.py. "
        "The Python copies are woof/core/noahmp_libm.py, woof/core/mynn_pbl.py and")
    notice = notice.replace("woof/core/mynn_pbl.py and\n\nwoof/core/ruc.py.",
                            "woof/core/mynn_pbl.py and\nwoof/core/ruc.py.")
    notice = _between(notice, "below is unchanged and still required by", "(log10_flt32.cuh joined",
        "below is unchanged and still required by the carriers listed above.")
    return {notice_path: notice, kernel_path: kernel}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    stale = []
    for path, text in generated_notices(ROOT).items():
        if path.read_text(encoding="utf-8") != text:
            stale.append(path.relative_to(ROOT).as_posix())
            if not args.check:
                path.write_text(text, encoding="utf-8", newline="\n")
    print(("DRIFT: " if args.check else "Updated: ") + ", ".join(stale))
    return int(args.check and bool(stale))


if __name__ == "__main__":
    raise SystemExit(main())
