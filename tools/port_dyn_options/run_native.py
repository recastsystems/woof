"""Run whole strict WRF cases and keep the native capture inputs/outputs."""
from pathlib import Path
import os
import re
import subprocess
import json
import time
import sys
import shutil

root = Path('/workspace/runs/port-dyn-options')
native = root / 'native'
base = Path('/workspace/data/release-r6/ensemble-test-data/wrf-real')
cases = [('baseline', {})]
for key, values in {
    'v_mom_adv_order': (2,4,6), 'v_sca_adv_order': (2,4,6),
    'h_mom_adv_order': (0,2,3,4,6), 'h_sca_adv_order': (0,2,3,4,6),
    'rk_ord': (2,), 'momentum_adv_opt': (3,), 'm_opt': (1,),
}.items():
    cases += [(f'{key}-{v}', {key:v}) for v in values]
records = []
if len(sys.argv) > 1:
    requested = set(sys.argv[1:])
    cases = [(name, settings) for name, settings in cases if name in requested]
    if {name for name, _ in cases} != requested:
        raise SystemExit('unknown case name')
for name, settings in cases:
    out = root / os.getenv('WOOF_NATIVE_CASES', 'native-cases') / name
    out.mkdir(parents=True, exist_ok=True)
    capture = out / 'capture'
    capture.mkdir(exist_ok=True)
    for path in (native / 'run').iterdir():
        dest = out / path.name
        if path.is_file() and path.name != 'namelist.input' and not dest.exists():
            dest.symlink_to(path.resolve())
    for key in ('wrfinput_d01','wrfbdy_d01'):
        dest = out / key
        if not dest.exists(): dest.symlink_to(base / key)
    # Reuse the completed native lookup tables. The qr_acr_qg table was
    # also regenerated by this strict build and its SHA-256 matched.
    for table in Path('/workspace/runs/rel-30-nest/tables').glob('qr*.dat'):
        shutil.copyfile(table, out / table.name)
    text = (base/'namelist.input').read_text()
    defaults = dict(run_days=0,run_hours=0,run_minutes=1,run_seconds=0,
                    history_interval=1,nproc_x=4,nproc_y=2)
    defaults.update(settings)
    if name == "h_sca_adv_order-0":
        defaults.update(moist_adv_opt=0, scalar_adv_opt=0)
    for key, value in defaults.items():
        pattern = rf'(?im)^\s*{key}\s*=.*$'
        if re.search(pattern,text):
            text = re.sub(pattern,f' {key} = {value},',text)
        else:
            section = 'time_control' if key.startswith('run_') or key=='history_interval' else 'domains' if key.startswith('nproc_') else 'dynamics'
            text = text.replace('&'+section,'&'+section+f'\n {key} = {value},')
    (out/'namelist.input').write_text(text)
    env = dict(os.environ, WOOF_DYN_CAPTURE=str(capture), WOOF_STRESS_CAPTURE=str(capture), OMP_NUM_THREADS='1',
               OPENBLAS_NUM_THREADS='1', MKL_NUM_THREADS='1')
    command = ['mpirun','--allow-run-as-root','--bind-to','none','-np','8',str(native/'main/wrf.exe')]
    began = time.time()
    with (out/'run.log').open('w') as log:
        result = subprocess.run(command,cwd=out,env=env,stdout=log,stderr=subprocess.STDOUT)
    row = dict(name=name,settings=settings,command=command,returncode=result.returncode,
               elapsed=time.time()-began,captures=len(list(capture.glob('*.bin'))))
    records.append(row)
    (out/'receipt.json').write_text(json.dumps(row,indent=2)+'\n')
    (root/'native-cases/receipt.json').write_text(json.dumps(records,indent=2)+'\n')
    print(json.dumps(row),flush=True)
