				    ts_dim2) * ts_dim1] * rxa[i__ + (j + (k +
				    1 + (im + (is << 1)) * rxa_dim3) *
				    rxa_dim2) * rxa_dim1] * denm;
			}
		    }
		}
		i__1 = *np + 1;
		for (k = 2; k <= i__1; ++k) {
		    i__2 = *n;
		    for (j = 1; j <= i__2; ++j) {
			i__3 = *m;
			for (i__ = 1; i__ <= i__3; ++i__) {
			    denm = 1.f / (1.f - rxa[i__ + (j + (k + (im + (is
				    << 1)) * rxa_dim3) * rxa_dim2) * rxa_dim1]
				     * rsa[i__ + (j + (k - 1 + (ih + (im << 1)
				    ) * rsa_dim3) * rsa_dim2) * rsa_dim1]);
			    fdndir[i__ + j * fdndir_dim1] = tda[i__ + (j + (k
				    - 1 + (ih + (im << 1)) * tda_dim3) *
				    tda_dim2) * tda_dim1];
			    xx = tda[i__ + (j + (k - 1 + (ih + (im << 1)) *
				    tda_dim3) * tda_dim2) * tda_dim1] * rra[
				    i__ + (j + (k + (im + (is << 1)) *
				    rra_dim3) * rra_dim2) * rra_dim1];
			    fdndif[i__ + j * fdndif_dim1] = (xx * rsa[i__ + (
				    j + (k - 1 + (ih + (im << 1)) * rsa_dim3)
				    * rsa_dim2) * rsa_dim1] + tta[i__ + (j + (
				    k - 1 + (ih + (im << 1)) * tta_dim3) *
				    tta_dim2) * tta_dim1]) * denm;
			    fupdif = (xx + tta[i__ + (j + (k - 1 + (ih + (im
				    << 1)) * tta_dim3) * tta_dim2) * tta_dim1]
				     * rxa[i__ + (j + (k + (im + (is << 1)) *
				    rxa_dim3) * rxa_dim2) * rxa_dim1]) * denm;
			    flxdn[i__ + (j + k * flxdn_dim2) * flxdn_dim1] =
				    fdndir[i__ + j * fdndir_dim1] + fdndif[
				    i__ + j * fdndif_dim1] - fupdif;
			    flxdnu[i__ + (j + k * flxdnu_dim2) * flxdnu_dim1]
				    = -fupdif;
			    flxdnd[i__ + (j + k * flxdnd_dim2) * flxdnd_dim1]
				    = fdndir[i__ + j * fdndir_dim1] + fdndif[
				    i__ + j * fdndif_dim1];
			}
		    }
		}
		i__1 = *n;
		for (j = 1; j <= i__1; ++j) {
		    i__2 = *m;
		    for (i__ = 1; i__ <= i__2; ++i__) {
			flxdn[i__ + (j + flxdn_dim2) * flxdn_dim1] = 1.f -
				rra[i__ + (j + ((im + (is << 1)) * rra_dim3 +
				1) * rra_dim2) * rra_dim1];
			flxdnu[i__ + (j + flxdnu_dim2) * flxdnu_dim1] = -rra[
				i__ + (j + ((im + (is << 1)) * rra_dim3 + 1) *
				 rra_dim2) * rra_dim1];
			flxdnd[i__ + (j + flxdnd_dim2) * flxdnd_dim1] = 1.f;
		    }
		}
		i__1 = *np + 1;
		for (k = 1; k <= i__1; ++k) {
		    i__2 = *n;
		    for (j = 1; j <= i__2; ++j) {
			i__3 = *m;
			for (i__ = 1; i__ <= i__3; ++i__) {
			    if (ih == 1 && im == 1 && is == 1) {
				fclr[i__ + (j + k * fclr_dim2) * fclr_dim1] =
					flxdn[i__ + (j + k * flxdn_dim2) *
					flxdn_dim1];
			    }
			    fall[i__ + (j + k * fall_dim2) * fall_dim1] +=
				    flxdn[i__ + (j + k * flxdn_dim2) *
				    flxdn_dim1] * ct[i__ + j * ct_dim1];
			    fallu[i__ + (j + k * fallu_dim2) * fallu_dim1] +=
				    flxdnu[i__ + (j + k * flxdnu_dim2) *
				    flxdnu_dim1] * ct[i__ + j * ct_dim1];
			    falld[i__ + (j + k * falld_dim2) * falld_dim1] +=
				    flxdnd[i__ + (j + k * flxdnd_dim2) *
				    flxdnd_dim1] * ct[i__ + j * ct_dim1];
			}
		    }
		}
		i__1 = *n;
		for (j = 1; j <= i__1; ++j) {
		    i__2 = *m;
		    for (i__ = 1; i__ <= i__2; ++i__) {
			fsdir[i__ + j * fsdir_dim1] += fdndir[i__ + j *
				fdndir_dim1] * ct[i__ + j * ct_dim1];
			fsdif[i__ + j * fsdif_dim1] += fdndif[i__ + j *
				fdndif_dim1] * ct[i__ + j * ct_dim1];
		    }
		}

	    }
	}
    }
    return 0;
}

 __device__ int flxco2_(real *workspace, const real *tables, gsfc_ptr<integer> m, gsfc_ptr<integer> n, gsfc_ptr<integer> np, gsfc_ptr<real> swc, gsfc_ptr<real> swh, gsfc_ptr<real> csm, gsfc_ptr<real> df) {



    gsfc_ptr<real> cah = (gsfc_ptr<real> )(tables + 2056);


    integer csm_dim1, csm_offset, swc_dim1, swc_dim2, swc_offset, swh_dim1,
	    swh_dim2, swh_offset, df_dim1, df_dim2, df_offset, i__1, i__2,
	    i__3;
    real r__1;


    integer i__, j, k;
    real x1, x2, y2, dc;
    integer ic;
    real dw;
    integer iw;
    real xx, clog, wlog;


    csm_dim1 = *m;
    csm_offset = 1 + csm_dim1;
    csm -= csm_offset;
    df_dim1 = *m;
    df_dim2 = *n;
    df_offset = 1 + df_dim1 * (1 + df_dim2);
    df -= df_offset;
    swh_dim1 = *m;
    swh_dim2 = *n;
    swh_offset = 1 + swh_dim1 * (1 + swh_dim2);
    swh -= swh_offset;
    swc_dim1 = *m;
    swc_dim2 = *n;
    swc_offset = 1 + swc_dim1 * (1 + swc_dim2);
    swc -= swc_offset;


    i__1 = *np + 1;
    for (k = 2; k <= i__1; ++k) {
	i__2 = *n;
	for (j = 1; j <= i__2; ++j) {
	    i__3 = *m;
	    for (i__ = 1; i__ <= i__3; ++i__) {
		xx = 3.3333333333333335f;
		r__1 = swc[i__ + (j + k * swc_dim2) * swc_dim1] * csm[i__ + j
			* csm_dim1];
		clog = (real)r_lg10(&r__1);
		r__1 = swh[i__ + (j + k * swh_dim2) * swh_dim1] * csm[i__ + j
			* csm_dim1];
		wlog = (real)r_lg10(&r__1);
		ic = (integer) ((clog + 3.15f) * xx + 1.f);
		iw = (integer) ((wlog + 4.15f) * xx + 1.f);
		if (ic < 2) {
		    ic = 2;
		}
		if (iw < 2) {
		    iw = 2;
		}
		if (ic > 22) {
		    ic = 22;
		}
		if (iw > 19) {
		    iw = 19;
		}
		dc = clog - (real) (ic - 2) * .3f + 3.f;
		dw = wlog - (real) (iw - 2) * .3f + 4.f;
		x1 = cah[(iw - 1) * 22 - 22] + (cah[iw * 22 - 22] - cah[(iw -
			1) * 22 - 22]) * xx * dw;
		x2 = cah[ic - 1 + (iw - 1) * 22 - 23] + (cah[ic - 1 + iw * 22
			- 23] - cah[ic - 1 + (iw - 1) * 22 - 23]) * xx * dw;
		y2 = x2 + (cah[ic + (iw - 1) * 22 - 23] - cah[ic - 1 + (iw -
			1) * 22 - 23]) * xx * dc;
		if (x1 < y2) {
		    x1 = y2;
		}
		df[i__ + (j + k * df_dim2) * df_dim1] += (x1 - y2) * .0343f;
	    }
	}
    }
    return 0;
}

 __device__ int o3prof_(real *workspace, const real *tables, gsfc_ptr<integer> np, gsfc_ptr<real> pres, gsfc_ptr<real> ozone, gsfc_ptr<integer>
	its, gsfc_ptr<integer> ite, gsfc_ptr<integer> kts, gsfc_ptr<integer> kte, gsfc_ptr<real> p, gsfc_ptr<real> o3) {


    integer p_dim1, p_offset, o3_dim1, o3_offset, i__1, i__2;


    integer i__, k, kk, ko;


    --ozone;
    --pres;
    o3_dim1 = *ite - *its + 1;
    o3_offset = *its + o3_dim1 * *kts;
    o3 -= o3_offset;
    p_dim1 = *ite - *its + 1;
    p_offset = *its + p_dim1 * *kts;
    p -= p_offset;


    i__1 = *np;
    for (k = 1; k <= i__1; ++k) {
	pres[k] = (real)gfk_log(pres[k]);
    }
    i__1 = *kte;
    for (k = *kts; k <= i__1; ++k) {
	i__2 = *ite;
	for (i__ = *its; i__ <= i__2; ++i__) {
	    p[i__ + k * p_dim1] = (real)gfk_log(p[i__ + k * p_dim1]);
	}
    }
    i__1 = *ite;
    for (i__ = *its; i__ <= i__1; ++i__) {
	ko = 1;
	i__2 = *kte;
	for (k = *kts + 1; k <= i__2; ++k) {
	    while(ko < *np && p[i__ + k * p_dim1] > pres[ko]) {
		++ko;
	    }
	    o3[i__ + k * o3_dim1] = (ozone[ko] * (pres[ko - 1] - p[i__ + k *
		    p_dim1]) + ozone[ko - 1] * (p[i__ + k * p_dim1] - pres[ko]
		    )) / (pres[ko - 1] - pres[ko]);
	    --ko;
	}
    }
    i__1 = *ite;
    for (i__ = *its; i__ <= i__1; ++i__) {
	ko = 1;
	k = *kts;
	while(ko <= *np && p[i__ + k * p_dim1] > pres[ko]) {
	    ++ko;
	}
	if (ko - 1 <= 1) {
	    o3[i__ + k * o3_dim1] = ozone[k];
	} else {
	    o3[i__ + k * o3_dim1] = 0.f;
	    for (kk = ko - 2; kk >= 1; --kk) {
		o3[i__ + k * o3_dim1] += ozone[kk] * (pres[kk + 1] - pres[kk])
			;
	    }
	    o3[i__ + k * o3_dim1] /= pres[ko - 1] - pres[1];
	}
    }
    return 0;
}



// Bottom-to-top packed layers. All optional water fields are present.
extern "C" __global__ void gsfcsw_columns_kernel(
    const float *tables, float *inputs, float *outputs, float *workspace,
    int ncol, int nlay, int warm, int fqi, int fqn,
    int julday, float solcon, float latitude) {
    int col = blockIdx.x * blockDim.x + threadIdx.x;
    if (col >= ncol) return;
    int n = nlay + 1, one = 1, two = 2, yes = 1, no = 0;
    float *a = inputs + col*(9*n+2), *b = outputs + col*(3*n+2);
    float zero[129] = {}, cp = 1004.5f, g = 9.81f, obscur = 0.0f;
    gsfcswrad_(workspace + (col/32)*32*GSFC_WORKSPACE_WORDS + col%32, tables,
        b, b+3*n, zero, zero, a+9*n+1, a, a+4*n, a+5*n, zero,
        a+6*n, zero, zero, a+8*n, a+n, a+2*n, a+3*n, a+7*n,
        b+3*n+1, &cp, &g, &julday, &solcon, b+n, b+2*n, &warm,
        zero,zero,zero,zero,zero,zero,zero,zero,zero,zero,zero,zero,
        &no, &yes,&yes,&no,&fqi,&no,&no,&fqn,
        a+9*n,&obscur,
        &one,&two,&one,&two,&one,&n,
        &one,&one,&one,&one,&one,&n,
        &one,&one,&one,&one,&one,&nlay,&latitude);
}

extern "C" __global__ void gsfcsw_math_probe(const float *rows,float *out,int count) {
    int i=blockIdx.x*blockDim.x+threadIdx.x;
    if(i>=count)return;
    int kind=(int)rows[4*i]; float a=rows[4*i+1],b=rows[4*i+2];
    if(kind==0)out[i]=gfk_exp(a);
    if(kind==1)out[i]=gfk_log(a);
    if(kind==2)out[i]=gfk_pow(a,b);
    if(kind==3)out[i]=r_lg10(&a);
}
