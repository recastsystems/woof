 __device__ int deledd_(real *workspace, const real *tables, gsfc_ptr<real> tau, gsfc_ptr<real> ssc, gsfc_ptr<real> g0, gsfc_ptr<real> csm, gsfc_ptr<real>
	rr, gsfc_ptr<real> tt, gsfc_ptr<real> td) {



    real ff, gp, xx, gm1, gm2, gm3, st1, st2, st3, st4, st7, st8, akk, all,
	    bll, cll, dll, ell, fll, zth, alf1, alf2, sscp, taup;

    zth = 1.f / *csm;
    ff = *g0 * *g0;
    xx = 1.f - ff * *ssc;
    taup = *tau * xx;
    sscp = *ssc * (1.f - ff) / xx;
    gp = *g0 / (*g0 + 1.f);
    xx = gp * 3.f;
    gm1 = (7.f - sscp * (xx + 4.f)) * .25f;
    gm2 = -(1.f - sscp * (4.f - xx)) * .25f;
    akk = (real)__fsqrt_rn((real)((gm1 + gm2) * (gm1 - gm2)));
    xx = akk * zth;
    st7 = 1.f - xx;
    st8 = xx + 1.f;
    st3 = st7 * st8;
    if (fabsf(st3) < 1e-8f) {
	zth += .001f;
	xx = akk * zth;
	st7 = 1.f - xx;
	st8 = xx + 1.f;
	st3 = st7 * st8;
    }
    *td = (real)gfk_exp((real)(-taup / zth));
    gm3 = (2.f - zth * 3.f * gp) * .25f;
    xx = gm1 - gm2;
    alf1 = gm1 - gm3 * xx;
    alf2 = gm2 + gm3 * xx;
    xx = akk * 2.f;
    all = (gm3 - alf2 * zth) * xx * *td;
    bll = (1.f - gm3 + alf1 * zth) * xx;
    xx = akk * gm3;
    cll = (alf2 + xx) * st7;
    dll = (alf2 - xx) * st8;
    xx = akk * (1.f - gm3);
    fll = (alf1 + xx) * st8;
    ell = (alf1 - xx) * st7;
    st2 = (real)gfk_exp((real)(-akk * taup));
    st4 = st2 * st2;
    st1 = sscp / ((akk + gm1 + (akk - gm1) * st4) * st3);
    *rr = (cll - dll * st4 - all * st2) * st1;
    *tt = -((fll - ell * st4) * *td - bll * st2) * st1;
    *rr = max(*rr,0.f);
    *tt = max(*tt,0.f);
    return 0;
}

