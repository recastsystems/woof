"""Bit-exact NumPy port of WRF v4.6.1's RRTMG McICA subcolumn generators.

Source authority: ``module mcica_subcol_gen_lw`` in
``phys/module_ra_rrtmg_lw.F`` and ``module mcica_subcol_gen_sw`` in
``phys/module_ra_rrtmg_sw.F`` (WRF v4.6.1, FP32 ``kind_rb`` build).  WRF's
legacy RRTMG option-4 drivers call these with the kissvec generator
(``irng = 0``), per-column seeds derived from the fractional parts of the
four bottom-layer pressures, and fixed permute seeds:

* longwave  (``rrtmg_lwrad``): ``irng = 0``, ``permuteseed = 150``
* shortwave (``rrtmg_swrad``): ``irng = 0``, ``permuteseed = 1``

and ``icld = cldovrlp`` from the WRF namelist (default 2, maximum-random
overlap).  ``idcor``, ``juldat`` and ``lat`` select the decorrelation
length for the exponential overlaps (``icld = 4, 5``).

FROZEN CONTRACT (consumed by the RRTMG LW/SW compute lanes)
-----------------------------------------------------------
:func:`generate_lw_subcolumns` / :func:`generate_sw_subcolumns` mirror the
Fortran dummy argument names of ``mcica_subcol_lw`` / ``mcica_subcol_sw``
one for one (``iplon`` is accepted and unused, exactly like the Fortran
dummy).  Arrays use the Fortran dimension order: per-column inputs are
``(ncol, nlay)``, band inputs ``(nbnd, ncol, nlay)``, and the returned
dict carries the Fortran output names with subcolumn arrays shaped
``(ngpt, ncol, nlay)`` (``ngptlw = 140``, ``ngptsw = 112``), all float32.
Layer index 0 is the layer nearest the surface (WRF passes bottom-up
columns; the kissvec seed requires ``pmid`` non-increasing across the
bottom four layers).

Every float32 operation reproduces the gfortran -O0 sequence of the
Fortran (multiplies/adds rounded singly, no FMA); integer RNG state is
exact 32-bit wraparound arithmetic; ``exp`` on float32 goes through
:mod:`woof.core.noahmp_libm`'s bit-exact glibc 2.39 ``expf``.  The gate
is ``tests/test_rrtmg_mcica.py`` against fixtures generated by the
unmodified WRF Fortran (``tools/rrtmg_wrf461_oracle/mcica_fixture_lw`` /
``_sw``), matched bit for bit.

Documented fail-closed divergences from WRF-undefined behaviour
---------------------------------------------------------------
* ``icld = 0``: the Fortran returns with every ``intent(out)`` array left
  undefined (the WRF driver never calls the generator in that state).
  This port raises instead of inventing output values.
* ``icld`` outside ``0..5``: the LW Fortran executes ``STOP``; the SW
  Fortran falls through its ``select case`` and uses an uninitialized
  CDF array (undefined behaviour).  This port raises for both.
* ``irng /= 0`` selects the Mersenne-Twister path, which WRF's option-4
  drivers never use; it is not ported and raises rather than silently
  substituting a different RNG.

CUDA device twin (forecast path)
--------------------------------
:func:`gpu_generate_lw_subcolumns` / :func:`gpu_generate_sw_subcolumns`
are device twins of the NumPy entries for ``icld = 2`` (maximum-random)
ONLY -- any other ``icld`` raises :class:`NotImplementedError` host-side
before any launch, and the NumPy generators above keep serving the other
overlaps.  They accept the same logical inputs (numpy or cupy float32),
return cupy arrays in the frozen output shapes, and are gated bitwise
against the NumPy port (hence transitively against the WRF Fortran) by
the device section of ``tests/test_rrtmg_mcica.py``.  Kernels live in
``woof/core/kernels/rrtmg_mcica_wrf.cu``.
"""

