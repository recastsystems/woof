NBNDLW = 16
NGPTLW = 140
NBNDSW = 14
NGPTSW = 112

#: permuteseed WRF v4.6.1 hardwires in rrtmg_lwrad / rrtmg_swrad.
LW_PERMUTESEED = 150
SW_PERMUTESEED = 1

# ngb data statements from lwcmbdat / swcmbdat: the band index of every
# reduced g-point (LW bands 1..16, SW bands 16..29).
_LW_NGC = (10, 12, 16, 14, 16, 8, 12, 8, 12, 6, 8, 8, 4, 2, 2, 2)
_SW_NGC = (6, 12, 8, 8, 10, 10, 2, 10, 8, 6, 6, 8, 6, 12)
_LW_NGB = np.repeat(np.arange(1, 17), _LW_NGC)          # 140 entries
_SW_NGB = np.repeat(np.arange(16, 30), _SW_NGC)         # 112 entries
assert _LW_NGB.shape == (NGPTLW,) and _SW_NGB.shape == (NGPTSW,)

_F32_ONE = np.float32(1.0)
_F32_ZERO = np.float32(0.0)
_CLDMIN = np.float32(1.0e-20)
_KISS_SCALE = np.float32(2.328306e-10)
_KISS_HALF = np.float32(0.5)
_PMID_SCALE = np.float32(1.0e2)
_SEED_SCALE = np.float32(1000000000.0)   # 1000000000_im converted to REAL(4)

# Decorrelation-length constants (mcica_subcol_lw/sw locals).
_AM1 = np.float32(1.4315)
_AM2 = np.float32(2.1219)
_AM4 = np.float32(-25.584)
_AMR = np.float32(7.0)
_ZO_DEFAULT = np.float32(2500.0)


def _expf32(values: np.ndarray) -> np.ndarray:
    """Elementwise glibc-2.39 expf on a float32 array."""
    flat = values.ravel()
    out = np.empty(flat.shape, dtype=np.float32)
    for i, x in enumerate(flat):
        out[i] = np.float32(expf(float(x)))
    return out.reshape(values.shape)


def _kissvec(seeds: list[np.ndarray]) -> np.ndarray:
    """One kissvec call: advance the four uint32 seed vectors, return the
    float32 random vector.  Bitwise identical to WRF's int32 kissvec (all
    Fortran ishft shifts are logical, hence the uint32 carrier)."""
    s1, s2, s3, s4 = seeds
    s1 = (np.uint32(69069) * s1 + np.uint32(1327217885)).astype(np.uint32)
    s2 = s2 ^ ((s2 << np.uint32(13)) & np.uint32(0xFFFFFFFF))
    s2 = s2 ^ (s2 >> np.uint32(17))
    s2 = s2 ^ ((s2 << np.uint32(5)) & np.uint32(0xFFFFFFFF))
    s3 = (np.uint32(18000) * (s3 & np.uint32(0xFFFF)) +
          (s3 >> np.uint32(16))).astype(np.uint32)
    s4 = (np.uint32(30903) * (s4 & np.uint32(0xFFFF)) +
          (s4 >> np.uint32(16))).astype(np.uint32)
    kiss = (s1 + s2 + ((s3 << np.uint32(16)) & np.uint32(0xFFFFFFFF)) + s4
            ).astype(np.uint32)
    seeds[0], seeds[1], seeds[2], seeds[3] = s1, s2, s3, s4
    # REAL(kiss): signed int32 value converted to float32 (round-nearest),
    # then a single float32 multiply and add.
    kiss_signed = kiss.view(np.int32).astype(np.float32)
    return (kiss_signed * _KISS_SCALE + _KISS_HALF).astype(np.float32)


def _make_seeds(pmid: np.ndarray, change_seed: int) -> list[np.ndarray]:
    """Per-column kissvec seeds from the bottom-four-layer pressures,
    advanced ``changeSeed`` times, exactly as generate_stochastic_clouds."""
    ncol = pmid.shape[0]
    if pmid.shape[1] < 4:
        raise ValueError("kissvec seeding requires at least four layers")
    if np.any(pmid[:, 0] < pmid[:, 1]):
        raise ValueError(
            "MCICA_SUBCOL: KISSVEC SEED GENERATOR REQUIRES PMID FROM "
            "BOTTOM FOUR LAYERS.")
    seeds = []
    for layer in range(4):
        col = pmid[:, layer]
        ipart = col.astype(np.int32)                    # Fortran INT(): trunc
        frac = (col - ipart.astype(np.float32)).astype(np.float32)
        scaled = (frac * _SEED_SCALE).astype(np.float32)
        seeds.append(scaled.astype(np.int32).view(np.uint32).copy())
    rand = np.empty(ncol, dtype=np.float32)
    for _ in range(change_seed):
        rand = _kissvec(seeds)
    del rand
    return seeds


def _decorr_len(ncol: int, idcor: int, juldat: int,
                lat: np.float32) -> np.ndarray:
    if idcor == 1:
        if juldat > 181:
            am3 = np.float32(np.float32(np.float32(np.float32(-4.0) * _AMR)
                                        / np.float32(365.0))
                             * np.float32(juldat - 272))
        else:
            am3 = np.float32(np.float32(np.float32(np.float32(4.0) * _AMR)
                                        / np.float32(365.0))
                             * np.float32(juldat - 91))
        diff = np.float32(np.float32(lat) - am3)
        arg = np.float32(-np.float32(np.float32(diff * diff)
                                     / np.float32(_AM4 * _AM4)))
        value = np.float32(
            np.float32(_AM1 + np.float32(
                _AM2 * np.float32(expf(float(arg)))))
            * np.float32(1.0e3))
    else:
        value = _ZO_DEFAULT
    return np.full(ncol, value, dtype=np.float32)


def _generate_stochastic_clouds(ncol, nlay, nsubcol, icld, irng, pmid,
                                cldf, hgt, decorr_len, change_seed):
    """Port of generate_stochastic_clouds[_sw] through the CDF stage.

    Returns the boolean iscloudy mask, shape (nsubcol, ncol, nlay).
    ``cldf`` is the already cldmin-thresholded cloud fraction.
    """
    if irng != 0:
        raise NotImplementedError(
            "irng != 0 selects the Mersenne-Twister generator, which WRF's "
            "RRTMG option-4 drivers never use; only kissvec (irng = 0) is "
            "ported")
    overlap = int(icld)
    seeds = _make_seeds(pmid, change_seed)
    cdf = np.empty((nsubcol, ncol, nlay), dtype=np.float32)

    if overlap == 1:
        for isubcol in range(nsubcol):
            for ilev in range(nlay):
                cdf[isubcol, :, ilev] = _kissvec(seeds)
    elif overlap == 2:
        for isubcol in range(nsubcol):
            for ilev in range(nlay):
                cdf[isubcol, :, ilev] = _kissvec(seeds)
        for ilev in range(1, nlay):
            below = cdf[:, :, ilev - 1]
            clear_frac = (_F32_ONE - cldf[:, ilev - 1]).astype(np.float32)
            keep = below > clear_frac[None, :]
            scaled = (cdf[:, :, ilev] * clear_frac[None, :]).astype(
                np.float32)
            cdf[:, :, ilev] = np.where(keep, below, scaled)
    elif overlap == 3:
        for isubcol in range(nsubcol):
            rand = _kissvec(seeds)
            cdf[isubcol, :, :] = rand[:, None]
    elif overlap in (4, 5):
        zo_inv = (_F32_ONE / decorr_len).astype(np.float32)
        alpha = np.zeros((ncol, nlay), dtype=np.float32)
        diff = (hgt[:, 1:] - hgt[:, :-1]).astype(np.float32)
        arg = -(diff * zo_inv[:, None]).astype(np.float32)
        alpha[:, 1:] = _expf32(arg)
        if overlap == 5:
            # Decorrelate where a clear layer follows a cloudy layer.
            decorrelate = (cldf[:, 1:] == _F32_ZERO) & \
                (cldf[:, :-1] > _F32_ZERO)
            alpha[:, 1:][decorrelate] = _F32_ZERO
        cdf2 = np.empty_like(cdf)
        for isubcol in range(nsubcol):
            for ilev in range(nlay):
                cdf[isubcol, :, ilev] = _kissvec(seeds)
                cdf2[isubcol, :, ilev] = _kissvec(seeds)
        for ilev in range(1, nlay):
            correlated = cdf2[:, :, ilev] < alpha[None, :, ilev]
            cdf[:, :, ilev] = np.where(
                correlated, cdf[:, :, ilev - 1], cdf[:, :, ilev])
    else:
        raise ValueError(
            f"MCICA_SUBCOL: INVALID ICLD {icld}: the WRF LW Fortran STOPs "
            "and the SW Fortran would read an uninitialized CDF array "
            "(undefined behaviour); woof fails closed for both")

    threshold = (_F32_ONE - cldf).astype(np.float32)    # (ncol, nlay)
    return cdf >= threshold[None, :, :]


def _common_inputs(ncol, nlay, play, cldfrac, hgt):
    play = np.asarray(play, dtype=np.float32)
    cldfrac = np.asarray(cldfrac, dtype=np.float32)
    hgt = np.asarray(hgt, dtype=np.float32)
    for name, arr in (("play", play), ("cldfrac", cldfrac), ("hgt", hgt)):
        if arr.shape != (ncol, nlay):
            raise ValueError(f"{name} must have shape (ncol, nlay) = "
                             f"({ncol}, {nlay}); got {arr.shape}")
    pmid = (play * _PMID_SCALE).astype(np.float32)
    cldf = cldfrac.copy()
    cldf[cldf < _CLDMIN] = _F32_ZERO
    return pmid, cldf, hgt


def _check_icld(icld: int) -> None:
    if icld == 0:
        raise ValueError(
            "icld=0 (clear sky): the WRF Fortran returns with every McICA "
            "output left undefined; the woof radiation driver must skip "
            "the generator instead of calling it")
    if icld < 0 or icld > 5:
        raise ValueError(
            f"MCICA_SUBCOL: INVALID ICLD {icld} (legal cloud-overlap "
            "settings are 1..5)")


def generate_lw_subcolumns(iplon, ncol, nlay, icld, permuteseed, irng,
                           play, cldfrac, ciwp, clwp, cswp, rei, rel, res,
                           tauc, hgt, idcor, juldat, lat):
    """Port of ``mcica_subcol_lw``; argument names mirror the Fortran.

    ``tauc`` is ``(nbndlw, ncol, nlay)``.  Returns a dict with the Fortran
    output names: ``cldfmcl``, ``ciwpmcl``, ``clwpmcl``, ``cswpmcl``,
    ``taucmcl`` shaped ``(ngptlw, ncol, nlay)`` and ``reicmcl``,
    ``relqmcl``, ``resnmcl`` shaped ``(ncol, nlay)``, all float32.
    """
    del iplon  # unused Fortran dummy
    _check_icld(icld)
    pmid, cldf, hgt = _common_inputs(ncol, nlay, play, cldfrac, hgt)
    tauc = np.asarray(tauc, dtype=np.float32)
    if tauc.shape != (NBNDLW, ncol, nlay):
        raise ValueError(
            f"tauc must have shape (nbndlw, ncol, nlay) = "
            f"({NBNDLW}, {ncol}, {nlay}); got {tauc.shape}")
    decorr = _decorr_len(ncol, idcor, juldat, lat)
    iscloudy = _generate_stochastic_clouds(
        ncol, nlay, NGPTLW, icld, irng, pmid, cldf, hgt, decorr,
        permuteseed)
    return _fill_outputs(iscloudy, ciwp, clwp, cswp, rei, rel, res,
                         _LW_NGB - 1, (("taucmcl", tauc, _F32_ZERO),))


def generate_sw_subcolumns(iplon, ncol, nlay, icld, permuteseed, irng,
                           play, cldfrac, ciwp, clwp, cswp, rei, rel, res,
                           tauc, ssac, asmc, fsfc, hgt, idcor, juldat, lat):
    """Port of ``mcica_subcol_sw``; argument names mirror the Fortran.

    Band inputs are ``(nbndsw, ncol, nlay)``.  Returns a dict with the
    Fortran output names: ``cldfmcl``, ``ciwpmcl``, ``clwpmcl``,
    ``cswpmcl``, ``taucmcl``, ``ssacmcl``, ``asmcmcl``, ``fsfcmcl`` shaped
    ``(ngptsw, ncol, nlay)`` and ``reicmcl``, ``relqmcl``, ``resnmcl``
    shaped ``(ncol, nlay)``, all float32.
    """
    del iplon  # unused Fortran dummy
    _check_icld(icld)
    pmid, cldf, hgt = _common_inputs(ncol, nlay, play, cldfrac, hgt)
    band_arrays = {}
    for name, arr in (("tauc", tauc), ("ssac", ssac), ("asmc", asmc),
                      ("fsfc", fsfc)):
        arr = np.asarray(arr, dtype=np.float32)
        if arr.shape != (NBNDSW, ncol, nlay):
            raise ValueError(
                f"{name} must have shape (nbndsw, ncol, nlay) = "
                f"({NBNDSW}, {ncol}, {nlay}); got {arr.shape}")
        band_arrays[name] = arr
    decorr = _decorr_len(ncol, idcor, juldat, lat)
    iscloudy = _generate_stochastic_clouds(
        ncol, nlay, NGPTSW, icld, irng, pmid, cldf, hgt, decorr,
        permuteseed)

    return _fill_outputs(
        iscloudy, ciwp, clwp, cswp, rei, rel, res, _SW_NGB - _SW_NGB[0],
        (("taucmcl", band_arrays["tauc"], _F32_ZERO),
         ("ssacmcl", band_arrays["ssac"], _F32_ONE),
         ("asmcmcl", band_arrays["asmc"], _F32_ZERO),
         ("fsfcmcl", band_arrays["fsfc"], _F32_ZERO)))


def _fill_outputs(iscloudy, ciwp, clwp, cswp, rei, rel, res, band_index, bands):
    ciwp = np.asarray(ciwp, dtype=np.float32)
    clwp = np.asarray(clwp, dtype=np.float32)
    cswp = np.asarray(cswp, dtype=np.float32)
    cloudy = iscloudy
    out = {
        "cldfmcl": np.where(cloudy, _F32_ONE, _F32_ZERO).astype(np.float32),
        "ciwpmcl": np.where(cloudy, ciwp[None, :, :], _F32_ZERO).astype(
            np.float32),
        "clwpmcl": np.where(cloudy, clwp[None, :, :], _F32_ZERO).astype(
            np.float32),
        "cswpmcl": np.where(cloudy, cswp[None, :, :], _F32_ZERO).astype(
            np.float32),
    }
    for name, array, clear in bands:
        out[name] = np.where(cloudy, array[band_index], clear).astype(np.float32)
    out.update({
        "reicmcl": np.asarray(rei, dtype=np.float32).copy(),
        "relqmcl": np.asarray(rel, dtype=np.float32).copy(),
        "resnmcl": np.asarray(res, dtype=np.float32).copy(),
    })
    return out


