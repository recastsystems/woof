"""WRF v4.6.1 Registry masked and integer feedback carrier inventory.

The public-domain Registry supplies names, operator and horizontal staggering.
Only allocated carriers participate: inactive WRF packages allocate no state.
This inventory is separate from lateral boundary forcing; soil and surface
carriers have no rolling boundary arrays. No mass averaging replaces the
Registry's one-point masked/integer operators.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class SurfaceFeedback:
    name: str
    operator: str
    stagger: str
    registry_line: int

    @property
    def keys(self):
        aliases = {"msfvx_inv": "msfv_inv"}
        if self.name in ("msft", "msfu", "msfv", "msfvx_inv", "f", "e", "sina", "cosa"):
            return (aliases.get(self.name, self.name),)
        return ("fields/" + self.name,)


