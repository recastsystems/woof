def validate(value):
    if type(value) is not float or not math.isfinite(value) or value < 0:
        raise ValueError("noahmp_acc_dt must be finite nonnegative minutes")
    return value

def shapes(option,shape):
    if int(option)!=3:return {}
    from woof.core.noahmp_runtime import NOAHMP_STATE_2D,NOAHMP_DIAGNOSTICS_2D
    existing=set(NOAHMP_STATE_2D+NOAHMP_DIAGNOSTICS_2D+("isnowxy","albedo","emiss","glw"))
    return dict.fromkeys(tuple(n for n in dict.fromkeys(CARRIERS[n] for n in (*ACCUMULATORS,*INPUTS)) if n not in existing),tuple(shape))

def advance(fields,*,dt,minutes,elapsed_seconds,opt_run=3,itimestep=1,stepwtd=1):
    validate(minutes)
    if minutes<=0:return
    from woof.core.kernels import load_module
    period=np.float32(np.float32(60.0)*np.float32(minutes))
    reset=np.fmod(np.float32(elapsed_seconds),period)==np.float32(0.0)
    arrays=tuple(fields[CARRIERS[n]] for n in (*ACCUMULATORS,*INPUTS))
    n=arrays[0].size
    load_module("noahmp_output").get_function("noahmp_output_calc")(
        ((n+127)//128,),(128,),(*arrays,np.float32(dt),np.int32(n),np.int32(reset),np.int32(opt_run),np.int32(int(itimestep)%max(1,int(stepwtd))==0)))

def update(state,cfg):
    if int(cfg.sf_surface_physics)!=4 or int(cfg.noahmp_output)!=3:return
    driver=state.physics
    if driver is None:return
    advance(driver.fields,dt=cfg.dt,minutes=cfg.noahmp_acc_dt,
            elapsed_seconds=float(state.elapsed_seconds)-float(getattr(state,"domain_start_offset",0.0)),opt_run=cfg.opt_run,
            itimestep=int(np.floor((float(state.elapsed_seconds)-float(getattr(state,"domain_start_offset",0.0)))/float(cfg.dt)+0.5))+1,
            stepwtd=getattr(driver,"stepwtd",1))
