@dataclass(frozen=True)
class ClassicTableSet:
    """Validated immutable host tables plus restart-safe asset identity."""

    root: Path
    arrays: Mapping[str, np.ndarray]
    assets: tuple[TableAsset, ...] = CLASSIC_TABLE_ASSETS

    @property
    def payload_bytes(self) -> int:
        return sum(array.nbytes for array in self.arrays.values())

    @property
    def identity(self) -> dict[str, object]:
        if self.assets == FORK_TABLE_ASSETS:
            return {
                "schema": 1,
                "table_set": FORK_TABLE_SET_ID,
                "wrf_version": "3.9-noaa-fork",
                "wrf_source": FORK_REFERENCE_SOURCE,
                "assets": [
                    {"filename": item.filename, "bytes": item.bytes,
                     "sha256": item.sha256}
                    for item in self.assets
                ],
            }
        return {
            "schema": 1,
            "table_set": TABLE_SET_ID,
            "wrf_version": WRF_REFERENCE_VERSION,
            "wrf_commit": WRF_REFERENCE_COMMIT,
            "assets": [
                {"filename": item.filename, "bytes": item.bytes,
                 "sha256": item.sha256}
                for item in self.assets
            ],
        }

    def to_device(self, backend) -> Mapping[str, object]:
        """Upload exact float64 tables while preserving Fortran index order.

        No float32 table path is admitted here.  It would be a separately
        quantified numerical variant, not a harmless storage optimization.
        """
        return MappingProxyType({
            name: backend.asarray(array, dtype=backend.float64, order="F")
            for name, array in self.arrays.items()
        })


def _sha256_file(path: Path, *, block_bytes: int = 8 * 1024 * 1024) -> str:
    # Once per process for an unchanged file (woof.file_digest): the table
    # validation and every checkpoint's physics identity hash these bytes,
    # and a replaced or rewritten table is still hashed again.
    from woof.file_digest import sha256_file
    return sha256_file(path, block_bytes=block_bytes)


def validate_table_assets(
        path: str | Path, assets: tuple[TableAsset, ...] = CLASSIC_TABLE_ASSETS,
        ) -> tuple[TableAsset, ...]:
    """Fail closed on absent, resized, or byte-substituted table assets."""
    root = Path(path)
    for asset in assets:
        family = "thompson-fork" if asset in FORK_TABLE_ASSETS else "thompson"
        command = f"woof fetch-tables --schemes {family} --from DIR --replace-damaged"
        current = root / asset.filename
        if not current.is_file():
            raise FileNotFoundError(
                f"missing Thompson table asset {current}; run {command}")
        actual_bytes = current.stat().st_size
        if actual_bytes != asset.bytes:
            raise ValueError(
                f"Thompson table asset {current} has {actual_bytes} bytes; "
                f"expected {asset.bytes}; run {command}")
        actual_sha256 = _sha256_file(current)
        if actual_sha256 != asset.sha256:
            raise ValueError(
                f"Thompson table asset {current} SHA-256 {actual_sha256}; "
                f"expected {asset.sha256}; run {command}")
    return assets


def read_validated_table_asset(path: str | Path, asset: TableAsset) -> bytes:
    """Immutable parser bytes, reusing admission's digest while unchanged."""
    current = Path(path) / asset.filename
    family = "thompson-fork" if asset in FORK_TABLE_ASSETS else "thompson"
    command = f"woof fetch-tables --schemes {family} --from DIR --replace-damaged"
    if not current.is_file():
        raise FileNotFoundError(
            f"missing Thompson table asset {current}; run {command}")
    from woof.tables import _file_state
    before = _file_state(current)
    actual_sha256 = _sha256_file(current)
    data = current.read_bytes()
    if _file_state(current) != before:
        raise ValueError(
            f"Thompson table asset {current} changed while being read; "
            f"refusing mixed lookup coefficients; run {command}")
    if len(data) != asset.bytes:
        raise ValueError(
            f"Thompson table asset {current} has {len(data)} bytes; "
            f"expected {asset.bytes}; run {command}")
    if actual_sha256 != asset.sha256:
        raise ValueError(
            f"Thompson table asset {current} SHA-256 {actual_sha256}; "
            f"expected {asset.sha256}; run {command}")
    return data


class _BufferReader:
    """``read(count)`` over immutable bytes, returning views, never copies."""

    def __init__(self, data: bytes):
        self._view = memoryview(data)
        self._offset = 0

    def read(self, count: int) -> memoryview:
        chunk = self._view[self._offset:self._offset + count]
        self._offset += len(chunk)
        return chunk


def sequential_file_bytes(records: tuple[TableRecord, ...], *,
                          marker_bytes: int = 4) -> int:
    """Exact file size with one leading/trailing marker per record."""
    if marker_bytes not in (4, 8):
        raise ValueError("Fortran record markers must be 4 or 8 bytes")
    return sum(record.payload_bytes + 2 * marker_bytes for record in records)


def read_sequential_records(
        path: str | Path, records: tuple[TableRecord, ...], *,
        marker_bytes: int = 4, byteorder: str = "little",
        data: bytes | None = None,
        ) -> dict[str, np.ndarray]:
    """Read and strictly validate WRF/gfortran sequential records.

    Arrays are returned in native-endian float64 with their documented
    Fortran shapes.  ``order='F'`` is essential: WRF's first index is the
    contiguous dimension, while NumPy otherwise assumes the last one is.

    ``data``, when given, is the file's content already in memory (``path``
    then only names it in messages); its native-endian records come back
    as read-only views of those bytes instead of copies.
    """
    source = Path(path)
    if data is not None and not isinstance(data, bytes):
        raise TypeError("sequential record data must be immutable bytes")
    if marker_bytes not in (4, 8):
        raise ValueError("Fortran record markers must be 4 or 8 bytes")
    if byteorder not in ("little", "big"):
        raise ValueError("byteorder must be 'little' or 'big'")
    marker_format = ("<" if byteorder == "little" else ">") + (
        "i" if marker_bytes == 4 else "q")
    dtype = np.dtype("<f8" if byteorder == "little" else ">f8")
    result: dict[str, np.ndarray] = {}
    opened = (source.open("rb") if data is None
              else contextlib.nullcontext(_BufferReader(data)))
    with opened as stream:
        for record in records:
            head = stream.read(marker_bytes)
            if len(head) != marker_bytes:
                raise ValueError(
                    f"{source}: missing leading marker for {record.name}")
            declared = struct.unpack(marker_format, head)[0]
            if declared != record.payload_bytes:
                raise ValueError(
                    f"{source}: {record.name} marker declares {declared} "
                    f"bytes, expected {record.payload_bytes}")
            payload = stream.read(record.payload_bytes)
            if len(payload) != record.payload_bytes:
                raise ValueError(
                    f"{source}: truncated {record.name} payload "
                    f"({len(payload)} != {record.payload_bytes} bytes)")
            tail = stream.read(marker_bytes)
            if len(tail) != marker_bytes or struct.unpack(
                    marker_format, tail)[0] != declared:
                raise ValueError(
                    f"{source}: mismatched trailing marker for "
                    f"{record.name}")
            values = np.frombuffer(payload, dtype=dtype, count=record.values)
            shaped = values.reshape(record.shape, order="F")
            if data is not None and dtype.isnative:
                result[record.name] = shaped
            else:
                result[record.name] = np.array(
                    shaped, dtype=np.float64, order="F", copy=True)
        extra = stream.read(1)
        if extra:
            raise ValueError(f"{source}: unexpected bytes after final record")
    return result


def read_generated_table_directory(path: str | Path) -> dict[str, np.ndarray]:
    """Read all three classic Thompson WRF-generated cache files."""
    root = Path(path)
    tables: dict[str, np.ndarray] = {}
    for filename, records in GENERATED_TABLE_FILES.items():
        current = read_sequential_records(root / filename, records)
        overlap = tables.keys() & current.keys()
        if overlap:
            raise RuntimeError(f"duplicate Thompson table names: {overlap}")
        tables.update(current)
    return tables


def read_classic_table_directory(path: str | Path) -> dict[str, np.ndarray]:
    """Read the complete classic mp=8 generated coefficient set."""
    root = Path(path)
    tables = read_generated_table_directory(root)
    auxiliary = read_sequential_records(
        root / AUXILIARY_TABLE_FILE, AUXILIARY_TABLE_RECORDS)
    overlap = tables.keys() & auxiliary.keys()
    if overlap:
        raise RuntimeError(f"duplicate Thompson table names: {overlap}")
    tables.update(auxiliary)
    return tables


def load_validated_classic_tables(
        path: str | Path, version: str = "wrf_461") -> ClassicTableSet:
    """Verify canonical bytes, parse every record, and freeze host arrays.

    Each asset is read once, checked against its pinned size and SHA-256 and
    parsed from those same bytes, the four assets on parallel threads (the
    hashing and the finite checks release the GIL).  The records are
    exactly the ones :func:`read_classic_table_directory` returns.

    ``version`` is RunConfig.thompson_version: ``"wrf_461"`` reads the WRF
    v4.6.1 set, ``"wrf_39_noaa"`` the operational WRF 3.9 fork's
    (:data:`FORK_GENERATED_TABLE_FILES`, :data:`FORK_TABLE_ASSETS`).
    """
    root = Path(path).resolve()
    try:
        generated_files, assets, _set_id = TABLE_SETS_BY_VERSION[version]
    except KeyError:
        raise ValueError(
            f"no Thompson table set for thompson_version={version!r}; "
            f"known: {sorted(TABLE_SETS_BY_VERSION)}") from None

    def parse(asset: TableAsset) -> dict[str, np.ndarray]:
        data = read_validated_table_asset(root, asset)
        records = (AUXILIARY_TABLE_RECORDS
                   if asset.filename == AUXILIARY_TABLE_FILE
                   else generated_files[asset.filename])
        current = read_sequential_records(
            root / asset.filename, records, data=data)
        for name, array in current.items():
            if not np.isfinite(array).all():
                raise ValueError(
                    f"Thompson table {name} contains non-finite values")
            array.flags.writeable = False
        return current

    with ThreadPoolExecutor(max_workers=len(assets)) as pool:
        groups = list(pool.map(parse, assets))
    arrays: dict[str, np.ndarray] = {}
    for current in groups:
        overlap = arrays.keys() & current.keys()
        if overlap:
            raise RuntimeError(f"duplicate Thompson table names: {overlap}")
        arrays.update(current)
    frozen = MappingProxyType(dict(arrays))
    result = ClassicTableSet(root=root, arrays=frozen, assets=assets)
    expected_payload = sum(
        record.payload_bytes
        for records in generated_files.values() for record in records
    ) + sum(record.payload_bytes for record in AUXILIARY_TABLE_RECORDS)
    if result.payload_bytes != expected_payload:
        raise RuntimeError(
            f"Thompson payload inventory is {result.payload_bytes} bytes; "
            f"expected {expected_payload}")
    return result


