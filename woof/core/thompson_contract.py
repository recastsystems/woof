@dataclass(frozen=True)
class TableRecord:
    """One real(kind=8) array in a WRF sequential-unformatted file."""

    name: str
    shape: tuple[int, ...]

    @property
    def values(self) -> int:
        return int(np.prod(self.shape, dtype=np.int64))

    @property
    def payload_bytes(self) -> int:
        return self.values * np.dtype("<f8").itemsize


