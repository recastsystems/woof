def _field_max_rel(got, want):
    got = np.asarray(got, np.float64)
    want = np.asarray(want, np.float64)
    both_zero = (got == 0.0) & (want == 0.0)
    rel = np.abs(got - want) / np.maximum(np.abs(want), 1.0e-30)
    return float(np.where(both_zero, 0.0, rel).max())


def test_device_saturation_fit_reproduces_the_fortran_horner_bitwise():
    """thompson_rslf must equal WRF's RSLF bit for bit, not to within an ulp.

    THIS IS NOT A ROUNDING GATE.  module_mp_thompson.F:3401 opens the whole
    condensation/nucleation block on ``ssatw(k) .gt. eps`` with eps = 1.E-15
    (:185), and :3197-3198 sets ssatw from qv/qvs with a snap to zero only
    inside that same 1e-15 band.  A saturation fit that is ONE float32 ulp
    low therefore does not perturb a rate -- it flips a branch.

    MEASURED on the aero-nc-sed entry column (RTX 5090, cupy 14.1.1): the
    device fit is 1 ulp below the Fortran at 24 of 24 levels, ssatw becomes
    +1.19e-7 instead of exactly 0, and the end-to-end call then condenses a
    few times 1e-10 kg/kg of cloud and activates around 1e6 droplets per
    kilogram at TWENTY of the twenty-four levels -- every cloud-free one --
    where WRF condenses nothing at all, consuming up to 5.6 percent of the
    column CCN in the process.

    ROOT CAUSE: nvrtc defaults to --fmad=true and contracts the Horner chain
    at thompson_aerosol_common.cuh:713-714 into FMAs, while build_aero.sh
    compiles the oracle with plain ``gfortran -O2`` on baseline x86-64, which
    has no FMA instruction.  FIX (thompson_aerosol_common.cuh, not this
    package): evaluate that chain through thompson_aa_add/thompson_aa_mul,
    exactly as the header already does for activ_ncloud, iceKoop and
    Eff_aero and for the same reason.  Doing so makes the mp=28 qvs differ
    from the frozen mp=8 qvs by one ulp, which is correct -- mp=28's oracle
    is WRF, not mp=8.
    """
    _require_device()
    from woof.core.thompson_aerosol_launch import probe_saturation

    before, _, _ = _oracle_aero_case("aero-nc-sed")
    pressure = _oracle_column(before, "p_pa")
    temperature = _oracle_column(before, "temp_k")
    qv = _oracle_column(before, "qv")

    reference = _reference_rslf(pressure, temperature)
    # the fixture is saturated by construction: qv IS rslf(p,T) in WRF
    assert np.array_equal(reference, qv), (
        "the aero-nc-sed entry column is no longer exactly saturated; this "
        "test's premise has changed")

    device = probe_saturation(_column(pressure).reshape(-1, 1, 1),
                              _column(temperature).reshape(-1, 1, 1))[0]
    cp.cuda.Stream.null.synchronize()
    got = device.get().ravel().astype(np.float32)
    ssatw = (qv / got).astype(np.float32) - np.float32(1.0)
    assert np.array_equal(got, reference), (
        f"device RSLF differs from the Fortran at "
        f"{int((got != reference).sum())}/{got.size} levels; the resulting "
        f"ssatw is {ssatw.max():.3e} against WRF's 0.0, which crosses the "
        f"eps = {WRF_EPS:g} gate at module_mp_thompson.F:3401")


#: Per-field agreement bounds for the whole-call comparison.
#:
#: 2e-6 is the working bound: one part in five hundred thousand across an
#: eighteen-kernel composition, and it is NOT slack.  woof applies mass
#: tendencies in place where WRF accumulates them and applies once at :3975,
#: so ``(q + d1) + d2`` is being compared against ``q + (d1 + d2)`` at every
#: level; that regrouping alone costs about one float32 ulp per process.
#:
#: TIGHTENED 25x BY WP-12c, FROM 2.5e-03 TO 1.0e-04, AND WHY.  The 2.5e-03
#: entry existed for a 1.92e-03 qr/nr residual at 0-based level 5 of
#: aero-reduces-to-classic (entry temperature 274.125 K, whose entire
#: 2.6186e-04 kg/kg of cloud water evaporates inside the step).  The cause was
#: found by WP-12a and closed in woof/core/microphysics_aerosol.py, but
#: :func:`_run_mp28_column` in THIS file -- a second, direct-launcher driver
#: that predates the adapter -- was still not passing it, so this file carried
#: a defect the production adapter no longer had:
#:
#:   module_mp_thompson.F:3193 diagnoses the TAU+1 density; :3242-3243 builds
#:   the working rain mass and number from it and :3384-3388 freezes
#:   ilamr/N0_r from those.  :3490 then OVERWRITES rho(k) inside the
#:   condensation loop, and :3505-3520's orho / rhof / vsc2 / rvs all read
#:   THAT one.  prv_rev is therefore proportional to the PRE-condensation
#:   density, and a driver carrying only the post-condensation density scales
#:   both prv_rev and pnr_rev by exactly rho_post/rho_pre.
#:
#: With ``entry_density`` wired in :func:`_run_mp28_column`, level 5 measures
#: 1.79e-07 (qr) and 5.70e-06 (nr) instead of 1.92e-03/1.92e-03, this file's
#: driver reproduces the production adapter's G3 row EXACTLY on every field,
#: and RAINNC on this fixture became BIT-IDENTICAL to WRF
#: (0.0019081949722021818).  The bound below is now the same 1.0e-04 the
#: adapter's ``_END_TO_END_BOUNDS`` carries, transcribed, and the residual it
#: covers is the same one: 0-based levels 1-4, the deep saturated warm-rain
#: part of the column, where the frozen mp=8 pipeline reproduces qr BITWISE
#: (tests/test_thompson_aerosol_adapter.py::
#: test_the_reduces_to_classic_residual_is_the_classic_paths).
#:
#: MEASURED after the fix (RTX 5090, cupy 14.1.1), aero-reduces-to-classic
#: with level 6 held to the ulp bound below:
#:     qr 7.8129e-05 (level 1), nr_per_kg 4.8317e-05 (level 1);
#:     every other field, RAINNC, SNOWNC and GRAUPELNC inside 2e-6.
_END_TO_END_BOUNDS = {
    "aero-nc-sed": {},
    "aero-reduces-to-classic": {"qr": 1.0e-4, "nr_per_kg": 1.0e-4},
}
_END_TO_END_DEFAULT_BOUND = 2.0e-6

#: Levels (0-based) held out of the RELATIVE qr/nr comparison and bounded in
#: ULPS OF THE ENTRY VALUE instead.  This used to be a bare exclusion list
#: justified as "WRF's own qr survives at a value BOTH ArWen ports drive to
#: exactly zero", and the test asserted ``got == 0.0`` there.  After
#: :func:`_run_mp28_column` was given WRF's :3193 density that sentence is
#: FALSE: mp=28 now produces 1.338405e-10 kg/kg at that level against WRF's
#: 1.342642e-10, and 39.999 per kg against 40.126.
#:
#: WHY RELATIVE IS THE WRONG METRIC AT THIS ONE LEVEL.  aero-reduces-to-classic
#: level 6 enters with qr = 3.1695777e-07 kg/kg and :3500-3574 evaporates
#: 99.958% of it in one 10 s step, so the surviving qr is the difference of two
#: nearly equal float32 numbers.  Relative error in the DIFFERENCE is the
#: relative error in the rate amplified by 1/(1 - 0.99958) = 2370, which puts a
#: 2e-06 relative gate below the float32 resolution of the entry value itself.
#: The bound is therefore stated in ulps of the entry value, which is the
#: quantity the cancellation is measured against, and it is the SAME bound the
#: adapter's ``_NEAR_CANCELLATION_LEVELS`` uses.
#: MEASURED: qr 14.90 ulp (4.2361e-13 kg/kg against ulp 2.842e-14),
#: nr_per_kg 4.05 ulp (0.1266 against ulp 0.03125).
#:
#: THIS IS STRICTLY MORE THAN THE OLD EXCLUSION ASSERTED.  The old form
#: skipped the level in the relative comparison and required a bare zero; this
#: form requires the produced value to be non-zero AND within 32 ulps of WRF's.
_WRF_QR_THRESHOLD_LEVELS = {"aero-reduces-to-classic": (6,)}
_NEAR_CANCELLATION_ULPS = 32.0


def _entry_ulp(value):
    """float32 ulp of ``value``, for the near-cancellation bound."""
    magnitude = np.float32(abs(np.float64(value)))
    if magnitude == 0.0:
        return float(np.nextafter(np.float32(0.0), np.float32(np.inf),
                                  dtype=np.float32))
    return float(np.nextafter(magnitude, np.float32(np.inf),
                              dtype=np.float32) - magnitude)


@pytest.mark.parametrize("scenario", ["aero-nc-sed", "aero-reduces-to-classic"])
def test_end_to_end_column_reproduces_the_committed_wrf_fixture(scenario):
    """A whole mp=28 call, entry to exit, against the committed oracle.

    ``aero-nc-sed`` (id 109) is the fixture this package owns: 24 saturated
    levels at 285 K with an nc ladder, so cloud fallout with its number
    channel is the dominant process.  ``aero-reduces-to-classic`` (id 119)
    spans 215-290 K and drives the cold network, DeMott nucleation, the
    balance limiter, condensation, rain evaporation and all five fallout
    species in one column.

    MEASURED (RTX 5090, cupy 14.1.1), with the saturation fit pinned as
    test_device_saturation_fit_reproduces_the_fortran_horner_bitwise
    requires:

        aero-nc-sed              qv, qc, qi, qs, qg, ni, nc, nwfa, nifa, temp,
                                 effc, effi, effs and RAINNC all BIT-EXACT;
                                 qr 9.3e-8; nr 2.2e-7.
        aero-reduces-to-classic  nwfa, nifa, qs, qg, effc, effs, RAINNC,
                                 SNOWNC and GRAUPELNC all BIT-EXACT;
                                 qi 8.2e-8, qv 9.1e-8, qc 1.2e-7, temp 1.4e-7,
                                 effi 1.5e-7, ni 3.5e-7, nc 6.6e-8;
                                 qr 7.8e-5 and nr 4.8e-5 at 0-based levels 1-4,
                                 the residual documented on
                                 _END_TO_END_BOUNDS, plus level 6 at 14.9 /
                                 4.05 ulps of its entry value.

    THESE NUMBERS ARE THE PRODUCTION ADAPTER'S, FIELD FOR FIELD.  Once
    :func:`_run_mp28_column` was given WRF's :3193 density, this file's
    direct-launcher driver reproduces
    ``tests/test_thompson_aerosol_adapter.py::_run_g3``'s row for
    aero-reduces-to-classic exactly -- qr 7.8129e-05 at level 1, nr 4.8317e-05
    at level 1, level 6 at 3.1550e-03/3.1552e-03 -- which is the strongest
    available statement that the two drivers are the same computation.
    """
    _require_device()
    before, after, surface, got = _run_mp28_column(scenario)

    excluded = list(_WRF_QR_THRESHOLD_LEVELS.get(scenario, ()))
    bounds = _END_TO_END_BOUNDS[scenario]
    worst = {}
    for field in _END_TO_END_FIELDS:
        want = _oracle_column(after, field)
        keep = np.ones(want.size, bool)
        if field in ("qr", "nr_per_kg"):
            keep[excluded] = False
        measured = _field_max_rel(got[field][keep], want[keep])
        limit = bounds.get(field, _END_TO_END_DEFAULT_BOUND)
        worst[field] = (measured, limit)
    over = {name: value for name, value in worst.items()
            if value[0] > value[1]}
    assert not over, (
        f"{sorted(worst.items(), key=lambda item: -item[1][0])}\n"
        f"If qv/qi/effi are the fields over bound, see "
        f"test_device_saturation_fit_reproduces_the_fortran_horner_bitwise: "
        f"the FMA-contracted RSLF in thompson_aerosol_common.cuh flips WRF's "
        f"ssatw > eps gate and this composition inherits it.")

    for name in ("rainnc_mm", "snownc_mm", "graupelnc_mm"):
        want = float(surface[name])
        assert abs(got[name] - want) <= 2.0e-6 * max(abs(want), 1.0e-30), (
            name, got[name], want)

    # The held-out level is BOUNDED, not skipped, and in the units the
    # cancellation is carried in.  The old form asserted got == 0.0 there;
    # after the entry-density wiring mp=28 produces a real value and this
    # requires it to be non-zero AND inside 32 ulps of the entry value, which
    # is strictly more than the old assertion.
    for level in excluded:
        for key in ("qr", "nr_per_kg"):
            entry = float(_oracle_column(before, key)[level])
            want_value = float(_oracle_column(after, key)[level])
            mine = float(got[key][level])
            assert entry > 0.0 and want_value > 0.0, (key, entry, want_value)
            # it really is a near-total consumption, so the bound cannot be
            # reused for a level that merely disagrees
            assert (entry - want_value) / entry > 0.999, key
            assert mine > 0.0, (
                f"{key} at level {level} collapsed to zero; the port used to "
                "do that and no longer should")
            ulp = _entry_ulp(entry)
            assert abs(mine - want_value) <= _NEAR_CANCELLATION_ULPS * ulp, (
                f"{key} at level {level}: "
                f"{abs(mine - want_value) / ulp:.2f} ulp of the entry value "
                f"exceeds {_NEAR_CANCELLATION_ULPS}")
        assert 0.0 < float(_oracle_column(after, "qr")[level]) < 1.0e-9

    # non-vacuous: the call has to have actually done something
    assert not np.array_equal(got["qc"], _oracle_column(before, "qc"))
    assert not np.array_equal(got["nc_per_kg"],
                              _oracle_column(before, "nc_per_kg"))


@pytest.mark.parametrize("scenario", ["aero-reduces-to-classic"])
def test_this_files_driver_hands_rain_evaporation_wrfs_pre_condensation_density(
        scenario):
    """The fails-before half of the ``entry_density`` wiring, measured HERE.

    ``woof/core/microphysics_aerosol.py`` was given WRF's :3193 density by
    WP-12a and pins it with its own gate.  :func:`_run_mp28_column` in THIS
    file is a SECOND driver -- wave 2's direct-launcher sequence, which
    predates the adapter and which every other whole-call gate in this module
    runs through -- and it was still omitting the argument, so this file was
    measuring a pipeline the shipped model no longer has.  A test that only
    checked the adapter could not see that.

    WHAT WRF DOES.  module_mp_thompson.F:3193 diagnoses rho(k); :3242-3243
    forms the working rain mass and number from it and :3384-3388 freezes
    ilamr/N0_r from those; :3490 OVERWRITES rho(k) inside the condensation
    loop and :3505-3520's orho/rhof/vsc2/rvs read the NEW one.  ``prv_rev`` is
    therefore proportional to the PRE-condensation density while everything
    around it scales with the post-condensation one, so a driver carrying only
    the second scales prv_rev and pnr_rev by exactly ``rho_post/rho_pre``.

    MEASURED HERE, 0-based level 5 (entry temperature 274.125 K, entry cloud
    water 2.6186e-04 kg/kg, all of which evaporates inside the step):

        without entry_density   qr 1.9151e-03   nr 1.9217e-03
        with    entry_density   qr 1.7877e-07   nr 5.7005e-06

    and the ratio of the two evaporated masses is the density ratio, which is
    the attribution rather than an unexplained epsilon.  RAINNC on this column
    goes from 1.1592e-06 off WRF to BIT-EXACT.
    """
    _require_device()
    import woof.core.thompson_aerosol_sat as sat_module

    level = 5
    real = sat_module.launch_aerosol_rain_evaporation

    def run(*, suppress):
        if suppress:
            def without(*args, **kwargs):
                kwargs.pop("entry_density", None)
                return real(*args, **kwargs)
            sat_module.launch_aerosol_rain_evaporation = without
        try:
            return _run_mp28_column(scenario)
        finally:
            sat_module.launch_aerosol_rain_evaporation = real

    before, after, surface, fixed = run(suppress=False)
    _, _, _, broken = run(suppress=True)

    want_qr = float(_oracle_column(after, "qr")[level])
    want_nr = float(_oracle_column(after, "nr_per_kg")[level])
    entry_qr = float(_oracle_column(before, "qr")[level])
    entry_nr = float(_oracle_column(before, "nr_per_kg")[level])

    def relative(got, want):
        return abs(float(got) - want) / abs(want)

    # 1. The argument really is being passed: dropping it moves the answer.
    assert relative(broken["qr"][level], want_qr) > 1.0e-3
    assert relative(broken["nr_per_kg"][level], want_nr) > 1.0e-3
    # 2. ...and passing it closes the gap by three decades on qr.
    assert relative(fixed["qr"][level], want_qr) < 1.0e-6
    assert relative(fixed["nr_per_kg"][level], want_nr) < 1.0e-5
    assert relative(broken["qr"][level], want_qr) > 1000.0 * relative(
        fixed["qr"][level], want_qr)
    # 3. THE ATTRIBUTION: the broken run's excess evaporation is the ratio of
    #    the two densities WRF keeps in play, not an unexplained epsilon.
    for key, entry, want in (("qr", entry_qr, want_qr),
                             ("nr_per_kg", entry_nr, want_nr)):
        evaporated_ratio = ((entry - float(broken[key][level]))
                            / (entry - want))
        assert 1.0015 < evaporated_ratio < 1.0025, (key, evaporated_ratio)
    # 4. And the surface accumulation this file also gates: bit-exact with the
    #    argument, not without it.
    assert fixed["rainnc_mm"] == float(surface["rainnc_mm"])
    assert broken["rainnc_mm"] != float(surface["rainnc_mm"])
    # 5. The bound this file publishes is only earned WITH the argument: the
    #    suppressed run blows through it, so _END_TO_END_BOUNDS cannot be
    #    quietly re-widened to cover a dropped argument again.
    limit = _END_TO_END_BOUNDS[scenario]["qr"]
    excluded = list(_WRF_QR_THRESHOLD_LEVELS.get(scenario, ()))
    keep = np.ones(len(after), bool)
    keep[excluded] = False
    assert _field_max_rel(fixed["qr"][keep],
                          _oracle_column(after, "qr")[keep]) <= limit
    assert _field_max_rel(broken["qr"][keep],
                          _oracle_column(after, "qr")[keep]) > limit


def _run_mp8_column(scenario):
    """The frozen mp=8 pipeline on the same entry column, for the bridge.

    A transcription of ``microphysics._apply_thompson``'s launcher sequence
    (microphysics.py:410-603) without its theta bookkeeping.  Every launcher
    is imported from woof.core.thompson and called with mp=8's own argument
    tuple; nothing here is aerosol-aware.
    """
    from woof.core.thompson import (
        launch_classic_graupel_number_finalize,
        launch_classic_graupel_number_init,
        launch_cloud_saturation_adjust,
        launch_cloud_sedimentation,
        launch_effective_radius,
        launch_final_phase_cleanup,
        launch_frozen_vapor_network_from_owner,
        launch_graupel_fallout_column_mask,
        launch_graupel_sedimentation,
        launch_hydrometeor_column_mask,
        launch_ice_sedimentation,
        launch_rain_evaporation,
        launch_rain_sedimentation,
        launch_snow_sedimentation,
        launch_warm_frozen_source_network_from_owner,
    )
    from woof.core.thompson_runtime import load_classic_device_tables
    from woof.physics_compat import thompson_table_root

    before, after, surface = _oracle_aero_case(scenario)
    dt = float(surface["dt_s"])
    shape = (len(before), 1, 1)
    owner = load_classic_device_tables(thompson_table_root())

    def volume(field):
        return _column(_oracle_column(before, field))

    def scratch():
        return cp.zeros(shape, dtype=cp.float32)

    qv, qc, qr = volume("qv"), volume("qc"), volume("qr")
    qi, qs, qg = volume("qi"), volume("qs"), volume("qg")
    ni, nr = volume("ni_per_kg"), volume("nr_per_kg")
    temperature, pressure = volume("temp_k"), volume("p_pa")
    dz, w = volume("dz_m"), volume("w_m_s")

    frozen_density, frozen_temperature = scratch(), scratch()
    rain_density = scratch()
    snow_melt_marker, graupel_melt_marker = scratch(), scratch()
    snow_velocity_boost, graupel_number_shadow = scratch(), scratch()
    effc, effi, effs = scratch(), scratch(), scratch()
    rainnc = cp.zeros((1, 1), dtype=cp.float32)
    rainncv = cp.zeros((1, 1), dtype=cp.float32)
    snownc = cp.zeros((1, 1), dtype=cp.float32)
    snowncv = cp.zeros((1, 1), dtype=cp.float32)
    graupelnc = cp.zeros((1, 1), dtype=cp.float32)
    graupelncv = cp.zeros((1, 1), dtype=cp.float32)
    sr = cp.zeros((1, 1), dtype=cp.float32)

    frozen_temperature[...] = (qg > R1).astype(cp.float32)
    graupel_melt_marker[...] = (
        temperature >= np.float32(273.15)).astype(cp.float32)
    launch_classic_graupel_number_init(
        qg, temperature, pressure, qv, graupel_number_shadow)
    launch_frozen_vapor_network_from_owner(
        qi, ni, qs, qg, qr, nr, temperature, pressure, qv, owner, dt, qc=qc,
        graupel_number_shadow=graupel_number_shadow,
        snow_velocity_boost=snow_velocity_boost)
    launch_warm_frozen_source_network_from_owner(
        qc, qr, nr, qs, qg, graupel_number_shadow, graupel_melt_marker,
        snow_melt_marker, temperature, pressure, qv, owner, dt)
    launch_hydrometeor_column_mask(qr, rainncv)
    launch_hydrometeor_column_mask(qc, snowncv)
    launch_graupel_fallout_column_mask(frozen_temperature, qg, sr)
    launch_cloud_saturation_adjust(
        temperature, pressure, qv, qc,
        reference_density=frozen_density,
        reference_temperature=frozen_temperature)
    launch_rain_evaporation(
        qr, nr, temperature, pressure, qv, dt,
        reference_density=rain_density,
        graupel_melt_marker=graupel_melt_marker)
    launch_cloud_sedimentation(
        qc, temperature, pressure, qv, w, dz, dt,
        reference_density=frozen_density,
        rain_active_columns=rainncv, cloud_active_columns=snowncv)
    launch_ice_sedimentation(
        qi, ni, temperature, pressure, qv, dz,
        rainnc, rainncv, snownc, snowncv, dt,
        reference_density=frozen_density)
    launch_snow_sedimentation(
        qs, temperature, pressure, qv, dz, rainnc, rainncv, snownc, snowncv,
        dt, reference_density=frozen_density,
        reference_temperature=frozen_temperature,
        snow_melt_marker=snow_melt_marker, melt_rain_qr=qr, melt_rain_nr=nr,
        velocity_boost=snow_velocity_boost, accumulate_surface=True)
    launch_graupel_sedimentation(
        qg, temperature, pressure, qv, dz, rainnc, rainncv, graupelnc,
        graupelncv, dt, reference_density=frozen_density, active_columns=sr,
        graupel_number_shadow=graupel_number_shadow, accumulate_surface=True)
    launch_rain_sedimentation(
        qr, nr, temperature, pressure, qv, dz, rainnc, rainncv, dt,
        reference_density=rain_density, accumulate_surface=True)
    launch_final_phase_cleanup(qc, qi, ni, temperature, pressure, qv)
    launch_classic_graupel_number_finalize(
        qg, temperature, pressure, qv, graupel_number_shadow)
    launch_effective_radius(
        temperature, pressure, qv, qc, qi, ni, qs, effc, effi, effs)
    cp.cuda.Stream.null.synchronize()

    result = {"qv": qv, "qc": qc, "qr": qr, "qi": qi, "qs": qs, "qg": qg,
              "ni_per_kg": ni, "nr_per_kg": nr, "temp_k": temperature}
    result = {key: value.get().ravel() for key, value in result.items()}
    result["rainnc_mm"] = float(rainnc.get()[0, 0])
    return result


