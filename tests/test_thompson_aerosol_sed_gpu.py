#: module_mp_thompson.F:185.  The gate that decides whether the condensation
#: block at :3401 runs at all.
WRF_EPS = 1.0e-15

#: RSLF coefficients, module_mp_thompson.F:5388-5396.
_RSLF_C = (0.611583699e3, 0.444606896e2, 0.143177157e1, 0.264224321e-1,
           0.299291081e-3, 0.203154182e-5, 0.702620698e-8, 0.379534310e-11,
           -0.321582393e-13)


def _reference_rslf(pressure, temperature):
    """module_mp_thompson.F:5383-5413 in float32 with NO fused multiply-add.

    build_aero.sh compiles the oracle with plain ``gfortran -O2`` on baseline
    x86-64, which has no FMA instruction, so WRF's Horner chain is evaluated
    with one rounding per operation.  This transcription reproduces the
    Fortran BITWISE on every level of the committed fixtures; it is the
    reference the device fit is measured against.
    """
    f32 = np.float32
    coefficients = [f32(value) for value in _RSLF_C]
    pressure = np.asarray(pressure, np.float32)
    temperature = np.asarray(temperature, np.float32)
    x = np.maximum(f32(-80.0), (temperature - f32(273.16)).astype(np.float32))
    esl = np.full(x.shape, coefficients[8], np.float32)
    for coefficient in reversed(coefficients[:8]):
        esl = (coefficient + (x * esl).astype(np.float32)).astype(np.float32)
    esl = np.minimum(esl, (pressure * f32(0.15)).astype(np.float32))
    return (f32(0.622) * esl / (pressure - esl).astype(np.float32)
            ).astype(np.float32)


