def test_every_column_of_a_tiled_domain_gets_the_single_column_answer():
    """One thread per column, so the (j, i) decomposition has to be right.

    The whole oracle gate runs on (nz, 1, 1) columns, where an ``nx``/``ny``
    indexing mistake is invisible.  This replicates the same column across a
    7 x 5 tile -- more than one 32-wide block's worth of rows is not needed,
    but a non-square tile catches a transposed ``j``/``i``.
    """
    _require_device()
    table = SED_TABLES["aero-nc-sed"]
    reference = _run_sediment(table)
    nz, ny, nx = table["dzq"].size, 7, 5

    def tile(values):
        host = np.ascontiguousarray(
            np.repeat(np.asarray(values, np.float32).reshape(-1, 1, 1),
                      ny * nx, axis=1).reshape(nz, ny, nx))
        return cp.asarray(host)

    qc_in = (table["qc1d"] + table["qcten_pre"] * np.float32(DT)
             ).astype(np.float32)
    qc = tile(qc_in)
    ncten = tile(table["ncten_pre"])
    launch_aa_cloud_sedimentation(
        qc, tile(table["nc1d"]), ncten,
        tile(table["temp"]), tile(table["p1d"]), tile(table["qv"]),
        tile(table["w1d"]), tile(table["dzq"]), DT,
        reference_density=tile(table["rho_pre"]))
    cp.cuda.Stream.null.synchronize()

    got_qc = qc.get()
    got_ncten = ncten.get()
    for j in range(ny):
        for i in range(nx):
            assert np.array_equal(got_qc[:, j, i], reference["qc"]), (j, i)
            assert np.array_equal(got_ncten[:, j, i],
                                  reference["ncten"]), (j, i)


