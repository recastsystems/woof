_SEED_ZEROED_BY_WRF = {"qc1d": "qc", "nc1d": "qc", "ni1d": "qi"}


def test_embedded_seed_matches_the_committed_fixture():
    """Tie EVERY embedded vector back to the committed oracle CSV it names.

    The pressure, layer depth, vertical velocity and temperature are pure
    entry state and must equal the committed ``*-column.csv`` "before" rows
    exactly.  If they ever stop matching, the embedded table has drifted away
    from the fixture it claims to describe.

    ``nc1d`` matches only where the column is cloudy, and that is a LOAD-
    BEARING FINDING, not a fudge.  module_mp_thompson.F:1844-1846 rewrites the
    caller's own array::

        else                       ! qc1d(k) .le. R1
           qc1d(k) = 0.0
           nc1d(k) = 0.0

    and :1870-1871 does the same to ``ni1d`` for ``qi1d <= R1``.  So the entry
    droplet and ice numbers every later block reads -- including this
    package's ``cloud_number_entry`` and ``ice_number_entry`` -- are the state
    arrays ZEROED wherever the corresponding condensate was absent at call
    entry, not the raw state arrays.  Handing in raw ``state.nc`` would give a
    non-zero working droplet number in air that has no droplets.

    WP-14 WIDENED THIS FROM ONE TABLE TO ALL FIVE.  It used to tie only
    ``aero-nc-sed``.  The other four -- ``wp08-melt``, ``wp08-freeze``,
    ``aero-reduces-to-classic`` and ``wp08-nusweep`` -- are now committed
    fixtures in the same deck (ids 119-122), so the tie is available and its
    absence was the gap.  That matters more than it looks: these tables are
    the INPUT half of every G2 gate in this file (``_run_sediment`` and
    ``_run_cleanup`` build the kernel's arguments out of them), so a table
    that has drifted fails nothing -- it quietly measures the right kernel on
    the wrong column, and when the deck is next regenerated the failure is
    indistinguishable from a physics regression.

    WHAT IS AND IS NOT COMPARED, and why the exclusions are not slack.
    :data:`_SEED_ENTRY_COLUMNS` names, per table, only the columns that are
    PURE ENTRY STATE.  ``temp`` and ``qv`` in the phase-cleanup tables are
    WRF's POST-source-network values -- :3186-3212 refreshes the temperature
    and :3490 the density inside the condensation loop -- so they cannot
    equal the fixture's ``before`` rows and are deliberately absent from the
    inventory rather than compared loosely.  Every column that IS listed is
    required to be BIT-EQUAL, with no tolerance at all.

    MEASURED: all five tables, every listed column, bit-equal.
    """
    from pathlib import Path

    import woof

    root = Path(woof.__file__).parent / "data" / "thompson" / "oracle-aero"
    tables = dict(SED_TABLES)
    tables.update(CLEAN_TABLES)
    assert set(tables) == set(_SEED_ENTRY_COLUMNS), (
        "an embedded table appeared or vanished without its entry-column "
        f"inventory: {sorted(set(tables) ^ set(_SEED_ENTRY_COLUMNS))}")

    checked = 0
    for scenario, table in sorted(tables.items()):
        path = root / f"{scenario}-column.csv"
        if not path.exists():  # pragma: no cover
            pytest.skip(f"missing aerosol oracle fixture {path}")
        rows = [line.split(",") for line in
                path.read_text(encoding="utf-8").strip().splitlines()]
        header = [name.strip() for name in rows[0]]
        before = [row for row in rows[1:] if row[0].strip() == "before"]

        def column(name, _header=header, _before=before):
            index = _header.index(name)
            return np.array([np.float32(row[index]) for row in _before],
                            dtype=np.float32)

        for name in _SEED_ENTRY_COLUMNS[scenario]:
            fixture = column(_SEED_FIXTURE_COLUMN[name])
            gate = _SEED_ZEROED_BY_WRF.get(name)
            if gate is not None:
                fixture = np.where(column(gate) > R1, fixture,
                                   np.float32(0.0)).astype(np.float32)
            assert np.array_equal(table[name], fixture), (
                f"{scenario}: the embedded {name} column no longer equals "
                f"{path.name}'s own before rows; the table describes a "
                "different column than the fixture it is named for.  "
                f"Differing 0-based levels: "
                f"{np.nonzero(table[name] != fixture)[0].tolist()}")
            checked += 1

        # The zeroing rule is only meaningful where the column has both
        # kinds of level; aero-nc-sed is the one that proves it does.
        if scenario == "aero-nc-sed":
            cloudy = column("qc") > R1
            assert cloudy.any() and not cloudy.all(), (
                "the fixture must have both cloudy and cloud-free levels for "
                "the :1844-1846 zeroing assertion to mean anything")

    # 7 + 7 + 7 + 5 + 5 entry columns over the five tables.
    assert checked == 31, checked


