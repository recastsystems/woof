def test_cloud_fallout_is_a_single_pass_with_no_onstep_factor():
    """Rain/ice/snow/graupel divide by onstep(1..4); cloud does not (:3829).

    Copying one of those launchers as a template and keeping its substep loop
    is a silent rate error, so this reconstructs the ONE-pass divergence
    explicitly from the kernel's own vtck/rc diagnostics and requires the
    applied tendency to equal it exactly -- any 1/nstep scaling fails.
    """
    _require_device()
    table = SED_TABLES["aero-nc-sed"]
    # 1 m layers make the fallout Courant number enormous; a substepping
    # implementation would visibly disagree here and nowhere else.
    got = _run_sediment(table, dz=1.0)
    nz = table["dzq"].size

    density = (np.float32(0.622) * table["p1d"]
               / (np.float32(287.04) * table["temp"]
                  * (np.maximum(np.float32(1.0e-10), table["qv"])
                     + np.float32(0.622)))).astype(np.float32)
    mass_flux = (got["mass_velocity"] * got["cloud_mass"]).astype(np.float32)

    sediment_top = 0
    height = np.float32(0.0)
    for k in range(nz - 1):
        if got["cloud_mass"][k] > np.float32(1.0e-6):
            sediment_top = k
        height = np.float32(height + np.float32(1.0))
        if height > np.float32(500.0):
            break

    odzq = np.float32(1.0) / np.float32(1.0)
    expected_qc = got["qc_in"].copy()
    for k in range(sediment_top, -1, -1):
        orho = np.float32(1.0) / density[k]
        divergence = np.float32(mass_flux[k + 1] - mass_flux[k])
        tendency = np.float32(np.float32(divergence * odzq) * orho)
        value = np.float32(expected_qc[k]
                           + np.float32(tendency * np.float32(DT)))
        expected_qc[k] = np.float32(0.0) if value <= R1 else value
    expected_qc = np.where(expected_qc <= R1, np.float32(0.0), expected_qc)
