def _table(rows, columns):
    """Return a name -> float32 column mapping for one embedded table."""
    array = np.asarray(rows, dtype=np.float64)
    assert array.shape[1] == len(columns), (array.shape, len(columns))
    return {name: array[:, i].astype(np.float32)
            for i, name in enumerate(columns)}


