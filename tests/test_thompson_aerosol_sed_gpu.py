def _bridge_pair(table, *, dz, dt):
    """Run the mp=28 and the frozen mp=8 cloud fallout on one identical column.

    ``nc`` is seeded at exactly ``Nt_c/rho`` so the working droplet number is
    the constant mp=8 hardcodes and ``nu_c`` is 12, the shape mp=8 froze.
    """
    nz = table["dzq"].size
    depth = np.full(nz, dz, np.float32)
    nc_entry = (np.float32(100.0e6) / table["rho_pre"]).astype(np.float32)
    qc_in = (table["qc1d"] + table["qcten_pre"] * np.float32(dt)
             ).astype(np.float32)

    diagnostics = {name: cp.zeros((nz, 1, 1), dtype=cp.float32)
                   for name in DIAGNOSTIC_FIELDS}
    aerosol_qc = _column(qc_in)
    launch_aa_cloud_sedimentation(
        aerosol_qc, _column(nc_entry), _column(np.zeros(nz, np.float32)),
        _column(table["temp"]), _column(table["p1d"]), _column(table["qv"]),
        _column(table["w1d"]), _column(depth), dt,
        reference_density=_column(table["rho_pre"]),
        diagnostics=diagnostics)

    classic_qc = _column(qc_in)
    classic_thompson.launch_cloud_sedimentation(
        classic_qc, _column(table["temp"]), _column(table["p1d"]),
        _column(table["qv"]), _column(table["w1d"]), _column(depth),
        dt, reference_density=_column(table["rho_pre"]))
    cp.cuda.Stream.null.synchronize()
    return (qc_in, aerosol_qc.get().ravel(), classic_qc.get().ravel(),
            {name: diagnostics[name].get().ravel()
             for name in DIAGNOSTIC_FIELDS})


