# ---------------------------------------------------------------------------
# SHARED-HELPER DE-DUPLICATION.
# ---------------------------------------------------------------------------
#
# thompson_aerosol_sed.cu used to carry its own thompson_aa_bound_ice_number
# whose only textual difference from the header's was spelling am_i as the
# product `3.1415926536f*890.0f/6.0f` instead of THOMPSON_AA_AM_I.  Two
# definitions of one helper in two cupy.RawModule translation units is exactly
# how the halves of a scheme drift apart, because nvrtc never diffs them.  The
# copy is gone; these three tests are what stop it coming back and prove the
# removal moved nothing.

_KERNEL_DIR = (Path(__file__).parents[1] / "woof" / "core" / "kernels")

#: Helpers thompson_aerosol_common.cuh publishes.  A .cu file that defines any
#: of these has forked the scheme.
_PUBLISHED_SHARED_HELPERS = (
    "thompson_aa_entry_rain_distribution",
    "thompson_aa_bound_rain_number",
    "thompson_aa_bound_ice_number",
)


def test_sed_defines_no_published_shared_helper():
    """The kernel must CALL the header's helpers, never redefine them.

    A redefinition with an identical body is an nvrtc error and would be
    caught by any GPU test.  A redefinition under a *different* name would
    not be, and neither would one guarded by #ifndef -- so this scans the
    source for a definition rather than relying on the compiler.
    """
    source = (_KERNEL_DIR / "thompson_aerosol_sed.cu").read_text(
        encoding="utf-8")
    header = (_KERNEL_DIR / "thompson_aerosol_common.cuh").read_text(
        encoding="utf-8")
    for helper in _PUBLISHED_SHARED_HELPERS:
        definition = re.compile(
            r"^__device__[^\n]*\b" + helper + r"\s*\(", re.MULTILINE)
        assert definition.search(header), (
            f"{helper} is not defined in thompson_aerosol_common.cuh; the "
            f"published-signature contract has changed")
        assert not definition.search(source), (
            f"thompson_aerosol_sed.cu redefines {helper}; delete the local "
            f"copy and call the header's")
    # ...and it must still actually use the one it does not define.
    assert "thompson_aa_bound_ice_number(" in source


def test_am_i_product_form_is_bit_identical_to_the_header_constant():
    """THOMPSON_AA_AM_I == the `PI*rho_i/6` product the deleted copy spelled.

    module_mp_thompson.F:137 is ``am_i = PI*rho_i/6.``  The deleted local copy
    evaluated that product in float32; the header stores the folded literal.
    If those two ever stop agreeing bitwise the de-duplication silently
    changed the ice-number bound, so pin both, plus am_r for the rain bound
    the same header publishes.
    """
    f32 = np.float32
    header = (_KERNEL_DIR / "thompson_aerosol_common.cuh").read_text(
        encoding="utf-8")
    literals = dict(re.findall(
        r"#define\s+(THOMPSON_AA_AM_[RI])\s+(\S+)f\b", header))
    assert set(literals) == {"THOMPSON_AA_AM_R", "THOMPSON_AA_AM_I"}, literals
    pi = f32(3.1415926536)
    for name, density in (("THOMPSON_AA_AM_I", 890.0),
                          ("THOMPSON_AA_AM_R", 1000.0)):
        product = f32(f32(pi * f32(density)) / f32(6.0))
        folded = f32(literals[name])
        assert product.tobytes() == folded.tobytes(), (
            name, float(product), float(folded))


def _reference_bound_ice_number(ice_mass, density, ice_number_per_kg):
    """module_mp_thompson.F:4029-4039, transcribed independently in NumPy.

    Deliberately written from the Fortran, not from the CUDA: it is the
    cross-check that makes "the two definitions were bit-identical in value"
    a measurement rather than an assertion about two texts.
    """
    f32 = np.float32
    if ice_mass <= f32(1.0e-12):
        return f32(0.0)
    am_i = f32(f32(f32(3.1415926536) * f32(890.0)) / f32(6.0))
    number = max(f32(1.0e-6), f32(ice_number_per_kg * density))
    lam = np.float64(f32(
        f32(f32(f32(am_i * f32(6.0)) * number) / ice_mass) ** f32(1.0 / 3.0)))
    diameter = f32(4.0 / lam)
    if diameter < f32(5.0e-6):
        lam = 4.0 / 5.0e-6
        number = min(f32(999.0e3), f32(
            f32(f32(f32(1.0 / 6.0) * ice_mass) / am_i) * f32(lam ** 3)))
    elif diameter > f32(300.0e-6):
        lam = 4.0 / 300.0e-6
        number = f32(
            f32(f32(f32(1.0 / 6.0) * ice_mass) / am_i) * f32(lam ** 3))
    return f32(min(number, f32(999.0e3)) / density)


def test_bound_ice_number_matches_an_independent_wrf_transcription():
    """Both size-clamp branches and the pass-through, value by value.

    Reaches the kernel through the cleanup launcher's melt-free, freeze-free
    path (temp between HGFR and T_0), which leaves :4025-4039 as the only
    thing that runs.  The ladder spans ice contents from 1e-11 to 1e-2 kg/m3
    against numbers from 1e2 to 1e7 /kg so that the D < 5 um clamp, the
    D > 300 um clamp, the 999e3 ceiling and the untouched middle all fire.
    """
    _require_device()
    f32 = np.float32
    masses = [1.0e-11, 1.0e-9, 1.0e-7, 1.0e-6, 1.0e-5, 1.0e-4, 1.0e-3, 1.0e-2]
    numbers = [1.0e2, 1.0e3, 1.0e4, 1.0e5, 1.0e6, 1.0e7]
    pressure = f32(90000.0)
    temperature = f32(260.0)             # HGFR < T < T_0: no melt, no freeze
    qv = f32(1.0e-3)
    density = f32(f32(0.622) * pressure
                  / f32(f32(287.04) * temperature * f32(qv + f32(0.622))))

    qi_host, ni_host = [], []
    for mass in masses:
        for number in numbers:
            qi_host.append(f32(mass) / density)
            ni_host.append(f32(number))
    nz = len(qi_host)
    zeros = np.zeros(nz, np.float32)
    qi = _column(qi_host)
    ni = _column(ni_host)
    launch_aa_final_phase_cleanup(
        _column(zeros), qi, ni,
        _column(np.full(nz, temperature, np.float32)),
        _column(zeros), _column(zeros), _column(zeros),
        _column(np.full(nz, pressure, np.float32)),
        _column(np.full(nz, qv, np.float32)), DT)
    cp.cuda.Stream.null.synchronize()
    got = ni.get().ravel()

    want = np.asarray(
        [_reference_bound_ice_number(f32(q * density), density, f32(n))
         for q, n in zip(qi_host, ni_host)], dtype=np.float32)
    assert np.array_equal(got, want), _max_rel(got, want)
    # The ladder has to actually exercise all three outcomes.
    entry = np.asarray(ni_host, np.float32)
    assert (want > entry).any() and (want < entry).any()
    assert np.isclose(want.max() * density, 999.0e3, rtol=1.0e-6)


# ---------------------------------------------------------------------------
# NUMBER/MASS CONSISTENCY -- the conservation gate for a genuinely new
# operator.
# ---------------------------------------------------------------------------
#
# Classic Thompson has NO cloud-water number flux at all, so nothing in the
# mp=8 evidence base constrains vtnck.  If the number channel silently reused
# the mass fall speed -- the obvious copy-paste -- every bound would hold,
# every budget would still "close" against its own fluxes, and the scheme
# would simply drift the droplet number with no error visible anywhere.  The
# tests below close that hole three ways, none of them relying on a fixture:
#
#   1. an EXACT analytic identity between the two fall speeds, from WRF's own
#      gamma definitions;
#   2. a per-level flux-divergence identity reconstructed from the kernel's
#      diagnostics, for BOTH channels, which catches a wrong odzq/orho/dt or a
#      stray onstep factor in one channel only;
#   3. a synthetic uniform slab in which a copied velocity would leave the
#      mean droplet mass exactly unchanged, and the correct kernel must not.

#: module_mp_thompson.F:89 Nt_c_max, :183-184 R1/R2, :164 bv_c, :163 av_c.
NT_C_MAX = np.float32(1999.0e6)
NC_FLOOR = np.float32(2.0)
R2 = np.float32(1.0e-6)


def _wrf_nu_c(nc_m3):
    """:2170 / :3654 -- MIN(15, NINT(1000.E6/nc) + 2), as int."""
    value = np.floor(np.float64(1.0e9) / np.asarray(nc_m3, np.float64) + 0.5)
    return np.minimum(15, value.astype(np.int64) + 2)


def _gamma_speed_ratio(nu_c):
    """vtck / vtnck from :3661-3663, in closed form.

    module_mp_thompson.F:673-684 with bm_r = 3 (:129) and bv_c = 2 (:164):

        ccg(5,n)*ocg2(n) = WGAMMA(n+6)/WGAMMA(n+4) = (n+5)(n+4)
        ccg(4,n)*ocg1(n) = WGAMMA(n+3)/WGAMMA(n+1) = (n+2)(n+1)

    Both are exact integers; WRF's REAL(4) WGAMMA series reproduces them to
    about 2e-6, which is where the tolerance below comes from -- not from any
    slack in the physics.  At n = 12 they are 272 and 182, which is why mp=8
    can fuse ``av_c*272.0f`` for the mass and has no number counterpart at
    all.
    """
    n = np.asarray(nu_c, np.float64)
    return ((n + 5.0) * (n + 4.0)) / ((n + 2.0) * (n + 1.0))


def _working_cloud_number(table, dt):
    """:3486 -- MAX(2, MIN((nc1d + ncten*DT)*rho, Nt_c_max)), on the HELD rho.

    This is the pre-fallout droplet number the kernel builds sed_n from; the
    diagnostic exports the POST-fallout value, so the host has to rebuild it.
    """
    f32 = np.float32
    value = (table["nc1d"] + table["ncten_pre"] * f32(dt)).astype(np.float32)
    value = (value * table["rho_pre"]).astype(np.float32)
    return np.maximum(NC_FLOOR, np.minimum(value, NT_C_MAX)).astype(np.float32)


def _column_density(table):
    """The kernel's per-level rho, from the CURRENT temperature/pressure/qv."""
    f32 = np.float32
    qvk = np.maximum(f32(1.0e-10), table["qv"]).astype(np.float32)
    return (f32(0.622) * table["p1d"]
            / (f32(287.04) * table["temp"] * (qvk + f32(0.622)))
            ).astype(np.float32)


def _sediment_top(cloud_mass, dz):
    """:3646-3652, reproduced exactly, including the kte-1 loop bound."""
    f32 = np.float32
    top = 0
    height = f32(0.0)
    for k in range(cloud_mass.size - 1):
        if cloud_mass[k] > R2:
            top = k
        height = f32(height + dz[k])
        if height > f32(500.0):
            break
    return top


def test_droplet_number_falls_at_the_exact_wrf_gamma_ratio_to_the_mass():
    """vtck/vtnck == (n+5)(n+4)/((n+2)(n+1)) at every reachable nu_c.

    This is the single strongest statement available about the number
    channel: it is an identity, not a measurement, and it fails immediately
    for any implementation that reuses the mass gamma columns, shifts the
    ccg row index, or drops ocg1 for ocg2.  A copied mass velocity gives 1.0
    against true values from 1.397 (n=15) to 2.8 (n=3).
    """
    _require_device()
    table = SED_TABLES["wp08-nusweep"]
    got = _run_sediment(table)
    nc_pre = _working_cloud_number(table, DT)
    nu_c = _wrf_nu_c(nc_pre)

    live = got["number_velocity"] > 0.0
    assert live.sum() >= 20
    assert set(nu_c[live].tolist()) == set(range(3, 16)), (
        "the nu_c sweep no longer covers every reachable droplet shape")

    ratio = (got["mass_velocity"][live].astype(np.float64)
             / got["number_velocity"][live].astype(np.float64))
    want = _gamma_speed_ratio(nu_c[live])
    assert _max_rel(ratio, want) <= 5.0e-6, sorted(
        zip(nu_c[live].tolist(), ratio.tolist(), want.tolist()))
    # non-vacuous: a copied mass velocity would read 1.0 everywhere
    assert ratio.min() > 1.39 and ratio.max() > 2.7


def test_both_channels_apply_the_same_single_pass_flux_divergence():
    """Per level, for mass AND number: tendency == (F[k+1]-F[k])/dz/rho.

    Reconstructed from the kernel's own vtck/vtnck/rc diagnostics plus WRF's
    :3486 working droplet number, in float32 with the kernel's operation
    order, and required to be BIT-EQUAL.  A 1/nstep factor, a swapped
    density, or a dt/dz mix-up in either channel alone fails here even though
    every value stays finite and bounded.
    """
    _require_device()
    f32 = np.float32
    for name, table in sorted(SED_TABLES.items()):
        got = _run_sediment(table)
        density = _column_density(table)
        nc_pre = _working_cloud_number(table, DT)
        rc_pre = got["cloud_mass"]
        mass_flux = (got["mass_velocity"] * rc_pre).astype(np.float32)
        number_flux = (got["number_velocity"] * nc_pre).astype(np.float32)
        top = _sediment_top(rc_pre, table["dzq"])

        want_ncten = table["ncten_pre"].astype(np.float32).copy()
        want_qcten = np.zeros(rc_pre.size, np.float32)
        for k in range(top, -1, -1):
            odzq = f32(f32(1.0) / table["dzq"][k])
            orho = f32(f32(1.0) / density[k])
            dmass = f32(mass_flux[k + 1] - mass_flux[k])
            dnumber = f32(number_flux[k + 1] - number_flux[k])
            want_qcten[k] = f32(f32(f32(dmass * odzq)) * orho)
            want_ncten[k] = f32(want_ncten[k]
                                + f32(f32(dnumber * odzq) * orho))
        want_qc = (got["qc_in"] + want_qcten * f32(DT)).astype(np.float32)
        want_qc = np.where(want_qc <= R1, f32(0.0), want_qc)

        assert np.array_equal(got["ncten"], want_ncten), (name, "ncten")
        assert np.array_equal(got["qc"], want_qc), (name, "qc")
        # non-vacuous in BOTH channels
        assert (got["ncten"] != table["ncten_pre"]).any(), name
        assert (got["qc"] != got["qc_in"]).any(), name


def test_column_number_and_mass_budgets_close_against_the_two_end_fluxes():
    """Telescoping identity: sum(rho*dz*tendency) == F[top+1] - F[0].

    The only sink is F[0], the flux through the bottom of kts, and WRF
    DISCARDS it -- there is no pptrain term for cloud (:3823-3838).  So the
    budget must close against the fluxes and must NOT close against zero.
    Asserting both is what distinguishes "the operator is conservative" from
    "the operator quietly invented a surface reservoir".
    """
    _require_device()
    f32 = np.float32
    table = SED_TABLES["wp08-nusweep"]
    got = _run_sediment(table)
    density = _column_density(table)
    nc_pre = _working_cloud_number(table, DT)
    mass_flux = (got["mass_velocity"] * got["cloud_mass"]).astype(np.float32)
    number_flux = (got["number_velocity"] * nc_pre).astype(np.float32)
    top = _sediment_top(got["cloud_mass"], table["dzq"])

    dz = np.float64(table["dzq"][0])
    assert (table["dzq"] == table["dzq"][0]).all()
    qcten = ((got["qc"] - got["qc_in"]).astype(np.float64) / DT)
    ncten = (got["ncten"] - table["ncten_pre"]).astype(np.float64)

    for label, tendency, flux in (("mass", qcten, mass_flux),
                                  ("number", ncten, number_flux)):
        integrated = float(np.sum(tendency[:top + 1]
                                  * density[:top + 1].astype(np.float64) * dz))
        through = float(np.float64(flux[top + 1]) - np.float64(flux[0]))
        assert abs(integrated - through) <= 5.0e-6 * abs(through), (
            label, integrated, through)
        # F[top+1] is zero -- nothing falls in from above the fallout depth --
        # so the whole budget IS the discarded surface loss.
        assert flux[top + 1] == 0.0, label
        assert flux[0] > 0.0, label
        assert integrated < 0.0, label

    # The two ends are linked by the fall-speed ratio and the mean droplet
    # mass; a number channel sharing the mass velocity would make this 1.0.
    lost_ratio = (float(number_flux[0]) / float(nc_pre[0])) / (
        float(mass_flux[0]) / float(got["cloud_mass"][0]))
    nu_c = int(_wrf_nu_c(nc_pre[:1])[0])
    assert abs(lost_ratio - 1.0 / _gamma_speed_ratio(nu_c)) <= 5.0e-6
    assert lost_ratio < 0.72


def test_a_copied_mass_velocity_would_freeze_the_mean_droplet_mass():
    """The direct drift gate, on a synthetic slab, no fixture involved.

    Uniform rc, nc, rho and dz over the whole fallout depth make every
    interior flux divergence identically zero, so the ONLY level that changes
    is the top of the fallout depth, where nothing falls in from above.  There

        rc_new/rc_old = 1 - vtck *dt/dz
        nc_new/nc_old = 1 - vtnck*dt/dz

    so the fractional losses are in the exact ratio vtck/vtnck.  An
    implementation that fell the number at the MASS velocity would leave that
    ratio at 1.0 and the mean droplet mass rc/nc bit-unchanged -- bounded,
    stable, and wrong, with no budget anywhere to flag it.  MEASURED here:
    the mean droplet mass at the fallout top falls by about 24 percent in one
    10 s step, against 0 percent for the copied-velocity implementation.
    """
    _require_device()
    f32 = np.float32
    nz = 8
    dz = 1.0                # 1 m layers: one step moves a resolvable fraction
    step = 30.0
    table = {
        "dzq": np.full(nz, dz, np.float32),
        "w1d": np.zeros(nz, np.float32),
        "p1d": np.full(nz, 96923.3203125, np.float32),
        "temp": np.full(nz, 285.0, np.float32),
        "qv": np.full(nz, 9.043043479323387e-3, np.float32),
        "qc1d": np.full(nz, 5.0e-4, np.float32),
        "qcten_pre": np.zeros(nz, np.float32),
        "ncten_pre": np.zeros(nz, np.float32),
    }
    # HELD density == refreshed density, so the fractional loss is exactly
    # v*dt/dz and the identity below is about the two velocities alone.
    density = _column_density(table)[0]
    table["rho_pre"] = np.full(nz, density, np.float32)
    table["nc1d"] = np.full(nz, f32(100.0e6) / density, np.float32)
    got = _run_sediment(table, dt=step)
    nc_pre = _working_cloud_number(table, step)
    top = _sediment_top(got["cloud_mass"], table["dzq"])
    assert top == nz - 2, top          # the search excludes kte

    # uniform slab -> uniform velocities -> only the top level moves
    assert np.allclose(got["mass_velocity"][:top + 1],
                       got["mass_velocity"][0], rtol=0, atol=0)
    interior = np.arange(0, top)
    assert np.array_equal(got["qc"][interior], got["qc_in"][interior])
    assert np.array_equal(got["ncten"][interior],
                          table["ncten_pre"][interior])

    mass_fraction = 1.0 - float(got["qc"][top]) / float(got["qc_in"][top])
    number_fraction = 1.0 - (float(got["cloud_number"][top])
                             / float(nc_pre[top]))
    assert mass_fraction > 0.05 and number_fraction > 0.05
    nu_c = int(_wrf_nu_c(nc_pre[top:top + 1])[0])
    assert nu_c == 12                  # nc pinned at Nt_c: mp=8's shape
    assert abs(mass_fraction / number_fraction
               - _gamma_speed_ratio(nu_c)) <= 5.0e-6 * _gamma_speed_ratio(nu_c)

    # the drift statement itself
    mean_before = float(got["qc_in"][top] * density) / float(nc_pre[top])
    mean_after = float(got["qc"][top] * density) / float(
        got["cloud_number"][top])
    assert mean_after < mean_before
    assert (mean_before - mean_after) / mean_before > 0.30, (
        mean_before, mean_after)
    # ...and a copied mass velocity would leave it unchanged: the SAME
    # fractional loss would cancel out of rc/nc exactly.  The residual below
    # is float64 round-off in the host algebra, five orders of magnitude
    # smaller than the 30 percent shift the real kernel produces.
    copied = float(got["qc_in"][top] * density * (1.0 - mass_fraction)) / (
        float(nc_pre[top]) * (1.0 - mass_fraction))
    assert abs(copied - mean_before) <= 1.0e-6 * mean_before


