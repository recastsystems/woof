def test_bridge_two_ports_agree_where_aerosol_is_neutral_and_split_where_it_is_not():
    """The reduces-to-classic bridge, judged against WRF, not against mp=8.

    aero-reduces-to-classic seeds nc at essentially Nt_c -- ``nc*rho`` is
    BITWISE ``100.0e6f`` at all 24 levels and ``nu_c = MIN(15,
    NINT(1000.E6/nc) + 2) = 12`` everywhere, which is exactly the constant
    WOOF's frozen mp=8 kernels embed.  That is the whole point of the
    fixture: with the droplet number neutral, mp=28 must reduce to classic
    Thompson wherever the aerosol is not doing anything, and must NOT reduce
    to it where the aerosol IS the physics.  Both halves have to be asserted
    -- a port that agreed with mp=8 everywhere would have failed to implement
    the scheme, and one that agreed nowhere would have broken the shared
    warm-rain path.

    THE COMPARISON THAT DECIDES IS AGAINST THE ORACLE.  An earlier version of
    this test required ``qc`` to agree between the two PORTS to 1.0e-7 and
    measured 8.638125e-07.  Widening that would have been the wrong repair
    twice over: mp=8 is not this port's authority, and mp=28 is the CLOSER of
    the two ports to the one that is.  MEASURED on this tree, at 0-based
    level 2, the only level where the two ports differ at all:

        WRF   2.358461206e-04     (the committed fixture's after-state)
        mp=28 2.358460915e-04     2 float32 ulps BELOW WRF
        mp=8  2.358462953e-04    12 float32 ulps ABOVE WRF

    The ports STRADDLE WRF, so the 8.638125e-07 two-port split is exactly the
    sum of their two distances (2 + 12 = 14 ulps of 1.4551915e-11), and
    mp=28's own distance from WRF is 1.234018e-07 -- six times smaller than
    mp=8's 7.404107e-07 and 16x inside the port's 2e-6 gate.  mp=28
    reproduces WRF's qc BITWISE at the other 23 levels.

    WHERE THE SPLIT IS INTRODUCED, AND WHY IT IS BY DESIGN.  Bisecting the two
    pipelines launcher by launcher on this column puts the entire difference
    in ONE stage -- the saturation adjustment (mp=8's
    ``launch_cloud_saturation_adjust`` against mp=28's
    ``launch_aerosol_saturation_adjust``).  qc entering that stage is bitwise
    identical in both ports (6.460639415e-04) and no later stage moves it.
    The two kernels are allowed to differ because
    ``woof/core/kernels/thompson_aerosol_sat.cu:70-100`` records, against an
    instrumented copy of pristine WRF that dumps ``clap`` as a raw float32 bit
    pattern at module_mp_thompson.F:3408, that :3403-3408's Newton solve is
    bit-exact ONLY with the contraction-pinned Horner chain AND a
    double-precision ``exp`` rounded to float:

        plain chain + expf              24 / 24 levels differ, worst 5.42e-05
        pinned chain + double exp        0 / 24 levels differ  (BIT-EXACT)

    mp=8 uses the plain chain and ``expf``; mp=28 uses the pinned chain and
    the double ``exp``.  That is the port's ONE deliberate divergence from the
    frozen kernels, it is recorded in the shared header's "THE SHARED FITS"
    note, and this test is the end-to-end evidence that it moves mp=28 TOWARDS
    WRF rather than away from it.  Restoring consistency with mp=8 here would
    make this test fail, which is the intent.

    THE SECOND SPLIT, AND IT IS ALSO BY DESIGN.  Rain mass and number used to
    be BITWISE identical between the two ports; after ``entry_density`` was
    wired into :func:`_run_mp28_column` they part at 5 of the 24 levels and
    stay bitwise at the other 19.  That is the correct behaviour and it is
    WRF's, not a drift: :3242-3243 forms the working rain moments from the
    :3193 PRE-condensation density while :3505-3520 reads the :3490
    POST-condensation one, mp=28 carries both and the frozen mp=8 kernel
    carries only the second, so they can only differ where condensation moved
    the column.  MEASURED AFTER WP-13a, qr:

        level  WRF               mp=28                mp=8
          0    1.655745873e-04   8.79e-08 from WRF    1.14e-06 from WRF
          1    3.263167746e-04   0.00e+00 (BITWISE)   7.61e-05
          2    3.304239654e-04   0.00e+00 (BITWISE)   4.00e-05
          3    1.679385314e-04   8.67e-08             6.98e-05
          4    4.151419853e-05   0.00e+00 (BITWISE)   6.27e-05
          5    2.543626124e-06   1.79e-07             1.92e-03
          6    1.342641553e-10   3.16e-03             1.00e+00  (mp=8 -> 0)

    mp=28 is nearer to WRF at ALL SEVEN, and RAINNC on this column is
    BIT-EXACT for mp=28 (0.0019081949722021818) and 1.16e-06 off for mp=8.

    THE SPLIT WIDENED IN WP-13a AND THAT IS THE RESULT, NOT A DRIFT.  This
    test used to require the two ports to agree bitwise at >= 19 of the 24
    levels and to split at exactly [0, 1, 4, 5, 6].  They now split at SEVEN
    levels, [0..6], because restoring WRF's level-wise :3237-vs-:3568
    sedimentation density moved mp=28 off mp=8 at levels 2 and 3 as well --
    and moved it ONTO WRF: level 2 went from mp=8's 4.00e-05 to bit-exact and
    level 3 from 6.98e-05 to 8.67e-08.  The old docstring also recorded level
    1 as "the one place mp=8 is marginally nearer"; that is gone, mp=28 is
    bit-exact there now.  The count assertion below is therefore re-measured
    (>= 17), and the assertion that actually carries the claim -- mp=28 at
    least as near WRF as mp=8 at EVERY split level -- was tightened from
    "four of five" to "all of them".

    THE REST, MEASURED:
      * snow and graupel BIT-IDENTICAL between the ports;
      * cloud ice and ice number a factor of 25 apart at the three DeMott
        levels, where mp=28 is bit-exact against WRF and mp=8 is not;
      * below 235.16 K the ice mass reconverges to 4.2e-4 and the ice number
        to 3.2e-7, because homogeneous freezing needs no aerosol;
      * over the whole column mp=28 is nearer to WRF than mp=8 on qr, nr, qc,
        qi and ni, which is asserted field by field at the end.
    """
    _require_device()
    _, after, surface, aerosol = _run_mp28_column("aero-reduces-to-classic")
    classic = _run_mp8_column("aero-reduces-to-classic")

    def oracle(key):
        return _oracle_column(after, key).astype(np.float64)

    def distances(key):
        want = oracle(key)
        return (_field_max_rel(aerosol[key], want),
                _field_max_rel(classic[key], want))

    # 1. WHERE THE AEROSOL IS NEUTRAL the two ports must not have drifted:
    #    snow and graupel are untouched by the aerosol scheme and are bitwise
    #    equal, and rain is bitwise equal at every level the two densities
    #    coincide at.
    assert np.array_equal(aerosol["qs"], classic["qs"])
    assert np.array_equal(aerosol["qg"], classic["qg"])
    for key in ("qr", "nr_per_kg"):
        same = np.nonzero(np.asarray(aerosol[key], np.float32)
                          == np.asarray(classic[key], np.float32))[0]
        # Levels 7-23 carry no rain at all in either port, so this is the
        # "aerosol is neutral -> no drift" half of the claim.  It was >= 19
        # with {2, 3} required as well; WP-13a moved levels 2 and 3 onto WRF
        # and off mp=8, which the docstring records and 1b re-asserts as a
        # STRICTLY STRONGER ordering claim than the bitwise identity it
        # replaces.
        assert same.size >= 17, (key, same.tolist())
        assert set(same) >= set(range(7, 24)), (key, same.tolist())

    # 1b. WHERE WRF KEEPS TWO DENSITIES the ports MUST split, and mp=28 must
    #     be the one that matches WRF.  module_mp_thompson.F:3242-3243 forms
    #     the working rain moments from the :3193 (pre-condensation) density
    #     while :3505-3520 reads the :3490 (post-condensation) one; mp=28
    #     carries both and the frozen mp=8 kernel carries only the second, so
    #     they agree exactly where condensation did not move the column and
    #     part where it did.  This is the finding
    #     ``entry_density`` produced in _run_mp28_column, and it is asserted
    #     rather than tolerated.
    split_levels = sorted(np.nonzero(
        np.asarray(aerosol["qr"], np.float32)
        != np.asarray(classic["qr"], np.float32))[0].tolist())
    assert split_levels == [0, 1, 2, 3, 4, 5, 6], split_levels
    want_qr = oracle("qr")
    nearer = 0
    for level in split_levels:
        mine = abs(float(aerosol["qr"][level]) - want_qr[level])
        theirs = abs(float(classic["qr"][level]) - want_qr[level])
        nearer += int(mine < theirs)
    # TIGHTENED BY WP-13a from "at least four of five" to ALL OF THEM.  Every
    # level the two ports disagree at is a level mp=28 is strictly nearer WRF
    # on; there is no longer any level where mp=8 wins.
    assert nearer == len(split_levels), (
        f"mp=28 is nearer to WRF at only {nearer} of {len(split_levels)} "
        "split levels; the two-density wiring is supposed to move it TOWARDS "
        "the oracle")
    # ...and at three of them it is BIT-EXACT against WRF where mp=8 is not.
    exact = [level for level in split_levels
             if float(aerosol["qr"][level]) == want_qr[level]]
    # FOUR now, not three.  The 1.4.1 merge inherited the mp=8 lane's two
    # sedimentation reconciliations (5e4af4e3, cb765336) into the frozen
    # kernel this port shares for rain fallout, and level 5 joined the
    # bit-exact set.  Pinned as EQUALITY, so losing one fails here.
    assert exact == [1, 2, 4, 5], exact
    for level in exact:
        assert float(classic["qr"][level]) != want_qr[level], level
    # The two levels the density mixture is worth decades on.
    assert abs(float(aerosol["qr"][5]) - want_qr[5]) / want_qr[5] < 1.0e-6
    assert abs(float(classic["qr"][5]) - want_qr[5]) / want_qr[5] > 1.0e-3
    assert float(aerosol["qr"][6]) > 0.0 and float(classic["qr"][6]) == 0.0

    # 1c. RAINNC IS THE HEADLINE.  mp=28 reproduces WRF's surface rain
    #     accumulation BIT FOR BIT on this column; the frozen mp=8 pipeline
    #     does not.  A float64 equality on a float32-derived accumulation is
    #     the strongest statement available and it needs no tolerance.
    assert aerosol["rainnc_mm"] == float(surface["rainnc_mm"]), (
        aerosol["rainnc_mm"], surface["rainnc_mm"])
    assert classic["rainnc_mm"] != float(surface["rainnc_mm"])
    assert aerosol["rainnc_mm"] > 0.0

    # 1d. CLOUD WATER IS JUDGED AGAINST THE ORACLE, AND THE TWO-PORT SPLIT IS
    #     RECORDED RATHER THAN BOUNDED.
    want_qc = oracle("qc")
    mine = np.asarray(aerosol["qc"], np.float64)
    theirs = np.asarray(classic["qc"], np.float64)
    aerosol_distance, classic_distance = distances("qc")
    split = _field_max_rel(classic["qc"], aerosol["qc"])

    assert aerosol_distance <= _END_TO_END_DEFAULT_BOUND, (
        f"mp=28 qc is {aerosol_distance:.6e} from WRF")
    exact = int((np.asarray(aerosol["qc"], np.float32)
                 == _oracle_column(after, "qc")).sum())
    assert exact == want_qc.size - 1, (exact, want_qc.size)
    assert classic_distance > 5.0 * aerosol_distance, (
        aerosol_distance, classic_distance)
    disagreeing = np.nonzero(mine != theirs)[0]
    assert disagreeing.size == 2, disagreeing.tolist()
    level = int(np.argmax(np.abs(mine - theirs)))
    wrf = want_qc[level]
    # Since development branch (WRF's REAL qvten/tten through the
    # condensation) the strict build lands mp=28 ON WRF at this level, so the
    # product is zero there; the split is then mp=8's distance alone, which
    # the sum below still states.  mp=8 must still be off WRF.
    assert theirs[level] != wrf
    assert (mine[level] - wrf) * (theirs[level] - wrf) <= 0.0, (
        "the two ports no longer straddle WRF; the split is no longer the "
        "sum of their distances and this test's arithmetic does not hold")
    assert split == pytest.approx(
        (abs(mine[level] - wrf) + abs(theirs[level] - wrf)) / abs(wrf),
        rel=1.0e-6), split
    ulp = _entry_ulp(wrf)
    assert abs(mine[level] - wrf) / ulp <= 2.0, abs(mine[level] - wrf) / ulp
    assert 6.0 <= abs(theirs[level] - wrf) / ulp <= 16.0, (
        abs(theirs[level] - wrf) / ulp)

    # 2. where the aerosol IS the physics the two ports must split, and mp=28
    #    must be the one that matches WRF.
    levels = list(_DEMOTT_ONLY_LEVELS)
    want_qi = _oracle_column(after, "qi")[levels].astype(np.float64)
    want_ni = _oracle_column(after, "ni_per_kg")[levels].astype(np.float64)
    assert (want_qi > 0.0).all()
    ratio = classic["qi"][levels].astype(np.float64) / want_qi
    assert ratio.min() > 20.0, ratio
    assert _field_max_rel(aerosol["qi"][levels], want_qi) <= 1.0e-6, (
        aerosol["qi"][levels], want_qi)
    assert _field_max_rel(aerosol["ni_per_kg"][levels], want_ni) <= 1.0e-6
    assert (classic["ni_per_kg"][levels].astype(np.float64)
            / want_ni).min() > 20.0

    # 3. below HGFR both ports converge again: homogeneous freezing, not
    #    DeMott, sets the ice there, and it needs no aerosol.
    cold = [index for index in range(18, 24)]
    assert _field_max_rel(classic["qi"][cold], aerosol["qi"][cold]) <= 1.0e-3
    assert _field_max_rel(classic["ni_per_kg"][cold],
                          aerosol["ni_per_kg"][cold]) <= 1.0e-6

    # 4. THE WHOLE-COLUMN SUMMARY, printed so a reader can see the direction
    #    of every one of these comparisons at once.
    print("\naero-reduces-to-classic: distance from WRF, mp=28 vs mp=8")
    for key in ("qr", "nr_per_kg", "qc", "qi", "ni_per_kg", "qv", "temp_k"):
        near, far = distances(key)
        print(f"  {key:11s} mp28 {near:.4e}   mp8 {far:.4e}   "
              f"{'mp28 nearer' if near < far else 'mp8 nearer'}")
    for key in ("qr", "nr_per_kg", "qc", "qi", "ni_per_kg"):
        near, far = distances(key)
        assert near <= far, (
            f"{key}: mp=28 is {near:.4e} from WRF and mp=8 is {far:.4e}; "
            "the aerosol port is supposed to be the nearer of the two")
