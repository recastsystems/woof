def _column(values):
    """One (nz, 1, 1) device column from a host vector."""
    host = np.ascontiguousarray(
        np.asarray(values, dtype=np.float32).reshape(-1, 1, 1))
    return cp.asarray(host)


def _max_rel(got, want):
    got = np.asarray(got, dtype=np.float64)
    want = np.asarray(want, dtype=np.float64)
    if got.size == 0:
        return 0.0
    return float(np.max(np.abs(got - want)
                        / np.maximum(np.abs(want), 1e-30)))


def _run_sediment(table, *, dt=DT, rain_active=False, dz=None, w=None,
                  cloud_active=True):
    nz = table["dzq"].size
    dz_column = table["dzq"] if dz is None else np.full(nz, dz, np.float32)
    w_column = table["w1d"] if w is None else np.full(nz, w, np.float32)
    qc_in = (table["qc1d"] + table["qcten_pre"] * np.float32(dt)
             ).astype(np.float32)
    diagnostics = {name: cp.zeros((nz, 1, 1), dtype=cp.float32)
                   for name in DIAGNOSTIC_FIELDS}
    qc = _column(qc_in)
    ncten = _column(table["ncten_pre"])
    nc_entry = _column(table["nc1d"])
    launch_aa_cloud_sedimentation(
        qc, nc_entry, ncten,
        _column(table["temp"]), _column(table["p1d"]), _column(table["qv"]),
        _column(w_column), _column(dz_column), dt,
        reference_density=_column(table["rho_pre"]),
        rain_active_columns=cp.full(
            (1, 1), 1.0 if rain_active else 0.0, dtype=cp.float32),
        cloud_active_columns=cp.full(
            (1, 1), 1.0 if cloud_active else 0.0, dtype=cp.float32),
        diagnostics=diagnostics)
    cp.cuda.Stream.null.synchronize()
    result = {name: diagnostics[name].get().ravel()
              for name in DIAGNOSTIC_FIELDS}
    result["qc"] = qc.get().ravel()
    result["ncten"] = ncten.get().ravel()
    result["nc_entry"] = nc_entry.get().ravel()
    result["qc_in"] = qc_in
    return result


