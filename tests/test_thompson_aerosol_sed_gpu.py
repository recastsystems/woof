def test_reduces_to_the_frozen_mp8_cloud_sedimentation():
    """With nc pinned at Nt_c the mass channel must reproduce mp=8.

    At the fixture's own resolution the two are BIT-IDENTICAL: over dt = 10 s
    and 500 m layers the fallout moves about 1e-8 kg/kg out of 5e-4, which is
    far below a float32 ulp of qc, so the small formula difference cannot
    show.  That is worth asserting because it is the statement "at nc = Nt_c
    mp=28 is classic Thompson" in the regime the oracle fixture covers.

    The difference is then resolved by amplifying the fallout (5 m layers,
    300 s) and comparing the qc CHANGE rather than qc.  It cannot be zero, and
    the reason is recorded in thompson_aerosol_common.cuh: thompson.cu
    hardcodes 2730.0f and 272.0f where WRF's runtime products are
    ccg(2,12)*ocg1(12) = 2729.9973 and ccg(5,12)*ocg2(12) = 272.00012.  mp=28
    computes them from WRF's own REAL(4) WGAMMA series and is therefore RIGHT;
    mp=8 stays frozen and slightly wrong, and reconciling them would move a
    model-validated trajectory.  Predicted separation in the fall speed is
    about 1.5e-6 relative -- a 9.9e-7 shift in the lambda argument entering as
    its cube root and then squared, plus 4.4e-7 in the prefactor.  MEASURED:
    1.26e-6 on the qc change.  The 5e-6 bound is tight enough to catch a real
    divergence (a wrong ccg row is 20% or more) and loose enough not to
    re-litigate the frozen literals.
    """
    _require_device()
    table = SED_TABLES["aero-nc-sed"]

    qc_in, aerosol, classic, _ = _bridge_pair(table, dz=500.0, dt=DT)
    assert (np.abs(classic - qc_in) > 0.0).any(), (
        "the bridge column has to actually sediment")
    assert np.array_equal(aerosol, classic)

    qc_in, aerosol, classic, _ = _bridge_pair(table, dz=5.0, dt=300.0)
    moved = np.abs(classic - qc_in) > 0.0
    assert moved.sum() >= 3
    fallen_aerosol = (aerosol - qc_in)[moved]
    fallen_classic = (classic - qc_in)[moved]
    # the amplified column must move a resolvable amount of water
    assert np.abs(fallen_classic).max() > 1.0e-6
    assert _max_rel(fallen_aerosol, fallen_classic) <= 5.0e-6


