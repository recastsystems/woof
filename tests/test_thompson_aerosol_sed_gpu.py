def test_only_cloud_fallout_is_a_single_pass_in_the_frozen_kernel_too():
    """The convention this kernel copies, asserted against thompson.cu.

    :3823-3838 has no ``do n = 1, nstep`` and no onstep(1..4) factor, while
    rain (:3790-3820), ice (:3840-3870), snow (:3871-3902) and graupel
    (:3903-3937) all do.  Pinning that against the byte-frozen mp=8 source
    means a future reader cannot conclude the aerosol kernel simply forgot
    the substep loop.
    """
    frozen = (_KERNEL_DIR / "thompson.cu").read_text(encoding="utf-8")

    def body(name):
        start = frozen.index("void " + name)
        stop = min(index for index in (frozen.find("\n__device__", start),
                                       frozen.find("\nextern", start),
                                       len(frozen)) if index > 0)
        return frozen[start:stop]

    cloud = body("thompson_cloud_sediment_held_density_impl")
    assert "nstep" not in cloud and "onstep" not in cloud
    for name in ("thompson_rain_sediment_impl", "thompson_ice_sediment_impl"):
        assert "nstep" in body(name), name

    aerosol = (_KERNEL_DIR / "thompson_aerosol_sed.cu").read_text(
        encoding="utf-8")
    # The operational WRF 3.9 fork's ice, snow and graupel fallout live in
    # this unit under THOMPSON_AA_WRF39 (thompson.cu stays frozen) and carry
    # the substep loop those species have; the convention is the cloud
    # fallout's, so the fork arms are set aside.
    import re
    aerosol = re.sub(r"^#if defined\(THOMPSON_AA_WRF39\)\n.*?^#endif[^\n]*\n",
                     "", aerosol, flags=re.S | re.M)
    # The hail image owns a separate graupel substep loop. It does not
    # change the single-pass cloud operation in the non-hail image.
    start = aerosol.rindex("#if defined(THOMPSON_AA_HAIL)")
    marker = "#endif  // THOMPSON_AA_HAIL"
    stop = aerosol.index(marker, start) + len(marker)
    hail = aerosol[start:stop]
    assert "thompson_aa_hail_graupel_sediment_impl" in hail
    assert "nstep" in hail and "onstep" in hail
    aerosol = aerosol[:start] + aerosol[stop:]
    # The v4.6.1 accumulator path's rain and ice fallout (2.8.6) carry the
    # substep loop rain and ice have; set aside likewise.
    start = aerosol.index("// RAIN AND ICE FALLOUT IN WRF'S TENDENCY FORM")
    stop = aerosol.rindex("THOMPSON_AA_ICE_ACCUMULATE_ARGUMENTS);")
    stop = aerosol.index("}", stop) + 1
    tendency_form = aerosol[start:stop]
    assert "nstep" in tendency_form and "onstep" in tendency_form
    aerosol = aerosol[:start] + aerosol[stop:]
    # The v4.6.1 snow and graupel fallout (development branch) carry
    # the substep loop those species have, and the surface totals follow
    # them; set aside likewise.
    start = aerosol.index("// SNOW AND GRAUPEL FALLOUT AND THE SURFACE TOTALS")
    stop = aerosol.index("void thompson_aa_surface_precipitation(")
    stop = aerosol.index("\n}\n", stop) + 3
    snow_graupel = aerosol[start:stop]
    assert "nstep" in snow_graupel and "onstep" in snow_graupel
    aerosol = aerosol[:start] + aerosol[stop:]
    code = "\n".join(line for line in aerosol.splitlines()
                     if not line.lstrip().startswith("//"))
    assert "nstep" not in code and "onstep" not in code


