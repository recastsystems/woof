def test_legacy_nssl_resolution_is_visible_beside_native_471_expectation():
    tool = _tool()
    for value in (17, 22):
        result = tool.probe("mp_physics", value)
        assert result["imports"]
        assert result["resolved"]["shared"]["mp_physics"] == 18
