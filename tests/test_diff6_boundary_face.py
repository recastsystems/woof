@pytest.mark.parametrize("opt", [1, 2])
@pytest.mark.parametrize("stagger", ["", "x", "y", "z"])
def test_mirror_matches_wrf_loop_oracle_on_forced_bounds(stagger, opt):
    """np_diff6 with open_x/open_y (the mask np_diff6 shares between open
    and specified/nested forcing) must reproduce the WRF-loop oracle
    everywhere -- including the u east / v north seam faces the 4d2ce99
    mirror zeroed."""
    from woof.verify.npref import np_diff6
    f, mut, c1, c2 = _forced_case(stagger)
    name = _STAG_NAME[stagger]
    want = wrf_sixth_order_diffusion(f, mut, c1, c2, FACTOR, DT, opt, name)
    got = np_diff6(f.astype(np.float64), mut, c1, c2, FACTOR, DT, opt,
                   stagger=stagger, open_x=True, open_y=True)
    np.testing.assert_allclose(got, want, rtol=1e-12, atol=0.0,
                               err_msg=f"{stagger}/{opt}")
    seam = _seam_mask(stagger, f.shape)
    if stagger in ("x", "y") and opt == 1:
        assert np.abs(want[seam]).min() > 0.0     # non-vacuous


@pytest.mark.parametrize("stagger", ["", "x", "y", "z"])
def test_mirror_matches_wrf_loop_oracle_with_slope_taper(stagger):
    """Same equivalence with the diff_6th_slopeopt taper engaged (3-D phb,
    non-identity msf), covering the taper arithmetic at the seam faces."""
    from woof.verify.npref import np_diff6
    f, mut, c1, c2 = _forced_case(stagger, seed=31)
    name = _STAG_NAME[stagger]
    phb, msfu, msfv = _slope_inputs()
    dx = dy = 500.0
    want = wrf_sixth_order_diffusion(f, mut, c1, c2, FACTOR, DT, 2, name,
                                     phb=phb, msfu=msfu, msfv=msfv,
                                     slopeopt=1, thresh=0.10, dx=dx, dy=dy)
    got = np_diff6(f.astype(np.float64), mut, c1, c2, FACTOR, DT, 2,
                   stagger=stagger, open_x=True, open_y=True, phb=phb,
                   msfu=msfu, msfv=msfv, slopeopt=1, thresh=0.10,
                   dx=dx, dy=dy)
    np.testing.assert_allclose(got, want, rtol=1e-12, atol=0.0,
                               err_msg=stagger)
    if stagger in ("x", "y"):
        seam = _seam_mask(stagger, f.shape)
        assert np.abs(want[seam]).max() > 0.0     # non-vacuous under taper


