def test_oracle_support_is_exactly_the_wrf_bounds():
    """The oracle's nonzero support equals WRF's specified-domain loop set
    for every stagger, and the u/v supports INCLUDE the seam faces."""
    for stagger in ("", "x", "y", "z"):
        f, mut, c1, c2 = _forced_case(stagger)
        name = _STAG_NAME[stagger]
        out = wrf_sixth_order_diffusion(f, mut, c1, c2, FACTOR, DT, 1, name)
        nlev = f.shape[0]
        (i0, i1), (j0, j1), (k0, k1) = _wrf_bounds(name, NY, NX, nlev)
        inside = np.zeros(f.shape, dtype=bool)
        inside[k0:k1 + 1, j0:j1 + 1, i0:i1 + 1] = True
        assert (out[~inside] == 0.0).all(), stagger
        # opt=1 (no monotonic zeroing) on continuous noise: every computed
        # entry is nonzero, so the support is the full WRF loop set.
        assert (out[inside] != 0.0).all(), stagger
        seam = _seam_mask(stagger, f.shape)
        if stagger in ("x", "y"):
            assert seam.sum() == (nlev * (NY - 6) if stagger == "x"
                                  else nlev * (NX - 6))
            assert inside[seam].all(), stagger
            assert np.abs(out[seam]).min() > 0.0, stagger


def test_oracle_seam_face_reads_the_true_boundary_datum():
    """Perturbing ONLY the stored boundary face (u[..., nx] / v[:, ny, :])
    changes the oracle exactly on the seam set -- the WRF read woof's
    wrapped stencil could not make -- and nowhere else."""
    for stagger in ("x", "y"):
        f, mut, c1, c2 = _forced_case(stagger)
        name = _STAG_NAME[stagger]
        base = wrf_sixth_order_diffusion(f, mut, c1, c2, FACTOR, DT, 1, name)
        g = f.copy()
        if stagger == "x":
            g[:, :, -1] += 1.5
        else:
            g[:, -1, :] += 1.5
        pert = wrf_sixth_order_diffusion(g, mut, c1, c2, FACTOR, DT, 1, name)
        diff = pert - base
        seam = _seam_mask(stagger, f.shape)
        assert np.abs(diff[seam]).min() > 0.0, stagger
        assert (diff[~seam] == 0.0).all(), stagger


