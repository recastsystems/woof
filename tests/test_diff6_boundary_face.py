_STAG_NAME = {"": "m", "x": "u", "y": "v", "z": "w"}


def _forced_case(stagger, nz=NZ, ny=NY, nx=NX, seed=17):
    """Random fp32 field with INDEPENDENT boundary-face data.

    Unlike the periodic fixtures, the last staggered column/row is NOT a
    duplicate of column/row 0: on a specified/nested domain it is the
    boundary-installed datum WRF's outermost computed face reads, and the
    pins are vacuous unless it differs from the opposite boundary.
    """
    rng = np.random.default_rng(seed)
    nlev = nz + 1 if stagger == "z" else nz
    shape = {"": (nlev, ny, nx), "z": (nlev, ny, nx),
             "x": (nlev, ny, nx + 1), "y": (nlev, ny + 1, nx)}[stagger]
    f = rng.standard_normal(shape).astype(np.float32)
    mut = (1.0 + 0.5 * rng.random((ny, nx))).astype(np.float32)
    c1 = (0.5 + 0.5 * rng.random(nlev)).astype(np.float32)
    c2 = (0.5 * rng.random(nlev)).astype(np.float32)
    return f, mut, c1, c2


def _slope_inputs(nz=NZ, ny=NY, nx=NX, seed=23):
    """Terrain-like phb + non-identity staggered msf, taper-straddling."""
    rng = np.random.default_rng(seed)
    z = (60.0 * np.cumsum(rng.random((ny, nx)), axis=1)
         + 40.0 * np.cumsum(rng.random((ny, nx)), axis=0))
    phb = (9.81 * (z[None] + 200.0 * np.arange(nz + 2)[:, None, None])
           ).astype(np.float32)[:nz + 1]
    msfu = (1.0 + 0.1 * rng.random((ny, nx + 1))).astype(np.float32)
    msfv = (1.0 + 0.1 * rng.random((ny + 1, nx))).astype(np.float32)
    return phb, msfu, msfv


def _seam_mask(stagger, shape):
    """Boolean mask of the two newly-computed WRF face sets (else False)."""
    m = np.zeros(shape, dtype=bool)
    nlev, nys, nxs = shape
    if stagger == "x":
        m[:, 3:nys - 3, nxs - 4] = True     # u: j in [3, ny-4], i = nx-3
    if stagger == "y":
        m[:, nys - 4, 3:nxs - 3] = True     # v: j = ny-3, i in [3, nx-4]
    return m


def _forced_cfg(**flags):
    from woof.config import RunConfig
    return RunConfig(nx=NX, ny=NY, nz=NZ, dx=1.0, dy=1.0, ztop=1.0, dt=DT,
                     run_seconds=0.0, diff_6th_opt=2, diff_6th_factor=FACTOR,
                     **flags)


def _production_masked_tend(f, mut, c1, c2, opt, stagger, cfg, **slope_kw):
    """launch_diff6 + _zero_open_strips exactly as prepare_fixed_tendencies
    / apply_diff6 drive them (boundary-aware kernel + WRF width-3 mask)."""
    import cupy as cp

    from woof.core.dycore import (_boundary_x, _boundary_y,
                                   _zero_open_strips, launch_diff6)
    fd = cp.asarray(f, dtype=cp.float32)
    tend = cp.zeros_like(fd)
    launch_diff6(fd, tend, cp.asarray(mut, cp.float32),
                 cp.asarray(c1, cp.float32), cp.asarray(c2, cp.float32),
                 FACTOR, DT, opt, stagger=stagger,
                 bnd_x=_boundary_x(cfg), bnd_y=_boundary_y(cfg), **slope_kw)
    _zero_open_strips(tend, cfg, 3)
    return cp.asnumpy(tend)


