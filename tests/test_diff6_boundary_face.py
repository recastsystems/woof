_F = np.float32
_XO_Z, _XO_O, _XO_H, _XO_Q = _F(0.0), _F(1.0), _F(0.5), _F(0.25)
_XO_TWO, _XO_FIVE, _XO_TEN = _F(2.0), _F(5.0), _F(10.0)
_XO_1_64 = _F(0.015625)


def _xo_add(a, b):
    return _F(_F(a) + _F(b))


def _xo_sub(a, b):
    return _F(_F(a) - _F(b))


def _xo_mul(a, b):
    return _F(_F(a) * _F(b))


def _xo_div(a, b):
    return _F(_F(a) / _F(b))


def _xo_mass_at(mut, j, i, c1, c2):
    return _xo_add(_xo_mul(c1, mut[j, i]), c2)


def _xo_avg2(a, b):
    return _xo_mul(_XO_H, _xo_add(a, b))


def _xo_avg4(a, b, c, d):
    # Source-ordered (((a+b)+c)+d), then multiply by 0.25.
    return _xo_mul(_XO_Q, _xo_add(_xo_add(_xo_add(a, b), c), d))


def _xo_flux_x(a, j, i, shift):
    d0 = _xo_sub(a[j, i + shift], a[j, i - 1 + shift])
    q0 = _xo_mul(_XO_TEN, d0)
    d1 = _xo_sub(a[j, i + 1 + shift], a[j, i - 2 + shift])
    q1 = _xo_mul(_XO_FIVE, d1)
    q2 = _xo_sub(q0, q1)
    d2 = _xo_sub(a[j, i + 2 + shift], a[j, i - 3 + shift])
    return _xo_add(q2, d2)


def _xo_flux_y(a, j, i, shift):
    d0 = _xo_sub(a[j + shift, i], a[j - 1 + shift, i])
    q0 = _xo_mul(_XO_TEN, d0)
    d1 = _xo_sub(a[j + 1 + shift, i], a[j - 2 + shift, i])
    q1 = _xo_mul(_XO_FIVE, d1)
    q2 = _xo_sub(q0, q1)
    d2 = _xo_sub(a[j + 2 + shift, i], a[j - 3 + shift, i])
    return _xo_add(q2, d2)


def _xo_limited(flux, first_difference):
    product = _xo_mul(flux, first_difference)
    return _XO_Z if product <= _XO_Z else _F(flux)


def _xo_bounds(kind, nx, ny):
    if kind == "u":
        return 3, nx - 3, 3, ny - 4
    if kind == "v":
        return 3, nx - 4, 3, ny - 3
    if kind in ("m", "w"):
        return 3, nx - 4, 3, ny - 4
    raise ValueError("kind must be 'u', 'v', 'm', or 'w'")


def xoracle_diff6_slice(field, kind, nx, ny, mut, mapx, mapy,
                        dt, factor, c1, c2, tendency=None):
    """One horizontal k slice, per-op FP32 (the handoff report's oracle)."""
    a = np.asarray(field, dtype=np.float32)
    mut = np.asarray(mut, dtype=np.float32)
    mapx = np.asarray(mapx, dtype=np.float32)
    mapy = np.asarray(mapy, dtype=np.float32)
    if tendency is None:
        out = np.zeros_like(a, dtype=np.float32)
    else:
        out = np.asarray(tendency, dtype=np.float32).copy()
    tx = np.zeros_like(a, dtype=np.float32)
    ty = np.zeros_like(a, dtype=np.float32)
    coef = _xo_div(_xo_mul(_F(factor), _XO_1_64), _xo_mul(_XO_TWO, _F(dt)))
    ilo, ihi, jlo, jhi = _xo_bounds(kind, nx, ny)
    for j in range(jlo, jhi + 1):
        for i in range(ilo, ihi + 1):
            fx0 = _xo_flux_x(a, j, i, 0)
            fx1 = _xo_flux_x(a, j, i, 1)
            fx0 = _xo_limited(fx0, _xo_sub(a[j, i], a[j, i - 1]))
            fx1 = _xo_limited(fx1, _xo_sub(a[j, i + 1], a[j, i]))
            if kind == "u":
                mx0 = _xo_mass_at(mut, j, i - 1, c1, c2)
                mx1 = _xo_mass_at(mut, j, i, c1, c2)
            elif kind == "v":
                mx0 = _xo_avg4(_xo_mass_at(mut, j - 1, i - 1, c1, c2),
                               _xo_mass_at(mut, j - 1, i, c1, c2),
                               _xo_mass_at(mut, j, i - 1, c1, c2),
                               _xo_mass_at(mut, j, i, c1, c2))
                mx1 = _xo_avg4(_xo_mass_at(mut, j - 1, i, c1, c2),
                               _xo_mass_at(mut, j - 1, i + 1, c1, c2),
                               _xo_mass_at(mut, j, i, c1, c2),
                               _xo_mass_at(mut, j, i + 1, c1, c2))
            else:
                mx0 = _xo_avg2(_xo_mass_at(mut, j, i - 1, c1, c2),
                               _xo_mass_at(mut, j, i, c1, c2))
                mx1 = _xo_avg2(_xo_mass_at(mut, j, i, c1, c2),
                               _xo_mass_at(mut, j, i + 1, c1, c2))
            xp1 = _xo_mul(_xo_mul(_XO_O, mx1), fx1)
            xp0 = _xo_mul(_xo_mul(_XO_O, mx0), fx0)
            tx[j, i] = _xo_mul(_xo_mul(coef, mapx[j, i]),
                               _xo_sub(xp1, xp0))
            fy0 = _xo_flux_y(a, j, i, 0)
            fy1 = _xo_flux_y(a, j, i, 1)
            fy0 = _xo_limited(fy0, _xo_sub(a[j, i], a[j - 1, i]))
            fy1 = _xo_limited(fy1, _xo_sub(a[j + 1, i], a[j, i]))
            if kind == "u":
                my0 = _xo_avg4(_xo_mass_at(mut, j - 1, i - 1, c1, c2),
                               _xo_mass_at(mut, j - 1, i, c1, c2),
                               _xo_mass_at(mut, j, i - 1, c1, c2),
                               _xo_mass_at(mut, j, i, c1, c2))
                my1 = _xo_avg4(_xo_mass_at(mut, j, i - 1, c1, c2),
                               _xo_mass_at(mut, j, i, c1, c2),
                               _xo_mass_at(mut, j + 1, i - 1, c1, c2),
                               _xo_mass_at(mut, j + 1, i, c1, c2))
            elif kind == "v":
                my0 = _xo_mass_at(mut, j - 1, i, c1, c2)
                my1 = _xo_mass_at(mut, j, i, c1, c2)
            else:
                my0 = _xo_avg2(_xo_mass_at(mut, j - 1, i, c1, c2),
                               _xo_mass_at(mut, j, i, c1, c2))
                my1 = _xo_avg2(_xo_mass_at(mut, j, i, c1, c2),
                               _xo_mass_at(mut, j + 1, i, c1, c2))
            yp1 = _xo_mul(_xo_mul(_XO_O, my1), fy1)
            yp0 = _xo_mul(_xo_mul(_XO_O, my0), fy0)
            ty[j, i] = _xo_mul(_xo_mul(coef, mapy[j, i]),
                               _xo_sub(yp1, yp0))
            out[j, i] = _xo_add(_xo_add(out[j, i], tx[j, i]), ty[j, i])
    return out, tx, ty, coef


def _xo_pattern(nj, ni, seed):
    j, i = np.indices((nj, ni), dtype=np.int32)
    raw = ((17 * i + 31 * j + 7 * i * j + seed) % 29) - 14
    checker = ((i + j) & 1).astype(np.float32)
    return (raw.astype(np.float32) * _F(0.25)
            + checker * _F(0.125)).astype(np.float32)


def _xo_example():
    """The report's deterministic 8x8 worked-example fixtures."""
    nx = ny = 8
    jm, im = np.indices((ny, nx), dtype=np.int32)
    mut = (_F(1.0) + _F(0.01) * (_F(3.0) * im.astype(np.float32)
                                 + _F(5.0) * jm.astype(np.float32))
           ).astype(np.float32)
    cases = []
    for kind, shape, seed, points in [
            ("u", (ny, nx + 1), 3, [(3, 3), (3, 5), (4, 5), (4, 6)]),
            ("v", (ny + 1, nx), 5, [(3, 3), (5, 3), (5, 4), (6, 4)]),
            ("m", (ny, nx), 7, [(3, 3), (4, 4), (4, 5), (5, 4)])]:
        field = _xo_pattern(*shape, seed)
        j, i = np.indices(shape, dtype=np.int32)
        mapx = (_F(0.90) + _F(0.002) * i.astype(np.float32)
                + _F(0.003) * j.astype(np.float32)).astype(np.float32)
        mapy = (_F(1.10) + _F(0.004) * i.astype(np.float32)
                - _F(0.001) * j.astype(np.float32)).astype(np.float32)
        cases.append((kind, field, mapx, mapy, points))
    return nx, ny, mut, cases


