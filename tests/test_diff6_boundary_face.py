"""Sixth-order diffusion: the WRF-computed high-side staggered faces.

The compiled WRF v4.7.1 oracle now supersedes the historical GPU golden:
the old golden retained missing tendency map factors and different REAL
rounding. The periodic and forced replay tests below grade compiled Fortran
words. The older captures and their generator remain historical evidence.

Oracle: WRF v4.6.1 (reference bundle) ``sixth_order_diffusion``,
dyn_em/module_big_step_utilities_em.F --
  bounds    :6332-6444: for ``specified .or. nested`` (:6333-6334) the
            loops are, 1-based with mass cells ids..ide-1:
              'u'   i = ids+3..ide-3, j = jds+3..jde-4   (:6354-6359)
              'v'   i = ids+3..ide-4, j = jds+3..jde-3   (:6381-6386)
              'w'   i = ids+3..ide-4, j = jds+3..jde-4, k = kts+1..ktf
                                                         (:6408-6415)
              mass  i = ids+3..ide-4, j = jds+3..jde-4   (:6435-6440)
  arithmetic :6461-6624: Xue eq. 3 face fluxes, the diff_6th_opt=2
            up-gradient zeroing, the diff_6th_slopeopt taper, and the
            variant-specific hybrid face-mass averages, with
            coef = diff_6th_factor*0.015625/(2*dt) (:6321).

0-based mapping (woof ``nx = e_we - 1`` mass points, so ids=1 -> 0 and
ide = nx+1; ditto j/ny):
  u faces computed:  i in [3, nx-3], j in [3, ny-4]
  v faces computed:  j in [3, ny-3], i in [3, nx-4]
  w/mass computed:   i in [3, nx-4], j in [3, ny-4]

The single WRF read outside each staggered axis' periodic core happens at
the outermost computed face: u's ``dflux_x_p1`` at i = nx-3 reads
``field(i+3)`` = the stored true east-boundary datum u[..., nx] (WRF
:6465-6467 reading field(ide)), and v's ``dflux_y_p1`` at j = ny-3 reads
v[..., ny, :] (WRF :6547-6549 reading field(jde)).  woof at 4d2ce99
instead zeroed those two face sets (``_zero_open_strips`` width 3 with
``stag_high_extra=1``; kernel header note), because the periodic-wrap
stencil would have corrupted the read with the OPPOSITE boundary's value.
The dropped WRF-computed sets are exactly

  u:  (k, j in [3, ny-4], i = nx-3)      east high-side staggered face
  v:  (k, j = ny-3, i in [3, nx-4])      north high-side staggered face

and nothing else (all other sides/staggers already match WRF's width-3
exclusion, pinned below).

These pins were written RED against 4d2ce99 (the mirror and both
application paths zeroed the two face sets where the WRF-loop oracle is
nonzero) and must stay green forever after.  The base-behavior capture
``tests/data/diff6_base_4d2ce99.npz`` was generated by THIS file's
``--generate`` entry point running the UNMODIFIED 4d2ce99 kernel (dual
run, elementwise-identical), and pins that the fix leaves every face
other than the two seam sets bit-identical, and periodic behavior
bit-identical everywhere.
"""
