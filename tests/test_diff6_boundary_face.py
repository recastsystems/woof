def _wrf_bounds(name, ny, nx, nlev):
    """0-based inclusive loop bounds for specified .or. nested domains.

    WRF module_big_step_utilities_em.F:6332-6444 (see module docstring for
    the 1-based originals and the ids=1/ide=nx+1 mapping)."""
    if name == "u":
        return (3, nx - 3), (3, ny - 4), (0, nlev - 1)
    if name == "v":
        return (3, nx - 4), (3, ny - 3), (0, nlev - 1)
    if name == "w":
        return (3, nx - 4), (3, ny - 4), (1, nlev - 2)
    return (3, nx - 4), (3, ny - 4), (0, nlev - 1)


def wrf_sixth_order_diffusion(field, mut, c1, c2, factor, dt, opt, name,
                              phb=None, msfu=None, msfv=None, slopeopt=0,
                              thresh=0.10, dx=0.0, dy=0.0,
                              mapx=None, mapy=None):
    """WRF v4.6.1 ``sixth_order_diffusion`` for a specified/nested domain.

    Independent float64 loop transcription (bounds :6332-6444, x fluxes
    :6461-6533, y fluxes :6543-6616, combine :6624), 0-based storage, NO
    periodic wrap anywhere: every stencil read is the stored datum, which
    inside the WRF bounds is always in range -- including the accurate
    boundary reads u[..., nx] / v[..., ny, :] at the outermost computed
    staggered faces.  ``mapx``/``mapy`` are the per-direction TENDENCY
    map factors (WRF msfux/msfuy for u, msfvx/msfvy for v, msftx/msfty
    for mass; field-shaped 2-D); they default to 1, the woof kernel's
    documented specialization.  ``msfu``/``msfv`` enter only the slopeopt
    dzmax scaling exactly as the Fortran's msfux/msfvy.  Returns the
    coupled tendency, zero outside the WRF loop bounds.

    Cross-checked against the blind independent derivation
    the diff6 cross-oracle record (2026-07-27): same bounds
    tables (its section 2), same flux-form/per-face-limiter/mass-average
    associations (its section 1), and digit-level agreement with its
    FP32 oracle's worked example (tests below).
    """
    f = np.asarray(field, dtype=np.float64)
    mut = np.asarray(mut, dtype=np.float64)
    c1 = np.asarray(c1, dtype=np.float64)
    c2 = np.asarray(c2, dtype=np.float64)
    nlev = f.shape[0]
    ny, nx = mut.shape
    assert nx >= 8 and ny >= 8, "domain too small for the WRF bounds"
    coef = factor * 0.015625 / (2.0 * dt)          # :6321
    slope = slopeopt >= 1 and phb is not None and np.ndim(phb) == 3
    if slope:
        ph = np.asarray(phb, dtype=np.float64)
        mfu = (np.ones((ny, nx + 1)) if msfu is None
               else np.asarray(msfu, dtype=np.float64))
        mfv = (np.ones((ny + 1, nx)) if msfv is None
               else np.asarray(msfv, dtype=np.float64))
        dzthr_x = thresh * 9.81 * dx               # :6489
        dzthr_y = thresh * 9.81 * dy               # :6571
    mapx = np.ones(f.shape[1:]) if mapx is None else np.asarray(
        mapx, dtype=np.float64)
    mapy = np.ones(f.shape[1:]) if mapy is None else np.asarray(
        mapy, dtype=np.float64)
    out = np.zeros_like(f)
    (i0, i1), (j0, j1), (k0, k1) = _wrf_bounds(name, ny, nx, nlev)

    def mu_avg(k, jj, ii):                         # c1(k)*MUT(i,j)+c2(k)
        return c1[k] * mut[jj, ii] + c2[k]

    for j in range(j0, j1 + 1):
        for k in range(k0, k1 + 1):
            for i in range(i0, i1 + 1):
                # ---- diffusion in x (:6461-6533) ----
                dflux_x_p0 = (10.0 * (f[k, j, i] - f[k, j, i - 1])
                              - 5.0 * (f[k, j, i + 1] - f[k, j, i - 2])
                              + (f[k, j, i + 2] - f[k, j, i - 3]))
                dflux_x_p1 = (10.0 * (f[k, j, i + 1] - f[k, j, i])
                              - 5.0 * (f[k, j, i + 2] - f[k, j, i - 1])
                              + (f[k, j, i + 3] - f[k, j, i - 2]))
                if opt == 2:                       # :6472-6482
                    if dflux_x_p0 * (f[k, j, i] - f[k, j, i - 1]) <= 0.0:
                        dflux_x_p0 = 0.0
                    if dflux_x_p1 * (f[k, j, i + 1] - f[k, j, i]) <= 0.0:
                        dflux_x_p1 = 0.0
                sdx_p0 = sdx_p1 = 1.0
                if slope:                          # :6487-6502
                    if name == "u":
                        dz0 = max(abs(ph[k, j, i] - ph[k, j, i - 1])
                                  * mfu[j, i],
                                  abs(ph[k, j, i - 1] - ph[k, j, i - 2])
                                  * mfu[j, i - 1])
                        dz1 = max(abs(ph[k, j, i + 1] - ph[k, j, i])
                                  * mfu[j, i + 1],
                                  abs(ph[k, j, i] - ph[k, j, i - 1])
                                  * mfu[j, i])
                    elif name == "v":
                        dz0 = max(abs(ph[k, j, i] - ph[k, j, i - 1])
                                  * mfu[j, i],
                                  abs(ph[k, j - 1, i] - ph[k, j - 1, i - 1])
                                  * mfu[j - 1, i])
                        dz1 = max(abs(ph[k, j, i + 1] - ph[k, j, i])
                                  * mfu[j, i + 1],
                                  abs(ph[k, j - 1, i + 1] - ph[k, j - 1, i])
                                  * mfu[j - 1, i + 1])
                    else:
                        dz0 = abs(ph[k, j, i] - ph[k, j, i - 1]) * mfu[j, i]
                        dz1 = (abs(ph[k, j, i + 1] - ph[k, j, i])
                               * mfu[j, i + 1])
                    sdx_p0 = max(1.0 - dz0 / dzthr_x, 0.0)
                    sdx_p1 = max(1.0 - dz1 / dzthr_x, 0.0)
                if name == "u":                    # :6506-6510
                    mu_p0 = mu_avg(k, j, i - 1)
                    mu_p1 = mu_avg(k, j, i)
                elif name == "v":                  # :6511-6523
                    mu_p0 = 0.25 * (mu_avg(k, j - 1, i - 1)
                                    + mu_avg(k, j - 1, i)
                                    + mu_avg(k, j, i - 1)
                                    + mu_avg(k, j, i))
                    mu_p1 = 0.25 * (mu_avg(k, j - 1, i)
                                    + mu_avg(k, j - 1, i + 1)
                                    + mu_avg(k, j, i)
                                    + mu_avg(k, j, i + 1))
                else:                              # :6524-6532
                    mu_p0 = 0.5 * (mu_avg(k, j, i - 1) + mu_avg(k, j, i))
                    mu_p1 = 0.5 * (mu_avg(k, j, i) + mu_avg(k, j, i + 1))
                tendency_x = (coef * mapx[j, i]
                              * (sdx_p1 * mu_p1 * dflux_x_p1
                                 - sdx_p0 * mu_p0 * dflux_x_p0))

                # ---- diffusion in y (:6543-6616) ----
                dflux_y_p0 = (10.0 * (f[k, j, i] - f[k, j - 1, i])
                              - 5.0 * (f[k, j + 1, i] - f[k, j - 2, i])
                              + (f[k, j + 2, i] - f[k, j - 3, i]))
                dflux_y_p1 = (10.0 * (f[k, j + 1, i] - f[k, j, i])
                              - 5.0 * (f[k, j + 2, i] - f[k, j - 1, i])
                              + (f[k, j + 3, i] - f[k, j - 2, i]))
                if opt == 2:                       # :6554-6564
                    if dflux_y_p0 * (f[k, j, i] - f[k, j - 1, i]) <= 0.0:
                        dflux_y_p0 = 0.0
                    if dflux_y_p1 * (f[k, j + 1, i] - f[k, j, i]) <= 0.0:
                        dflux_y_p1 = 0.0
                sdy_p0 = sdy_p1 = 1.0
                if slope:                          # :6569-6584
                    if name == "u":
                        dz0 = max(abs(ph[k, j, i] - ph[k, j - 1, i])
                                  * mfv[j, i],
                                  abs(ph[k, j, i - 1] - ph[k, j - 1, i - 1])
                                  * mfv[j, i - 1])
                        dz1 = max(abs(ph[k, j + 1, i] - ph[k, j, i])
                                  * mfv[j + 1, i],
                                  abs(ph[k, j + 1, i - 1] - ph[k, j, i - 1])
                                  * mfv[j + 1, i - 1])
                    elif name == "v":
                        dz0 = max(abs(ph[k, j, i] - ph[k, j - 1, i])
                                  * mfv[j, i],
                                  abs(ph[k, j - 1, i] - ph[k, j - 2, i])
                                  * mfv[j - 1, i])
                        dz1 = max(abs(ph[k, j + 1, i] - ph[k, j, i])
                                  * mfv[j + 1, i],
                                  abs(ph[k, j, i] - ph[k, j - 1, i])
                                  * mfv[j, i])
                    else:
                        dz0 = abs(ph[k, j, i] - ph[k, j - 1, i]) * mfv[j, i]
                        dz1 = (abs(ph[k, j + 1, i] - ph[k, j, i])
                               * mfv[j + 1, i])
                    sdy_p0 = max(1.0 - dz0 / dzthr_y, 0.0)
                    sdy_p1 = max(1.0 - dz1 / dzthr_y, 0.0)
                if name == "u":                    # :6588-6600
                    mu_p0 = 0.25 * (mu_avg(k, j - 1, i - 1)
                                    + mu_avg(k, j - 1, i)
                                    + mu_avg(k, j, i - 1)
                                    + mu_avg(k, j, i))
                    mu_p1 = 0.25 * (mu_avg(k, j, i - 1)
                                    + mu_avg(k, j, i)
                                    + mu_avg(k, j + 1, i - 1)
                                    + mu_avg(k, j + 1, i))
                elif name == "v":                  # :6602-6606
                    mu_p0 = mu_avg(k, j - 1, i)
                    mu_p1 = mu_avg(k, j, i)
                else:                              # :6607-6615
                    mu_p0 = 0.5 * (mu_avg(k, j - 1, i) + mu_avg(k, j, i))
                    mu_p1 = 0.5 * (mu_avg(k, j, i) + mu_avg(k, j + 1, i))
                tendency_y = (coef * mapy[j, i]
                              * (sdy_p1 * mu_p1 * dflux_y_p1
                                 - sdy_p0 * mu_p0 * dflux_y_p0))

                out[k, j, i] = tendency_x + tendency_y     # :6624
    return out


