def _nu_c_sweep_states():
    """A dense (qc, nc) grid spanning every reachable nu_c.

    The geometric nc axis alone is not enough: nu_c is a step function of nc
    and two of its thirteen bins (11 and 13, i.e. nc in 1.05-1.18e8 and
    0.87-0.95e8) are narrower than the 1.21x grid ratio, so a purely
    geometric sweep skips them.  The bin CENTRES nc = 1000e6/(nu_c - 2) are
    therefore added explicitly -- otherwise a kernel that mis-indexed those
    two columns would never be exercised.
    """
    qc_axis = 10.0 ** np.linspace(-12.0, -2.0, 61)
    centres = np.array([1000.0e6 / (nu_c - 2.0)
                        for nu_c in range(3, 16)], dtype=np.float64)
    nc_axis = np.unique(np.concatenate([
        10.0 ** np.linspace(0.0, 12.0, 145), centres]))
    qc_grid, nc_grid = np.meshgrid(qc_axis, nc_axis, indexing="ij")
    return qc_grid.ravel().astype(np.float32), nc_grid.ravel().astype(
        np.float32)


