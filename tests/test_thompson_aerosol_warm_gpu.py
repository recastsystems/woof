def test_efficiency_log10_is_correctly_rounded_like_alog10():
    """Ef_gw = 0.55*ALOG10(2.51*stoke_g) (:2426) is a LOGARITHM WITH A ZERO.

    2.51*stoke_g reaches 1 at stoke_g = 0.398, one part in a thousand below
    the ``stoke_g >= 0.4`` gate the expression is evaluated behind, so an
    absolute error in the log10 is an unbounded RELATIVE error in Ef_gw and
    therefore in prg_gcw and pnc_gcw.  gfortran lowers ALOG10 to glibc's
    correctly-rounded log10f; CUDA's log10f is ~2 ulp.

    MEASURED on the full 14400-row oracle: plain log10f leaves Ef_gw
    bit-exact on 13316 rows, the correctly-rounded form on 13702; Ef_gw's
    ABSOLUTE error stays under 6.8e-8 either way, which is exactly why the
    RELATIVE bound alone cannot separate them.  The sub-freezing slice can:
    it is bit-exact on all seven rows one way and not the other.
    """
    import cupy as cp

    oracle = _table(_FROZEN_COLD_ORACLE)
    got = _run_frozen_probe(oracle)
    have = cp.asnumpy(got["Ef_gw"]).astype(np.float64)
    assert np.array_equal(have, oracle["Ef_gw"]), (
        "Ef_gw must be bit-exact against ALOG10 on this slice; got "
        f"{have} want {oracle['Ef_gw']}")
    warm = _frozen_oracle()
    warm_got = _run_frozen_probe(warm)
    warm_have = cp.asnumpy(warm_got["Ef_gw"]).astype(np.float64)
    active = warm["Ef_gw"] > 0.0
