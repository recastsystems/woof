# ---------------------------------------------------------------------------
# Warm-level snow/graupel number and aerosol sinks.
# ---------------------------------------------------------------------------
#
# ACCURATE SCOPE STATEMENT.  pnc_scw, pnc_gcw, pna_sca, pnd_scd, pna_gca and
# pnd_gcd (module_mp_thompson.F:2403-2471) are NOT gated against the Fortran
# oracle here.  The WP-07 oracle program covers :2144-2232 only.  What is
# gated below is their structure and their WRF caps, and what backs the
# formulas themselves is that each is line-for-line the corresponding MASS
# rate -- prs_scw, prg_gcw -- with rc replaced by nc / nwfa / nifa and, for
# the aerosol pair, Ef_sw/Ef_gw replaced by Eff_aero.  Those mass rates are
# thompson.cu's model-validated warm-network code, copied unchanged.
#
# They live in this package because iiwarm is a PARAMETER .false.
# (module_mp_thompson.F:59), so WRF's frozen block runs at EVERY level
# including ambient-warm ones, while WP-06's cold kernel returns early at
# T >= 273.15 K.  See the package-boundary note at the top of
# woof/core/kernels/thompson_aerosol_warm.cu.

def _mixed_column(n=32):
    column = _warm_column(n=n)
    column["qs"] = np.full(n, 5.0e-4, dtype=np.float32)
    column["qg"] = np.full(n, 3.0e-4, dtype=np.float32)
    column["ng"] = (column["qg"] * (3.672 / 1.0e-3) ** 3
                    / (np.pi * 400.0)).astype(np.float32)
    return column


def _run_mixed(column, dt=20.0):
    import cupy as cp

    from woof.core.thompson_aerosol_warm import (
        launch_aerosol_warm_source_network)

    n = column["pressure"].size
    have_ice = "qs" in column
    state = {name: _f32(column[name])
             for name in ("qc", "qr", "nr", "temperature", "qv")}
    state["pressure"] = _f32(column["pressure"])
    state["qs"] = _f32(column["qs"] if have_ice else np.zeros(n))
    state["qg"] = _f32(column["qg"] if have_ice else np.zeros(n))
    state["ng"] = _f32(column["ng"] if have_ice else np.zeros(n))
    entry = {name: _f32(column[name]) for name in ("nc", "nwfa", "nifa")}
    accum = {name: _f32(np.zeros(n))
             for name in ("ncten", "nwfaten", "nifaten")}
    rain_snow, rain_graupel = _zero_collision_tables()
    launch_aerosol_warm_source_network(
        state["qc"], state["qr"], state["nr"], state["qs"], state["qg"],
        state["ng"], _f32(column["warm_mask"]), _f32(np.zeros(n)),
        state["temperature"], state["pressure"], state["qv"],
        entry["nc"], entry["nwfa"], entry["nifa"],
        accum["ncten"], accum["nwfaten"], accum["nifaten"],
        _t_efrw(), _t_efsw(), rain_snow, rain_graupel, dt)
    return {name: cp.asnumpy(accum[name]) for name in accum}


def test_warm_level_frozen_collectors_add_extra_sinks():
    """Snow and graupel scavenge aerosol and collect droplets at T > 0 C.

    WRF's frozen block is not temperature gated (iiwarm is a PARAMETER
    .false.), so a warm level carrying snow or graupel still loses droplets
    to riming and still loses CCN and IN to wet scavenging.  Dropping these
    because "the level is warm" is a silent physics hole.
    """
    liquid = _run_mixed(_warm_column(n=32))
    mixed = _run_mixed(_mixed_column(n=32))
    for name in ("ncten", "nwfaten", "nifaten"):
        assert np.all(mixed[name] <= liquid[name] + 1e-12), name
        assert np.any(mixed[name] < liquid[name]), name
        assert np.all(np.isfinite(mixed[name])), name


def test_warm_level_sinks_respect_wrfs_per_species_caps():
    """Each rate is MIN'd against the FULL available reservoir, per species.

    module_mp_thompson.F caps pnc_* at nc*odts and pna_*/pnd_* at
    nwfa*odts / nifa*odts individually, and deliberately does NOT apply a
    shared limiter across collectors -- so the SUM may overshoot by at most
    the number of collectors.  Four droplet sinks (autoconversion,
    accretion, snow riming, graupel riming) and three aerosol collectors
    (rain, snow, graupel) are active here.
    """
    import cupy as cp

    from woof.core.thompson_aerosol_warm import probe_warm_rates

    column = _mixed_column(n=32)
    accum = _run_mixed(column)
    dt = 20.0
    # The reservoirs WRF caps against are the per-cubic-metre values it
    # diagnosed at entry, NOT the per-kilogram state: the droplet number is
    # rediagnosed through the D0c / 2*D0r size clamp at :1834-1841 and can be
    # orders of magnitude away from nc1d*rho.  Reading them back from the
    # probe is the only correct way to state this bound.
    rates = probe_warm_rates(
        _f32(column["pressure"]), _f32(column["temperature"]),
        _f32(column["qv"]), _f32(column["qc"]), _f32(column["nc"]),
        _f32(column["qr"]), _f32(column["nr"]), _f32(column["nwfa"]),
        _f32(column["nifa"]), _t_efrw(), dt)
    orho = 1.0 / column["rho"].astype(np.float64)
    nc_m3 = cp.asnumpy(rates["nc_m3"]).astype(np.float64)
    nwfa_m3 = cp.asnumpy(rates["nwfa_m3"]).astype(np.float64)
    nifa_m3 = cp.asnumpy(rates["nifa_m3"]).astype(np.float64)
    assert np.all(-accum["ncten"] <= 4.0 * nc_m3 / dt * orho * (1 + 1e-5))
    assert np.all(
        -accum["nwfaten"] <= 3.0 * nwfa_m3 / dt * orho * (1 + 1e-5))
    assert np.all(
        -accum["nifaten"] <= 3.0 * nifa_m3 / dt * orho * (1 + 1e-5))


