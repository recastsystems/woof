def test_double_application_of_the_balance_is_observable_but_quiet():
    """Why the limiter is a SEPARATE launch, stated as an executable fact.

    On most states the limiter is a fixed point after one application, so a
    second application changes nothing and no unit test would notice a
    double-apply.  MEASURED on the full 11025-row oracle: 1120 rows -- all in
    the ``xDc < D0c`` branch -- are NOT fixed points, because ``nu_c`` is
    reselected from the projected ``xnc`` that the first application just
    rewrote, and a different ``nu_c`` selects a different ``cce(2,nu_c)``
    clamp.  The state below is one of those rows.

    So double-applying is a real physics change on ~10 percent of clamped
    cells and invisible on the rest.  That is precisely the failure mode the
    port spec calls "the single most plausible-looking wrong port", and it is
    why the adapter -- not this kernel and not the warm network -- owns the
    sequencing.
    """
    import cupy as cp

    from woof.core.thompson_aerosol_warm import launch_ncten_balance

    args = (_f32(np.full(2, 2.0e-12)), _f32(np.full(2, 2.0e-12)),
            _f32(np.full(2, 1.708778e7)), _f32(np.full(2, 1.1704271)))
    ncten = _f32(np.full(2, 1.708778e7 * 5.0 / 20.0))
    launch_ncten_balance(*args, ncten, 20.0)
    once = cp.asnumpy(ncten).copy()
    launch_ncten_balance(*args, ncten, 20.0)
    twice = cp.asnumpy(ncten)
    assert not np.array_equal(once, twice)
    # A third application then settles: the damage is done in the second.
    launch_ncten_balance(*args, ncten, 20.0)
    assert np.array_equal(twice, cp.asnumpy(ncten))


