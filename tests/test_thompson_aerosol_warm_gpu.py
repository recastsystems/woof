def test_stokes_number_uses_wrfs_sub_freezing_viscosity_branch():
    """visco(k) is branched at :1991-1996 and the Stokes number reads it.

    thompson.cu's warm network drops the -1.2e-5*tempc**2 term because that
    kernel only ever sees tempc >= 0, where the two forms agree exactly.  But
    WRF's frozen block is NOT temperature gated, and stoke_g is proportional
    to 1/visco, so the unbranched form is 0.86 percent high at tempc = -33 K.
    MEASURED on the aero-cold-overlap entry column with the unbranched form:
    prg_gcw and pnc_gcw 2.529e-02 relative; with WRF's branch prg_gcw is
    BIT-EXACT and pnc_gcw is 1.01e-07.

    Driving the probe below freezing is legitimate and is exactly what the
    scheme does: WP-06's kernel owns those levels in the network, but the
    rate formulas are the same ones and this function is the only
    implementation of them.
    """
    import cupy as cp

    from woof.core.thompson_aerosol_warm import probe_warm_frozen_rates

    n = 8
    tempc = np.linspace(-40.0, 20.0, n).astype(np.float32)
    one = lambda v: _f32(np.full(n, v, np.float32))
    got = probe_warm_frozen_rates(
        one(9.0e4), _f32(np.float32(273.15) + tempc), one(2.0e-3),
        one(1.0e-3), one(1.0e8), one(2.0e-3), one(5.0e-4),
        one(1.0e4), one(3.0e8), one(1.0e6), _t_efrw(), _t_efsw(), 20.0)
    visco = cp.asnumpy(got["visco"]).astype(np.float64)
    want = np.where(
        tempc >= 0.0,
        (np.float32(1.718) + np.float32(0.0049) * tempc) * np.float32(1.0e-5),
        (np.float32(1.718) + np.float32(0.0049) * tempc
         - np.float32(1.2e-5) * tempc * tempc) * np.float32(1.0e-5),
    ).astype(np.float64)
    unbranched = ((np.float32(1.718) + np.float32(0.0049) * tempc)
                  * np.float32(1.0e-5)).astype(np.float64)
    cold = tempc < 0.0
    # The reference above is evaluated WITHOUT contraction; nvrtc defaults to
    # --fmad=true and this expression is copied verbatim from thompson.cu,
    # which leaves it contracted.  MEASURED: agreement is bit-exact on 7 of
    # these 8 states and one float32 ulp on the eighth, and BIT-EXACT on all
    # 14400 rows of the Fortran oracle (every one of which is above freezing,
    # where the quadratic term is absent).  The claim under test is the
    # BRANCH, not the last bit, so the bound is one ulp and the branch is
    # asserted separately below.
    ulp = np.spacing(want.astype(np.float32)).astype(np.float64)
    assert np.all(np.abs(visco - want) <= ulp), (visco, want)
    # The device must be on WRF's sub-freezing branch, not thompson.cu's
    # warm-only form: the quadratic term is strictly negative, so the
    # branched viscosity is strictly smaller below 0 C, by far more than a
    # rounding.
    assert np.all(visco[cold] < unbranched[cold])
    assert np.all(
        (unbranched[cold] - visco[cold]) / visco[cold] > 1.0e-4)
    # And the Stokes number must actually consume it.
    stoke = cp.asnumpy(got["stoke_g"]).astype(np.float64)
    assert np.all(stoke[cold] > 0.0)


