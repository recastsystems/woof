def _named_fixture(name):
    """Parse one aerosol oracle fixture into before/after dicts plus dt."""
    import csv
    from pathlib import Path

    root = (Path(__file__).parents[1] / "woof" / "data" / "thompson"
            / "oracle-aero")
    with (root / f"{name}-column.csv").open(encoding="utf-8") as handle:
        rows = [{key.strip(): value for key, value in row.items()}
                for row in csv.DictReader(handle)]
    with (root / f"{name}-surface.csv").open(encoding="utf-8") as handle:
        surface = {key.strip(): value
                   for key, value in next(csv.DictReader(handle)).items()}

    def phase(tag):
        selected = [row for row in rows if row["phase"].strip() == tag]
        assert selected, tag
        return {field: np.asarray(
            [float(row[field]) for row in selected], dtype=np.float64)
            for field in rows[0] if field != "phase"}

    return phase("before"), phase("after"), float(surface["dt_s"])


def _fixture_probe(before, dt):
    from woof.core.thompson_aerosol_warm import probe_warm_rates

    pressure = before["p_pa"].astype(np.float32)
    temperature = before["temp_k"].astype(np.float32)
    qv = before["qv"].astype(np.float32)
    rho = (0.622 * pressure
           / (287.04 * temperature * (qv + 0.622))).astype(np.float32)
    rates = probe_warm_rates(
        _f32(pressure), _f32(temperature), _f32(qv),
        _f32(before["qc"]), _f32(before["nc_per_kg"]),
        _f32(before["qr"]), _f32(before["nr_per_kg"]),
        _f32(before["nwfa_per_kg"]), _f32(before["nifa_per_kg"]),
        _t_efrw(), dt)
    return rates, rho


