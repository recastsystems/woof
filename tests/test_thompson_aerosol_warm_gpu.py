def _f32(values):
    import cupy as cp
    return cp.asarray(np.asarray(values, dtype=np.float32))


def _t_efrw():
    """WRF's ``t_Efrw(nbr,nbc)`` rain/cloud collection efficiency table.

    Read from the canonical packaged auxiliary record, not regenerated: this
    is the same array ``woof.core.thompson_runtime`` uploads for mp=8.
    """
