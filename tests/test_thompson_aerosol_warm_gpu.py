def test_network_adds_to_a_pre_seeded_accumulator():
    """The three tendencies are ADDED, never assigned.

    WRF writes ``ncten(k) = ncten(k) + (...)``: the cold network runs first
    and its contribution must survive.  A kernel that assigned instead of
    adding would pass every warm-only test and silently delete the cold
    network's droplet sinks.
    """
    import cupy as cp

    from woof.core.thompson_aerosol_warm import (
        launch_aerosol_warm_source_network)

    column = _warm_column()
    n = column["pressure"].size
    seed = np.linspace(-3.0, 3.0, n).astype(np.float32)
    _, _, fresh, _ = _run_network(column)
    baseline = {name: cp.asnumpy(fresh[name]) for name in fresh}

    state = {name: _f32(column[name])
             for name in ("qc", "qr", "nr", "temperature", "qv")}
    state["pressure"] = _f32(column["pressure"])
    entry = {name: _f32(column[name]) for name in ("nc", "nwfa", "nifa")}
    accum = {name: _f32(seed) for name in ("ncten", "nwfaten", "nifaten")}
    rain_snow, rain_graupel = _zero_collision_tables()
    launch_aerosol_warm_source_network(
        state["qc"], state["qr"], state["nr"], _f32(np.zeros(n)),
        _f32(np.zeros(n)), _f32(np.zeros(n)),
        _f32(column["warm_mask"]), _f32(np.zeros(n)),
        state["temperature"], state["pressure"], state["qv"],
        entry["nc"], entry["nwfa"], entry["nifa"],
        accum["ncten"], accum["nwfaten"], accum["nifaten"],
        _t_efrw(), _t_efsw(), rain_snow, rain_graupel, 20.0)
    for name in ("ncten", "nwfaten", "nifaten"):
        assert np.allclose(
            cp.asnumpy(accum[name]), seed + baseline[name],
            rtol=1e-6, atol=1e-12), name


def test_network_leaves_cold_cells_untouched():
    """Sub-freezing cells belong to WP-06's kernel and must not be double-run.

    The entry mask arrives in ``graupel_melt_marker``; the kernel consumes it
    and must zero the two melt markers for a cold cell without writing any
    state or any accumulator.
    """
    column = _warm_column()
    mask = column["warm_mask"].copy()
    mask[::2] = 0.0
    column["warm_mask"] = mask
    state, _, accum, cp = _run_network(column)
    cold = mask == 0.0
    for name, original in (("qc", column["qc"]), ("qr", column["qr"]),
                           ("nr", column["nr"]),
                           ("temperature", column["temperature"])):
        assert np.array_equal(
            cp.asnumpy(state[name])[cold], original[cold]), name
    for name in ("ncten", "nwfaten", "nifaten"):
        assert np.all(cp.asnumpy(accum[name])[cold] == 0.0), name
    assert np.all(cp.asnumpy(state["graupel_marker"])[cold] == 0.0)
    assert np.all(cp.asnumpy(state["snow_marker"])[cold] == 0.0)


def test_network_moves_cloud_water_to_rain():
    """Sanity: the warm network is still the warm network."""
    column = _warm_column()
