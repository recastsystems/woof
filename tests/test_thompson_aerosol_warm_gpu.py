def _zero_collision_tables():
    import cupy as cp

    from woof.core.thompson_aerosol_warm import (
        RAIN_GRAUPEL_TABLE_NAMES, RAIN_GRAUPEL_TABLE_SHAPE,
        RAIN_SNOW_TABLE_NAMES, RAIN_SNOW_TABLE_SHAPE)

    rain_snow = tuple(
        cp.zeros(RAIN_SNOW_TABLE_SHAPE, dtype=cp.float64, order="F")
        for _ in RAIN_SNOW_TABLE_NAMES)
    rain_graupel = tuple(
        cp.zeros(RAIN_GRAUPEL_TABLE_SHAPE, dtype=cp.float64, order="F")
        for _ in RAIN_GRAUPEL_TABLE_NAMES)
    return rain_snow, rain_graupel


