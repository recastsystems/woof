def _host_balance_reference(rc, xrc, nc1d, rho, ncten_in, dt,
                            *, force_nu_c=None):
    """module_mp_thompson.F:3001-3019 in float64 on the host.

    Returns ``(ncten, nu_c, branch)`` where branch is 'clamp-d0c',
    'clamp-2d0r', 'in-range', 'wipe' or 'cap'.  Deliberately independent of
    the device code path: it reads the gamma tables straight from
    :mod:`woof.core.thompson_aerosol_contract`, which builds them from
    WRF's own REAL(4) WGAMMA series.
    """
    from woof.core.thompson_aerosol_contract import (
        AM_R, CCE2, CCG1, CCG2, NT_C_MAX, OCG1, OCG2, cloud_shape_parameter)

    d0c = 1.0e-6
    d0r = 50.0e-6
    bm_r = 3.0
    xrc = max(1.0e-12, xrc * rho)
    xnc = max(2.0, (nc1d + ncten_in * dt) * rho)
    ncten = ncten_in
    branch = "in-range"
    if xrc > 1.0e-12:
        nu_c = (cloud_shape_parameter(xnc) if force_nu_c is None
                else force_nu_c)
        lamc = (xnc * AM_R * CCG2[nu_c] * OCG1[nu_c] / rc) ** (1.0 / 3.0)
        x_dc = (bm_r + nu_c + 1.0) / lamc
        if x_dc < d0c:
            lamc = CCE2[nu_c] / d0c
            branch = "clamp-d0c"
        elif x_dc > d0r * 2.0:
            lamc = CCE2[nu_c] / (d0r * 2.0)
            branch = "clamp-2d0r"
        if branch != "in-range":
            xnc = CCG1[nu_c] * OCG2[nu_c] * xrc / AM_R * lamc ** bm_r
            ncten = (xnc - nc1d * rho) / dt / rho
    else:
        nu_c = 0
        ncten = -nc1d / dt
        branch = "wipe"
    projected = max(0.0, (nc1d + ncten * dt) * rho)
    if projected > NT_C_MAX:
        ncten = (NT_C_MAX - nc1d * rho) / dt / rho
        branch = "cap"
    return ncten, nu_c, branch


def _balance_nu_c_cases():
    """One clamped state per nu_c in 2..15, none of them hitting the cap."""
    from woof.core.thompson_aerosol_contract import (
        AM_R, CCG2, OCG1, cloud_shape_parameter)

    cases = []
    for nu_c in range(2, 16):
        if nu_c == 2:
            # xnc must exceed 2e9 for NINT(1000e6/xnc) to be 0, but nc1d
            # itself must stay under Nt_c_max or the trailing cap -- not the
            # gamma column -- would decide the answer.  Reach it through the
            # INCOMING tendency, which :3001 does not clamp.
            nc1d, ncten_in = 1.0e9, 1.5e8
            xnc = (nc1d + ncten_in * 20.0)
        else:
            nc1d = float(np.float32(1000.0e6 / (nu_c - 2)))
            ncten_in = 0.0
            xnc = nc1d
        assert cloud_shape_parameter(xnc) == nu_c, (nu_c, xnc)
        moment = xnc * AM_R * CCG2[nu_c] * OCG1[nu_c]
        rc_star = (1.0e-6 / (3.0 + nu_c + 1.0)) ** 3 * moment
        cases.append(dict(nu_c=nu_c, nc1d=nc1d, ncten_in=ncten_in,
                          rc=0.5 * rc_star,
                          xrc=(1.7 * rc_star if nu_c != 2
                               else 2.18e-7)))
    return cases


