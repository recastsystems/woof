@pytest.mark.parametrize("name", sorted(
    list(_FROZEN_EXACT) + list(_FROZEN_TOLERANCE)))
def test_frozen_rate_matches_wrf_oracle_above_freezing(name):
    """Every rate of :2402-2471 against the Fortran oracle, above 273.15 K.

    This is the gate the six mp=28-only number and aerosol sinks never had.
    """
    import cupy as cp

    oracle = _frozen_oracle()
    got = _run_frozen_probe(oracle)
    have = cp.asnumpy(got[name]).astype(np.float64)
    want = oracle[name]
    if name in _FROZEN_EXACT:
        bad = int((have != want).sum())
        assert bad == 0, (
            f"{name}: {bad}/{want.size} rows differ from the Fortran oracle; "
            f"worst {_relative(have, want).max():.3e}.  This field measured "
            "BIT-EXACT on all 14400 oracle rows.")
        return
    rel = _relative(have, want)
    worst = int(np.argmax(rel))
    assert rel.max() <= _FROZEN_TOLERANCE[name], (
        f"{name}: max relative {rel.max():.3e} at row {worst} "
        f"(got {have[worst]!r}, want {want[worst]!r}), bound "
        f"{_FROZEN_TOLERANCE[name]:.1e}")


def test_embedded_frozen_oracle_reaches_the_states_it_claims():
    """The subset must exercise every branch, or the gate above is theatre."""
    oracle = _frozen_oracle()
    assert np.all(oracle["temp"] > 273.15), (
        "this oracle exists for ABOVE-freezing states")
    twet = oracle["twet"]
    assert (twet > 273.15).any(), "no row takes the Ef_gw *= 0.1 branch"
    assert (twet < 273.15).any(), "no row leaves Ef_gw unscaled"
    stoke = oracle["stoke_g"]
    assert ((stoke > 0) & (stoke < 0.4)).any(), "Stokes < 0.4 branch missing"
    assert ((stoke >= 0.4) & (stoke <= 10.0)).any(), "log10 branch missing"
    assert (stoke > 10.0).any(), "Stokes > 10 branch missing"
    assert (oracle["xDs"] > 300.0e-6).any(), "no row rimes snow (xDs > D0s)"
    assert (oracle["prs_scw"] > 0).any()
    assert (oracle["prg_gcw"] > 0).any()
    for name in ("pnc_scw", "pnc_gcw", "pna_sca", "pnd_scd",
                 "pna_gca", "pnd_gcd"):
        assert (oracle[name] > 0).any(), f"{name} is zero on every row"
    reseed = (oracle["ng_per_kg"] == 0.0) & (oracle["qg"] > 0.0)
    assert reseed.any(), (
        "no row drives WRF's ng(k) <= R2 re-seed branch at :1924-1928")


