@pytest.mark.parametrize("nu_c", list(range(2, 16)))
def test_the_balance_limiter_reads_the_gamma_column_its_own_nu_c_selects(
        nu_c):
    """Not just "close to the reference" -- the NEIGHBOURING column is wrong.

    ccg(1,n)*ocg2(n)*cce(2,n)**3 changes materially between adjacent n, so a
    kernel that indexed nu_c+1 or nu_c-1 would still look finite, still look
    monotone, and still be wrong.  This asserts the device agrees with its
    OWN column to 1e-6 and disagrees with both neighbours by more than 4
    percent.  MEASURED: the tightest neighbour pair over these fourteen
    cases is nu_c = 15 against 14 at 4.84 percent, so 4 percent is the
    measurement with headroom and not a number chosen to pass.
    """
    import cupy as cp

    from woof.core.thompson_aerosol_warm import launch_ncten_balance

    case = next(c for c in _balance_nu_c_cases() if c["nu_c"] == nu_c)
    dt = 20.0
    ncten = _f32([case["ncten_in"]])
    launch_ncten_balance(
        _f32([case["rc"]]), _f32([case["xrc"]]), _f32([case["nc1d"]]),
        _f32([1.0]), ncten, dt)
    got = float(cp.asnumpy(ncten)[0])

    want, _, _ = _host_balance_reference(
        case["rc"], case["xrc"], case["nc1d"], 1.0, case["ncten_in"], dt)
    assert abs(got - want) / abs(want) <= 1.0e-6

    for neighbour in (nu_c - 1, nu_c + 1):
        if not 1 <= neighbour <= 15:
            continue
        wrong, _, _ = _host_balance_reference(
            case["rc"], case["xrc"], case["nc1d"], 1.0, case["ncten_in"],
            dt, force_nu_c=neighbour)
        assert abs(wrong - want) / abs(want) > 0.04, (
            f"nu_c={nu_c} vs {neighbour}: the two columns differ by only "
            f"{abs(wrong - want) / abs(want):.3%}, so this case cannot "
            "discriminate them")
        assert abs(got - wrong) / abs(want) > 0.04


