@pytest.mark.parametrize("name", sorted(_NAMED_FIXTURES))
def test_named_fixture_after_nifa_matches_this_packages_pnd_rcd(name):
    """FULL-COLUMN WRF gate on pnd_rcd, bit-exact.

    ``nifaten`` has exactly one live source on these columns
    (module_mp_thompson.F:2966-2967), and WRF applies it once at :3981-3982
    as MAX(naIN1*0.01, MIN(9999.E6, nifa1d + nifaten*DT)) -- note that the
    clamp bounds are per-cubic-metre constants applied to a PER-KILOGRAM
    value, which is WRF's own code and is transcribed rather than tidied.

    Bit-exact is not an aspiration here: it is what was measured on all four
    fixtures, at both dt = 10 s and dt = 50 s.
    """
    import cupy as cp

    before, after, dt = _named_fixture(name)
    rates, rho = _fixture_probe(before, dt)
    orho = (np.float32(1.0) / rho).astype(np.float64)
    nifaten = (-cp.asnumpy(rates["pnd_rcd"]) * orho).astype(np.float32)
    entry = before["nifa_per_kg"].astype(np.float32)
    predicted = np.maximum(
        np.float32(5.0e3),
        np.minimum(np.float32(9999.0e6),
                   entry + nifaten * np.float32(dt)))
    want = after["nifa_per_kg"].astype(np.float32)
    bad = np.flatnonzero(predicted != want)
    assert bad.size == 0, (
        f"{name}: {bad.size}/{want.size} levels differ; first at k="
        f"{bad[0]}: predicted {predicted[bad[0]]!r} want {want[bad[0]]!r} "
        f"(entry {entry[bad[0]]!r}, nifaten {nifaten[bad[0]]!r})")
    # The gate must have something to say: at least one level must actually
    # have been scavenged, or this is a test that 0 == 0.
    if name != "aero-nc-auto":
        assert np.count_nonzero(cp.asnumpy(rates["pnd_rcd"])) >= 9, name


