def test_nu_c_reduces_to_the_mp8_constant_at_nt_c():
    """nc = Nt_c = 100e6 must still give nu_c = 12.

    thompson.cu:3241 hardcodes exactly that value.  If the generalized
    formula did not reproduce it, mp=8 would have been wrong too.
    """
