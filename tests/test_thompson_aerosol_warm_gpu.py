def _warm_column(n=48, warm_mask=None):
    """A liquid-only ambient-warm column with a live nc/nwfa/nifa ladder."""
    rng = np.random.default_rng(20260731)
    pressure = np.linspace(100000.0, 55000.0, n).astype(np.float32)
    temperature = np.full(n, 285.0, dtype=np.float32)
    qv = np.full(n, 0.006, dtype=np.float32)
    rho = (0.622 * pressure
           / (287.04 * temperature * (qv + 0.622))).astype(np.float32)
    qc = np.full(n, 1.0e-3, dtype=np.float32)
    qc[::7] = 0.0
    qr = np.full(n, 3.0e-4, dtype=np.float32)
    qr[1::5] = 0.0
    nr = np.where(
        qr > 0.0,
        qr * (3.672 / 5.0e-4) ** 3 / (np.pi * 1000.0), 0.0).astype(np.float32)
    ladder = np.array([2.0, 50.0, 7.7e7, 1.0e8, 1.25e8, 2.0e8, 5.0e8,
                       1.0e9, 1.999e9], dtype=np.float32)
    nc = (ladder[np.arange(n) % ladder.size] / rho).astype(np.float32)
    nwfa = (rng.uniform(1.0e7, 5.0e9, n) / rho).astype(np.float32)
    nifa = (rng.uniform(5.0e3, 5.0e9, n) / rho).astype(np.float32)
    if warm_mask is None:
        warm_mask = np.ones(n, dtype=np.float32)
    return dict(pressure=pressure, temperature=temperature, qv=qv, rho=rho,
                qc=qc, qr=qr, nr=nr, nc=nc, nwfa=nwfa, nifa=nifa,
                warm_mask=warm_mask.astype(np.float32))


def _run_network(column, dt=20.0):
    import cupy as cp

    from woof.core.thompson_aerosol_warm import (
        launch_aerosol_warm_source_network)

    n = column["pressure"].size
    state = {name: _f32(column[name])
             for name in ("qc", "qr", "nr", "temperature", "qv")}
    state["pressure"] = _f32(column["pressure"])
    state["qs"] = _f32(np.zeros(n))
    state["qg"] = _f32(np.zeros(n))
    state["ng"] = _f32(np.zeros(n))
    state["graupel_marker"] = _f32(column["warm_mask"])
    state["snow_marker"] = _f32(np.zeros(n))
    entry = {name: _f32(column[name]) for name in ("nc", "nwfa", "nifa")}
    accum = {name: _f32(np.zeros(n))
             for name in ("ncten", "nwfaten", "nifaten")}
    rain_snow, rain_graupel = _zero_collision_tables()
    launch_aerosol_warm_source_network(
        state["qc"], state["qr"], state["nr"], state["qs"], state["qg"],
        state["ng"], state["graupel_marker"], state["snow_marker"],
        state["temperature"], state["pressure"], state["qv"],
        entry["nc"], entry["nwfa"], entry["nifa"],
        accum["ncten"], accum["nwfaten"], accum["nifaten"],
        _t_efrw(), _t_efsw(), rain_snow, rain_graupel, dt)
    return state, entry, accum, cp


def test_network_never_writes_the_frozen_entry_state():
    """state nc/nwfa/nifa are READ-ONLY for the whole mp=28 call.

    This is the invariant the whole three-accumulator design exists to keep.
    If a network wrote entry state directly, every later kernel that
    recomputed a working value would see a different starting point than WRF
    does, and the error would be invisible in any single-kernel test.
    """
    column = _warm_column()
    _, entry, _, cp = _run_network(column)
    for name in ("nc", "nwfa", "nifa"):
        assert np.array_equal(
            cp.asnumpy(entry[name]), column[name]), name


def test_network_accumulates_exactly_the_probe_rates():
    """ncten/nwfaten/nifaten must be the WRF sums of the probed rates.

    module_mp_thompson.F:2963-2994.  On a liquid-only warm column the cold
    terms (pni_wfz, pnc_scw, pnc_gcw, pni_iha, pni_inu) are identically zero
    and the aerosol sinks reduce to the rain collector, so the accumulators
    are a closed function of rates this test can read back independently.
    """
    from woof.core.thompson_aerosol_warm import probe_warm_rates

    column = _warm_column()
    _, _, accum, cp = _run_network(column)
    rates = probe_warm_rates(
        _f32(column["pressure"]), _f32(column["temperature"]),
        _f32(column["qv"]), _f32(column["qc"]), _f32(column["nc"]),
        _f32(column["qr"]), _f32(column["nr"]), _f32(column["nwfa"]),
        _f32(column["nifa"]), _t_efrw(), 20.0)
    orho = (np.float32(1.0) / column["rho"]).astype(np.float32)
    pnc_wau = cp.asnumpy(rates["pnc_wau"])
    pnc_rcw = cp.asnumpy(rates["pnc_rcw"])
    pna_rca = cp.asnumpy(rates["pna_rca"])
    pnd_rcd = cp.asnumpy(rates["pnd_rcd"])
    expect_nc = ((-pnc_wau - pnc_rcw) * orho.astype(np.float64)
                 ).astype(np.float32)
    expect_nwfa = (-(pna_rca * orho.astype(np.float64))).astype(np.float32)
    expect_nifa = (-(pnd_rcd * orho.astype(np.float64))).astype(np.float32)
    assert np.array_equal(cp.asnumpy(accum["ncten"]), expect_nc)
    assert np.array_equal(cp.asnumpy(accum["nwfaten"]), expect_nwfa)
    assert np.array_equal(cp.asnumpy(accum["nifaten"]), expect_nifa)


def test_network_accumulator_sinks_are_signed_correctly():
    """Droplet and aerosol tendencies are SINKS wherever the rate is live."""
