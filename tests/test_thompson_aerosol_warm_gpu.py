# TASK 2: the 273.15 K seam between the cold and the warm network.
# ---------------------------------------------------------------------------
#
# WHY THIS LIVES HERE AND WHY IT DRIVES SOMEONE ELSE'S KERNEL
# -----------------------------------------------------------
# WRF runs ONE column loop.  woof splits it into a sub-freezing kernel
# (thompson_aerosol_cold.cu) and an ambient-warm kernel
# (thompson_aerosol_warm.cu).  Each owner can prove their own half in
# isolation; NEITHER can prove the seam, because the seam is a property of
# the pair.  Two failure modes live here and both are silent:
#
#   GAP        a level that neither kernel services.  WRF's warm-section
#              number sinks pnc_wau (:2192-2193), pnc_rcw (:2205-2207),
#              pna_rca (:2213-2216) and pnd_rcd (:2218-2221) sit at
#              :2160-2230, i.e. INSIDE the k-loop opened at :2156 and BEFORE
#              both the `.not. iiwarm` branch at :2239 and the
#              `temp(k) .lt. T_0` guard at :2554.  WRF therefore evaluates
#              all four at EVERY level, sub-freezing ones included.  This
#              file's kernel returns for a level whose entry mask is unset,
#              so if the cold kernel does not carry them, cloud mass leaves
#              without its droplet number and rain wet-scavenging of CCN and
#              IN is absent from the entire cold half of the domain.
#
#   DOUBLE     a level both kernels service.  The three accumulators are
#              read-modify-write by design (WRF's `ncten(k) = ncten(k) + ...`
#              at :2963-2994), so a second evaluation ADDS rather than
#              overwrites, stays finite, and is simply twice the truth.
#
# THE CONTRACT BEING PROVEN
# -------------------------
#   warm serviced  <=>  entry mask set, and the adapter sets the mask with
#                       `temperature >= 273.15` on the ENTRY temperature
#                       (woof/core/microphysics.py:504 is the mp=8
#                       precedent this port copies).
#   cold serviced  <=>  temperature < 273.15 at the moment the cold kernel
#                       runs, which is the entry temperature because the
#                       adapter captures the mask first and launches cold
#                       before warm.
# Those two predicates are exact complements, so exactly one fires per level
# -- INCLUDING at exactly 273.15 K, which belongs to the warm side.
#
# HOW THE FIXTURE ISOLATES THE FOUR SHARED TERMS
# ----------------------------------------------
# qs = qg = qi = 0 kills pnc_scw, pnc_gcw, pna_sca, pnd_scd, pna_gca and
# pnd_gcd in both kernels.  The cloud-freezing and rain-freezing coefficient
# records are supplied as ZEROS, which zeroes pni_wfz.  The column is
# ice-SUBSATURATED, so cold.cu's `ssati >= 0.25` deposition-nucleation gate
# never opens and pni_inu is zero; every level is far above 238 K so Koop's
# pni_iha is zero too.  t_Efrw is the REAL packaged table, because pnc_rcw
# reads it.  What survives in the three accumulators is then EXACTLY
#     ncten    = (-pnc_wau - pnc_rcw) * orho
#     nwfaten  = -pna_rca * orho
#     nifaten  = -pnd_rcd * orho
# at every level of the sweep, and this file's own probe -- which has no
# temperature gate at all, exactly like WRF's :2160-2230 -- supplies the
# reference the pair must reproduce once and only once.

_FREEZE_K = np.float32(273.15)


def _seam_temperatures():
    """A sweep straddling 273.15 K, with the seam itself sampled exactly.

    Includes float32(273.15) itself and its two float32 neighbours, because
    ``>=`` versus ``>`` at the boundary is precisely the kind of one-bit
    disagreement that would leave one level unserviced or served twice.
    """
    sweep = np.linspace(268.15, 278.15, 41, dtype=np.float64)
    edges = np.asarray([
        273.15,
        float(np.nextafter(_FREEZE_K, np.float32(0.0))),
        float(np.nextafter(_FREEZE_K, np.float32(400.0))),
        273.1499, 273.1501, 272.9999, 273.3001,
    ], dtype=np.float64)
    values = np.unique(
        np.concatenate([sweep, edges]).astype(np.float32))
    assert np.count_nonzero(values == _FREEZE_K) == 1, (
        "the sweep must sample exactly 273.15 K")
    assert (values < _FREEZE_K).any() and (values > _FREEZE_K).any()
    return values


def _seam_column():
    """One column whose only variation across levels is temperature and nc."""
    temperature = _seam_temperatures()
    n = temperature.size
    pressure = np.full(n, 85000.0, dtype=np.float32)
    # 1.5 g/kg is far below the ice saturation mixing ratio anywhere in
    # 268-278 K at 850 hPa, so cold.cu's nucleation gate stays shut.
    qv = np.full(n, 1.5e-3, dtype=np.float32)
    rho = (0.622 * pressure
           / (287.04 * temperature * (qv + 0.622))).astype(np.float32)
    qc = np.full(n, 1.0e-3, dtype=np.float32)
    qr = np.full(n, 3.0e-4, dtype=np.float32)
    # mvd_r = 500 um, comfortably above D0r so the accretion and scavenging
    # branches are open at every level.
    nr = (qr * (3.672 / 5.0e-4) ** 3 / (np.pi * 1000.0)).astype(np.float32)
    ladder = np.array([2.0, 50.0, 7.7e7, 1.0e8, 1.25e8, 2.0e8, 5.0e8,
                       1.0e9, 1.999e9], dtype=np.float32)
    nc = (ladder[np.arange(n) % ladder.size] / rho).astype(np.float32)
    nwfa = np.full(n, 3.0e9, dtype=np.float32) / rho
    nifa = np.full(n, 1.0e7, dtype=np.float32) / rho
    return dict(temperature=temperature, pressure=pressure, qv=qv, rho=rho,
                qc=qc, qr=qr, nr=nr, nc=nc.astype(np.float32),
                nwfa=nwfa.astype(np.float32), nifa=nifa.astype(np.float32),
                warm_mask=(temperature >= _FREEZE_K).astype(np.float32))


