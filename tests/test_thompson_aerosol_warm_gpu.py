def _code_only(source: str) -> str:
    """Blank every ``//`` line comment, preserving line numbering.

    The structural gates below scan for CODE patterns.  A comment that
    QUOTES one of those patterns -- and the header block of
    thompson_aerosol_warm.cu deliberately quotes several, because a
    structural rule nobody can read is a rule nobody keeps -- must not be
    mistaken for the pattern itself.
    """
    out = []
    for line in source.split("\n"):
        index = line.find("//")
        out.append(line if index < 0 else line[:index] + " " * (len(line) - index))
    return "\n".join(out)


def test_only_the_limiter_may_overwrite_ncten():
    """Every other aerosol kernel must ACCUMULATE into ncten, never assign.

    module_mp_thompson.F:2963-2994 writes ``ncten(k) = ncten(k) + (...)``;
    only the balance limiter at :3007/:3011/:3014/:3018 ASSIGNS, because it
    backs the tendency out against ``nc1d*rho`` rather than adding to it.
    An assignment anywhere else silently deletes whichever network ran
    first, which on a mixed column is the entire cold half of the scheme.

    This is a stronger statement than "the limiter kernel is defined once":
    it is what makes the limiter's uniqueness observable in the data flow
    rather than only in the symbol table.
    """
    import re
    from pathlib import Path

    kernels = Path(__file__).parents[1] / "woof" / "core" / "kernels"
    overwrites = []
    for path in sorted(kernels.glob("thompson_aerosol_*.cu")):
        source = _code_only(path.read_text(encoding="utf-8"))
        for match in re.finditer(r"ncten\[idx\]\s*=(?!=)(.*?);", source,
                                 re.DOTALL):
            if "ncten[idx]" in match.group(1):
                continue                      # read-modify-write, allowed
            line = source[:match.start()].count("\n") + 1
            overwrites.append((path.name, source.splitlines()[line - 1].strip()))
    assert overwrites == [
        ("thompson_aerosol_warm.cu", "ncten[idx] = tendency;")], overwrites


