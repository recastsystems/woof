def test_network_does_not_apply_the_balance():
    """The limiter must NOT be fused into the network.

    Evidence that it is not: after the network launch, the standalone limiter
    still MOVES the accumulator.  If the network had already applied it, the
    accumulator would already satisfy the limiter's own fixed point on the
    cells whose droplet size is out of bounds.
    """
    import cupy as cp

    from woof.core.thompson_aerosol_warm import launch_ncten_balance

    column = _warm_column()
    state, entry, accum, _ = _run_network(column)
    before = cp.asnumpy(accum["ncten"]).copy()
    launch_ncten_balance(
        _f32(column["qc"]), state["qc"], entry["nc"], _f32(column["rho"]),
        accum["ncten"], 20.0)
