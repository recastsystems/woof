def _table(text: str) -> dict[str, np.ndarray]:
    """Parse an embedded oracle block into float64 columns."""
    stream = io.StringIO(text)
    names = stream.readline().strip().split(",")
    columns: dict[str, list[float]] = {name: [] for name in names}
    for line in stream:
        line = line.strip()
        if not line:
            continue
        values = line.split(",")
        assert len(values) == len(names), line
        for name, value in zip(names, values, strict=True):
            columns[name].append(float(value))
    return {name: np.asarray(values, dtype=np.float64)
            for name, values in columns.items()}


